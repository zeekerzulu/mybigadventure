<p>
I really enjoyed my visit to the West Thumb Geyser Basin.  I liked that it bordered Yellowstone Lake, which provided additional viewing opportunities when looking east of the basin.  My favorite feature was Abyss Pool.  True to its name, it just seemed to go on forever and ever.
<p>
I rate my tour of the West Thumb Geyser Basin Trail a solid 9.5 out of a 10.
