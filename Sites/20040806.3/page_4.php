<p>
"One of the deeper hot springs in the park, Abyss Pool descends to 53 feet.  It varies from turquoise blue to emerald green to various shades of brown.  Abyss Pool erupted for the first time in recent history in August 1987.  It remained quiet again until September 1991, when it erupted frequently in spectacular, but short, 100 foot bursts.  The next active period lasted December 1991 through June 1992, when it erupted several times per day.  Each eruption was a series of explosive bursts, sending water 30-80 feet high and a plume of steam above the treetops.  The pool's entire body of water appeared to turn end-over-end in a turbulent boil.  Since that time, Abyss has been a quiet, distinctive feature at West Thumb."
