My next stop on the trail is Boston's oldest public building, the <ax href="javascript:myPopup4('http://www.nps.gov/bost/bost_lographics/oldstate.htm')">Old State House</a>.  Built in 1713 and used by Massachusetts colony, county, and town governments, it was a beehive of activity during colonial times.  Having the foresight to encourage the public's understanding of the government's inner-workings, a visitor's gallery was added in 1766 to accommodate a public audience while the legislature was in session.
<p>
The last three shots do well in showing how the old and new architecture share common space but not common time.  I really appreciate all the contrasts in architecture here in Boston.  There's always room for history and antiquity here in good ole Beantown.  The last two photos are from later this evening.
