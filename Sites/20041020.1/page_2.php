<p>
Soon enough I'm at the <ax href="javascript:myPopup5('http://www.nga.gov/feature/shaw/home.htm')">Shaw Memorial</a>.  It is here where you'll find the starting point of the <ax href="javascript:myPopup1('http://www.nps.gov/boaf/')">Black Heritage Trail</a>.  This memorial is dedicated to <ax href="javascript:myPopup6('http://www.medalofhonor.com/RobertGouldShaw.htm')">Colonel Robert Gould Shaw and the African-American Massachusetts 54th Regiment</a>.  On May 28, 1863, Colonel Shaw and 1,000 black soldiers, the fifth African American troop to be organized during the Civil War, marched past Boston onlookers and into the war.
<p>
The memorial was created to commemorate not only that snapshot in time, but also the regiment's bravery in battle.  Ultimately, two months later, the regiment sustained staggering losses of life, including Colonel Shaw, at Fort Wagner in Charleston, SC.  According to President Lincoln, their battle marked the turning point in the war between the states.
<p>
In 1989 TriStar released the movie <ax href="javascript:myPopup7('http://www.mooviees.com/895-glory/movie')">Glory</a> which traces the life and times of Colonel Shaw and the 54th Regiment, from initial training to the horrors they meet on the battlefield.  I've seen this movie and it's a must see.  To support this claim, the movie was nominated for 5 Academy Awards and walked away with 3 in the categories of Best Sound, Best Cinematography, and Best Actor in a Supporting Role.
