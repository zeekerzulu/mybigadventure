<ax href="javascript:myPopup7('http://www.oldnorth.com/hist.htm')">The Old North Church</a> proves to be a church of antiquity.  Boasting religious artifacts of tradition and history, upon entry I immediately  experience strong feelings of respect, remembrance, and honor.  Boston's oldest standing church, Old North Church was constructed in 1723 to provide relief to King's Chapel, which, at the time, was bursting at the seams with an ever-growing congregation.
<p>
The church's interior is spacious and ornate.  In the rear of the church you'll find a 1,500 pipe double manual organ and a clock built in 1726 that is thought to be the oldest working clock of its kind.
<p>
