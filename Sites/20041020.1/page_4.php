Next to Park Street Church I find <ax href="javascript:myPopup10('http://www.cityofboston.gov/parks/HBGI/hbginfo.asp?ID=16')">Granary Burying Ground</a>, resting place for the famous and not so famous, approximately 8,000 individuals are interred here.  Founded in 1660, it's the third oldest cemetery in Boston, and surprisingly, it has experienced a litany of name changes; New Burying Ground, South Burying Ground, Middle Burying Ground, Central Burying Ground.  Come on people, get a compass, will ya!
