Not one, not two, but three, yes, three signers of the <ax href="javascript:myPopup1('http://www.ushistory.org/declaration/document/index.htm')">Declaration of Independence</a> are buried here.  They are <ax href="javascript:myPopup2('http://www.ushistory.org/declaration/signers/hancock.htm')">John Hancock</a>, <ax href="javascript:myPopup3('http://www.ushistory.org/declaration/signers/adams_s.htm')">Samuel Adams</a>, and <ax href="javascript:myPopup4('http://www.ushistory.org/declaration/signers/paine.htm')">Robert Treat Paine</a>.  Scoring the plot of John Hancock is a pretty big deal.  Think about it, when asked who signed the Declaration of Independence, who do you think of first? Exactly, you see my point.  Signature hogs always get all the attention.
<p>
Believe it or not, the throwing of snowballs may have been the starting catalyst to the Colonial Revolution.  On February 22, 1770, a pissed-off crowd gathered and threw snowballs at a Tory sympathizer's home, resulting in the homeowner shooting one of the throwers, a 12-year old boy. From this event, tensions rose sharply between the Colonists and the British, and on March, 5, 1770, British Troops shoot and kill 5 demonstrators, the killing is dubbed the <ax href="javascript:myPopup5('http://www.americaslibrary.gov/cgi-bin/page.cgi/jb/revolut/boston_1')">Boston Massacre</a>.  Massacre?  Would you classify the murder of 5 people a <ax href="javascript:myPopup6('http://dictionary.reference.com/search?q=massacre')">massacre</a>?  I think the Colonists hyped up the event just a bit to push their agenda of independence from England.  In any event, the 12-year old and the 5 victims are buried together here in the cemetery.  Additionally, the parents of Benjamin Franklin, as well as Paul Revere call Granary Burying Ground their final resting place.
