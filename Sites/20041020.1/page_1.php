Standing at the start of the trail, I see in the distance a guy in a cape, is that Batman?  Upon closer inspection, my hunch proves false, rather, he's one of the National Park Service's tour guides.  All dressed up in colonial garb, I stick around long enough to listen for a few minutes.  He's filled full of interesting facts and information, too bad all I have time for today is a self-guided tour.
