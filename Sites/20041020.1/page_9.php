My next stop, <ax href="javascript:myPopup10('http://www.kings-chapel.org/history.htm')">King's Chapel</a>.  Completed in 1754, the church was designed to compete with the best, most opulent churches that England had to offer.  Possessing one of the most elegant interiors of the colonial era, it does well in the competition of architectural one-upmanship.  The last two pictures are from later this evening.
<p>
Next to the chapel you'll find the burial ground where <ax href="javascript:myPopup9('http://www.kirjasto.sci.fi/hawthorn.htm')">Nathaniel Hawthorne</a> found his inspiration to write <ax href="javascript:myPopup10('http://www.gradesaver.com/ClassicNotes/Titles/thescarletletter/fullsumm.html')">The Scarlet Letter</a>.  Legend says his inspiration came in the form of the <ax href="javascript:myPopup1('http://www.hawthorneinsalem.org/images/image.php?name=MMD1578')">gravestone of Elizabeth Pain</a>, who he used as the prototype for Hester Prynne, the main female character in his celebrated American Classic.
