Time to move on to the last sight of my tour, the USS Constitution.  I have a bit of a walk ahead of me, it's located a ways away in the Charlestown Navy Yard.
<p>
Unfortunately, I don't have time to see the <ax href="javascript:myPopup9('http://www.nps.gov/bost/Bunker_Hill.htm')">Bunker Hill Monument</a>, time is running short.  Certainly worthy of mention, Bunker Hill was the scene of one of the bloodiest battles in the War of Independence, the Battle of Bunker Hill.  It is here the legendary order was made, "Don't fire until you see the whites of their eyes!"  The British won the battle, however, the large losses they incurred provided sufficient catalyst to inspire the patriots to continue on with the war, which eventually resulted in the hard-earned independence from England in 1783.
