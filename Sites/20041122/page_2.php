Here's a good one.  Prohibition hit Colorado in 1916, four years early, and Coors survived thirteen dry years making malted milk and porcelain.  Porcelain!  Somewhere out there is a toilet with the Coors name on it, and I want to see it.  Today it's 4,000-plus employees here in Golden, plus plants in Tennessee, Virginia and the UK.
