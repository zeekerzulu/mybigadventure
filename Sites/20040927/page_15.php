I hop into the van and start my way down the mountainside.  The highway down proves to be very steep.  So much so, to conserve my brakes I shift into 2nd gear and used my engine as a brake during my 5 mile descent.
<p>
The ride down concludes my tour of Whiteface Mountain.  I really enjoyed all aspects to my tour which included Whiteface Castle, the stair climb to the mountaintop, the shelter house with all its memorabilia, the cursing construction crew, the glorious views, the elevator ride, and subsequent tunnel traverse.  I give my tour of Whiteface Mountain a solid 5 thumbs-up out of a possible 5 thumbs.
