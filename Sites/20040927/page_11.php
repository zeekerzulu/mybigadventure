There are 3-D plastic maps on the wall illustrating the topography of the mountain's surrounding area.  Boy, what a blast-from-the-past this is for me.  I remember playing with this kind of map as a kid and I'm sure there are a lot of you out there who can relate to what I'm about to share.  I remember pretending to be riding in an airplane by skimming my eyeball close to the surface of the map.  Have you ever done this?  Being a big kid myself, I can't resist the urge to replay that fun-filled childhood memory once again.  <b>VIDEO:</b> Here's a <a href="Pics/Daily/20040927/DSCN0639.mp4">movie</a> replicating my experience.
