Time for a little run-down on the various NASA space missions.  From 1961 to 1972, there were three phases to America's space program, namely, Mercury (1961-1965), Gemini (1965-1966), and Apollo (1967-1972).
<p>
<a href="index.php?action=Pics&name=Daily/20041114/DSCN0599.jpg"><img src="Pics/Daily/20041114/Small/DSCN0599.jpg"></a>
<p>
The first phase, <a href="javascript:myPopup1('http://en.wikipedia.org/wiki/Project_Mercury')">Project Mercury</a>, was initiated in response to a mounting space-race between the United States and the Soviet Union.  The overall goal of the project was to build a manned spacecraft that could preserve human life during orbit around the Earth in the dangerous environment of space.
