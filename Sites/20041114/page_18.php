Here's a <a href="javascript:myPopup6('http://en.wikipedia.org/wiki/Space_shuttle_main_engines')">Space Shuttle Main Engine</a>.  The only large-scale reusable rocket engine in the world, the Space Shuttle sports three of these babies.  Each are rated to run continuously for 7.5 hours but only get exercised 8.5 minutes on each Shuttle flight.  Such an engine can be used on about 30 Shuttle missions before being retired.  Hmmm, I wonder if this is a retired one?  Probably not.  It's probably just a plastic model.
