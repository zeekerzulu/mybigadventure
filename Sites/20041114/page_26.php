Okay, my tour of Space Center Houston is finally over.  I've completely run out of things to see.  On my way out of the Visitor Center I grab a space gumball and score an orange one.  Sweet!
<p>
My visit to Space Center Houston was both interesting and inspiring.  During more than 5 hours of touring, I managed to see Mission Control, experimental spacecraft in the works, towering rockets, moon rocks, spacesuits, a mockup of the Space Shuttle, a Lunar Lander, and many, many more interesting exhibits and displays.
<p>
I give my vist to Space Center Houston 4.5 thumbs-up, a near perfect rating!
