Here is a bird's eye view of the Indiana Dune National Lakeshore.  The park stretches 20 miles along the southern shore of Lake Michigan.  "The dunelands of southern Lake Michigan are renowned for stretches of uncrowded beaches, bird-filled marshes, oak and maple forests, and towering dunes.  Shoreline sand dunes are created when wind blowing off Lake Michigan lifts grains of sand and transports them inland until plants and hills slow the wind and it drops it's cargo.  On windy days you can place an obstacle on the beach and watch a miniature dune form behind it."
