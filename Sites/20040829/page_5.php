And last but not least, there is the retail aspect of the mall.  It is HUGE!  I've only scratched the surface with these few pictures.  The stores just go on and on and on.  They even have highly specialized stores like this Halloween store.
<p>
I have to admit I'm not a big shopper.  Actually I really hate to shop.  But if I have a choice to shop for, let's say, everyone on my Christmas list, I'd choose to shop at Mall of America because everything is under one roof.  This place is truly a convenient one-stop-shop once you get a feel for where everything is.  And you'll also get a lot of exercise with all the walking around you'll be doing.
<p>
I give my tour of the Mall of America 4 thumbs-up out of a possible 5 thumbs.
