Once built, The Mayflower II set sail from Plymouth, England to Plymouth, MA in 1957.  These placards talk about the transatlantic trip as well as subsequent trips since arriving in America.
<p>
<a href="index.php?action=Pics&name=Daily/20041023/DSCN0202.jpg"><img src="Pics/Daily/20041023/Small/DSCN0202.jpg"></a>
<p>
This looks like the end of the line, my ship tour is over.  I really enjoyed learning about The Mayflower and its descendant, The Mayflower II.  Being able to walk the decks and peer into the holds of a replica ship is almost as good as being on the original.  Hats off to the operator, Pilmoth Plantation, for maintaining a tiptop and tight ship.  I rate my tour of The Mayflower II an overwhelming 5 thumbs-up, a perfect rating!
