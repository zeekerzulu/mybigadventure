<p>
Yellowstone's Canyon Area, located just north of the parks center point, hugs the Yellowstone River as it flows northeastward out of the park.  The western part of the canyon is where you'll find two great falls and trails lining (and sometimes diving into) the canyon's northern and southern rims. I decided to tour the southern rim because that's were Artist Point is located, supposedly the most photographed sight in the park.
<p>
<a href="index.php?action=Pics&name=Daily/20040807.2/P1010002.JPG"><img src="Pics/Daily/20040807.2/Small/P1010002.JPG"></a>
<a href="index.php?action=Pics&name=Daily/20040807.2/P1010003.JPG"><img src="Pics/Daily/20040807.2/Small/P1010003.JPG"></a>
<p>
The western portion of the canyon is comprised of two waterfalls, a 109 foot Upper Falls and a 308 foot Lower Falls.  The Upper Falls is easily accessible, requiring only a short walk from the parking lot.
