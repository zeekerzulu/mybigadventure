I thought the Upper Falls was interesting, it widens as it spills over its ledge.  On the northern rim you can hike down to the top of the falls for a closer view.  This falls, while beautiful, was only a hint of what was in store for me as I prepared to hike eastward on the South Rim Trail, a 1 mile trail that ties the Upper Falls to Artist Point.
