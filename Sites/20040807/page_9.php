As I continued upward along the South Rim Trail, I noticed certain rim sections exhibited extensive erosion.  Many trees were on the brink of spilling over the canyon wall.
<p>
At this point the sun was cloud-covered but dangerously low in the sky.  I found myself feeling concerned that once I got to Artist Point, the sun would break free from the clouds and interfere with my picture taking.  The shining sun would be just to the right of the canyon and my camera would underexpose my shots because of too much light.
