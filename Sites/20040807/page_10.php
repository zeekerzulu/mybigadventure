I mounted the platform then looked west at the view.  It was just spectacular!  I can see why this may be the most photographed sight in the park.  I was fortunate, the sun had stayed behind the clouds, so my pictures would hopefully turn out.  I wondered how the view changed at different times of the day.  If I ever make it back to Yellowstone I'll have to make a point to come back in the morning or early afternoon.
<p>
"When you reach this set of overlooks, you'll see why this is one of the most photographed views in Yellowstone.  Framed by the canyon walls with forest for a backdrop, the Yellowstone River thunders more that 308 feet over Lower Falls.  From the upper overlook, you can view the canyon in both directions.  Look for osprey, bald eagles, ravens, and swallows.  The lower overlook is accessible to wheelchairs."
