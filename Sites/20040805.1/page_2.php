The next formation I encountered was Palette Spring.  "Water flows in crisscrossing patterns down a steep ridge where 

colorful thermopiles create a changing palette dominated by hues of orange and brown.  This effect is much the same as an 

artist would achieve by allowing watercolors to run down a vertical surface."
<p>
<a href="index.php?action=Pics&name=Daily/20040805/P1010025.JPG"><img src="Pics/Daily/20040805/Small/P1010025.JPG"></a>
<p>
There was a sign saying it was okay to run and jump on the formation... well actually it said to "Stay Off" but you couldn't 

tell that from the picture.  Yellowstone kinda dropped the ball on this one.  Many of the signs I encountered throughout the 

Park's exhibits had light blue lettering, to simulate the color of many of their natural springs I suppose.  In any 

event, it looks nice in person but certainly not in photos.  I suspect many folks get their pictures back from the developer 

only to scratch their heads, wondering what the heck they took a picture of...  It's a shame.
