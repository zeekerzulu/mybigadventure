"Activity shifts dramatically around this terrace.  The cascades of travertine beside the boardwalks were formed in the 

1990s.  Some years, they are dry.  Whatever its level of activity, you can see why Minerva Terrace was named for the Roman 

goddess of artists and sculptors.  Its ornate travertine formations create the look of layered cakes and lace-edged pools.  

In many dry areas, you can clearly see the many layers and the varying depths.  Where water flows, notice the thermopiles 

coloring the terrace."
<p>
Well to me the entire formation looked bone-dry, so it must have been dormant?
<p>
Adjacent to Minerva Terrace, I soon came upon the Jupiter and Mound Terraces.
