<p>
I really loved the color of the spring.  Plus it was nice of the Park Service to put up that sign. The sign said "No life guard on 

duty, but heck, jump in, the water's great!".
<p>
"If you'd like to view flowing hot water and travertine formations, plus enjoy a stop in the shade, walk down this trail.  It 

ends in platforms with views of the runoff from Canary Spring.  As you listen to the cascading water, imagine you were here 

in the late 1800s".  [Okay, it's a little corny, but please play along...]  "At that time yellow filamentous bacteria was 

prominent".  [Oh geeze, that was kinda gross, I wonder if it looked AND smelled bad?]  "Yellow remains a common color near 

the vent, and the spring also exhibits the orange, brown, and green seen in the other hot springs of the area."
<p>
Funny, all I saw was hot, streaming, canary blue water.  But that was enough for me to make it my favorite.  It was quite 

beautiful...
<p>
<a href="index.php?action=Pics&name=Daily/20040805/P1010069.JPG"><img src="Pics/Daily/20040805/Small/P1010069.JPG"></a>
<p>
... but it stunk, smelled like rotten eggs, probably sulfur in the water.  And lucky me, I had wade back through the stinking 

fog since I was at a dead-end in the boardwalk.  
<p>
<a href="index.php?action=Pics&name=Daily/20040805/P1010073.JPG"><img src="Pics/Daily/20040805/Small/P1010073.JPG"></a>
<p>
Here is a gander across the Main Terrace.
<p>
With that last photo it was a wrap, I had seen all the formations.  In summary my experience was both educational and 

inspiring.  Now that I'll all knowledge-filled, I think I'm going to replicate one of the terraces myself.  Just need some 

underground limestone formations and lava.  You think maybe Yellowstone has any real-estate it wants to sell me?
<p>
I rate this great sight a 10 out of 10.  Its one of a kind...
