Outside the restaurant I see this old car on display.  It's part of the Elvis Presley Automobile Museum.  Looking under the car I get a chuckle, I notice it's suspended on wooden blocks and is chained to the concrete block atop which it sits.  Once painted pink and used as a salad bar, this 1957 Cadillac Seville is now tasked with marking the entrance to the museum.  Based on the car's sordid history, is chaining it down really necessary?
