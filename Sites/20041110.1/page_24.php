While admiring my Graceland postcards I picked up at the gift shop, I pass by this airplane as I walk out of the complex.  Apparently it's part of the Lisa Marie and Hound Dog II Tour.
<p>
Well, that wraps up my tour of Graceland.  In a nutshell, I arrived not a fan of Elvis, and I now leave a fan of Elvis.  What more can one say?  Elvis was the predominate catalyst and the first crashing wave to bring rock-and-roll to the masses.  Elvis was a great man, he could sing, he could act, he was charitable, he served his country in the US Army, he was many things to many people.  Even today, 27 years after his death, his legacy is still remembered and revered by countless millions of fans.
<p>
I give my tour of Graceland 5 thumbs-up, a perfect rating!
