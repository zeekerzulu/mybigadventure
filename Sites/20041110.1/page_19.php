Before this ground was turned into a cemetery, it was Elvis' place of contemplation and meditation.  Currently, it features a circular 12-foot fountain pool containing one large water jet encircled by 5 smaller ones that are all lit by multi-colored lights.  The curving wall in front of the grave markers is made of Mexican brick and holds 4 stained-glass windows.
