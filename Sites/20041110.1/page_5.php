<p>
<a href="index.php?action=Pics&name=Daily/20041110.1/DSCN0119.jpg"><img src="Pics/Daily/20041110.1/Small/DSCN0119.jpg"></a>
<p>
In the dining room I discover this picture of <ax href="javascript:myPopup5('http://en.wikipedia.org/wiki/Priscilla_Presley')">Priscilla Beaulieu Presley</a> with 2-year-old daughter <ax href="javascript:myPopup6('http://en.wikipedia.org/wiki/Lisa_Marie_Presley')">Lisa Marie</a>.  Elvis met 14-year-old Priscilla in West Germany when he was serving two years in the US Army from 1958-1960.  She eventually moved to Memphis in 1962 and slowly moved in with Elvis at Graceland.  Married in 1967, the couple quickly produced their only offspring, Lisa Marie, 9 months later.   Elvis and Priscilla separated in 1972 and divorced in 1973.  Both parents shared custody of Lisa Marie, splitting her home between Graceland and Los Angeles.
<p>
Elvis was... how shall I say... Elvis.  Given all the opportunities he had with beautiful women, it's been said "his list of one night stands could fill volumes."  Due to all his philandering, his long-term relationships suffered greatly.  As time passed, he entered into a pattern of leaving older women for younger ones.  At the time of his death at 42, he was in a relationship with an 18 year-old woman who was living at Graceland.
