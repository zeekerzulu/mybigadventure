Facing the front door is the stairway to the <!--<ax href="javascript:myPopup10('http://www.linkydinky.com/graceland')">-->second floor<!--</a>-->.  Hmmm, I see there's a curtain covering access to the second story.  My audio recorder tells all.  The curtain is there because Elvis never, ever let company upstairs.  In respect of his privacy, even in death, tour folks are not allowed up there.
<p>
Rumor has it, only 3 people are allowed up there.  The entire upstairs has been "locked-down" since Elvis' death in 1977.  Supposedly nothing has been moved or touched.  The three people allowed upstairs are Priscilla, Lisa-Marie, and Graceland's Curator.
<p>
Until now!  I'm going to crash through the barrier, run up the steps, a hidden security guard is going to jump me (supposedly there's one up there on the landing in a non-sacred area), a struggle will ensue, re-enforcements will be called in, I'll be cuffed, then dragged to the police station!
<p>
Ummm, I think I've just changed my mind. Lets just continue on with the tour, shall we?
