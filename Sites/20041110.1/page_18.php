Before exiting the exhibit, I catch these last two displays.  In 1993, the <ax href="javascript:myPopup1('http://www.postalmuseum.si.edu/artofthestamp/SubPage%20table%20images/artwork/rarities/Elvis%20Ballot/elvisballot.htm')">US Postal Service</a> issued a stamp bearing the image of young Elvis.  Earlier, a public poll was conducted, to determine which image of Elvis should adorn the stamp, a <ax href="javascript:myPopup6('http://www.postalmuseum.si.edu/artofthestamp/SubPage%20table%20images/artwork/rarities/Elvis%20Ballot/BIGyoungelvis.htm')">young Elvis</a> or an <ax href="javascript:myPopup5('http://www.postalmuseum.si.edu/artofthestamp/SubPage%20table%20images/artwork/rarities/Elvis%20Ballot/BIGoldelvis.htm')">older Elvis</a>.  By an overwhelming margin of 75% of the 1.2 million votes cast, young Elvis ruled supreme.
<p>
The last display houses an America flag folded in military funeral style, in a triangle.  Elvis served in the US Army for 2 years between 1958 and 1960.  This tribute is a way for the Veterans Administration to acknowledge Elvis' contributions, not only the military, but more importantly, to his country.
