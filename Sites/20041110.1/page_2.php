Here's my ticket.  I'm not sure what to expect when I walk in the front door.  I've heard second and third-hand that Graceland is really tacky and outrageous; shag carpets, gaudy fixtures, lots of mirrors, etc.  Regardless, I'm entering this tour with an open mind.
