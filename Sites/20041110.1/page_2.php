While waiting for the next tour bus to arrive, the facility offers overhead audio and video entertainment to help pass the time.  Since the tours run all year long, space heaters have been installed to help take the chill out of the Tennessee air during cold spells.
<p>
<a href="index.php?action=Pics&name=Daily/20041110.1/DSCN0065.jpg"><img src="Pics/Daily/20041110.1/Small/DSCN0065.jpg"></a>
