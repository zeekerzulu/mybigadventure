Ahhh, the seemingly mandatory photo shoot.  Let's see if they try to sell me my photo at the end of the tour.  I'd only be interested in buying it if the scene was of Elvis singing on stage and I can stick my face through a hole in place of Elvis' face.  This particular background scene is just way too pastoral for my tastes.
