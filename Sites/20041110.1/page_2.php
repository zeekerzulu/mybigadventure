I buy my ticket then get in line for the shuttle bus.  A bus is required because Graceland Mansion is located across a busy street.  Apparently they didn't want to erect tourist facilities on the estate, a good decision on their part.  I decide to just pony up for the tour of Graceland Mansion.  Other options include:
<ul>
<li>Elvis Presley Automobile Museum
<li>Sincerely Elvis Museum
<li>Lisa Marie and Hound Dog II Tour
<li>Watch the film Walk A Mile In My Shoes
