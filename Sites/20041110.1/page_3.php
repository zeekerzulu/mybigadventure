Graceland's architecture is predominantly Colonial style with Greek influences.  Funny, the 14-room mansion isn't as big as I had envisioned.  Built in 1939, the mansion is located at <a href="javascript:myPopup2('http://mappoint.msn.com/(zm2ipr55v2xu5v455mdeo5vt)/map.aspx?L=USA&C=35.04794%2c-90.02362&A=4.30000&P=|138279|&TI=Graceland+(museum)%2c+Memphis%2c+Tennessee%2c+United+States')">3764 Elvis Presley Blvd</a>.  In 1957, Elvis bought the mansion for $100,000 and lived here until his death in 1977.  Opened as a museum on 1982, the mansion was listed on the <ax href="javascript:myPopup3('http://nationalregisterofhistoricplaces.com')">National Regsiter of Historic Places</a> in 1991.
