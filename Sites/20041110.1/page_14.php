Stepping out of the Hall of Gold, I encounter this display that speaks of Elvis' stint in the US Army.  He was drafted in 1957 and served two years in West Germany.  Given his fame at the time, he could have easily pushed a few buttons and rode out his tour with relative ease.  Not Elvis!  He just wanted to be treated just like any other soldier.  That's the kind of guy he was.  Hard working and loyal to his country.  I find his attitude almost as impressive as all his record trophies in the Hall of Gold.  Elvis had character.
