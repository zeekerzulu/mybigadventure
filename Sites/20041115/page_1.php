The Alamo is a sacred place where many Texans died at the hands of Mexican forces on March 6th, 1836.  Located near the mission complex, I find the Alamo Cenotaph.  This 60-foot high monument is a fine tribute to all the American's who died during the <a href="javascript:myPopup10('http://en.wikipedia.org/wiki/Battle_of_the_Alamo')">Battle of the Alamo</a>.
