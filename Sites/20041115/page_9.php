Here's a close-up of the Long Barrack.  Owned by the State of Texas and operated and maintained by the <a href="javascript:myPopup5('http://en.wikipedia.org/wiki/Daughters_of_The_Republic_of_Texas')">Daughters of the Republic of Texas</a>, the Alamo Complex is certainly a national treasure of epic significance.  No wonder so many people from around the world make a point of visiting this fine historical sight.
<p>
<a href="index.php?action=Pics&name=Daily/20041115/DSCN0213.jpg"><img src="Pics/Daily/20041115/Small/DSCN0213.jpg"></a>
<p>
Let's check out the Long Barrack Museum.  Established in 1968 using the original remains of the Long Barrack, the museum contains exhibits that trace through the Alamo's historic past as well as the Clara Driscoll Theater where you can watch an orientation film every 20 minutes.
