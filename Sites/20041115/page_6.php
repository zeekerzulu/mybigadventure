Next to the Wall of History is the Gift Museum.  Gift Museum?  I walk inside to check it out and soon discover it's just a <a href="javascript:myPopup10('http://thealamo.org/ecommerce/index.html')">large gift shop</a>.  Geeze, not only is the building not original, they make out like it contains historical artifacts that were once gifts.  If they had appropriately named it the Gift Shop I wouldn't have gone in.  Ooooh, I get it now.  Ha!  But I foiled them by golly, I didn't buy anything.
