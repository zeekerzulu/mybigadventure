Nearby I notice, of all things, a Japanese Monument.  This marker is rather fascinating.  In 1914, a Japanese geography professor presented this monument to the Alamo.  Impressed with how similar the Battle of the Alamo was to the Japanese <a href="javascript:myPopup1('http://en.wikipedia.org/wiki/Battle_of_Nagashino')">Siege of Nagashino Castle</a> in 1575, Shigetaka Shiga commissioned the creation of this monument which bears a poem he wrote that compares the events at the Alamo to the famous Japanese incident.
