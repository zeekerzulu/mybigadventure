Thinking back, working at Tony and Maria's was a really good gig.  The employees could eat and drink as much as they wanted (but we curtailed that activity when times got tough for Tony) and I remember drinking whole 6-packs of pop on long shifts during hot, muggy days.  Tony always left the ovens on 7 x 24 so that only added to our heat induced thirst.
<p>
And then there is the time we got held up at gunpoint.  I was just visiting (I think Mike Finello and Dave Sargent were working at the time), on my way home from the high school basketball game, when this guy walks in with a deer rifle, demanding us to "put the money in a bag".  All the while I was just standing there, looking at the gun, never once did I look at the robber. After Dave handed over the cash the robber told us to "drop down below the counter" which we all simultaneously performed on his command. After we dropped down, a customer (Tim Shultz?) who was talking to Mike just before the robbery happened was taken hostage.  We could hear the robber say "Hey fatboy, we're going for a ride".
<p>
Long story short, the robber let the customer go when they exited via the front door, we went down to the police station to made a report, the next day the robber's brother called the police, and the police got their man.  I think he got away with something like $350 which was a pretty good night at the parlor.  They only recovered something like $90.
