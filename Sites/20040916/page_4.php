Next street of interest for me was Pearl Street.  This street bisects the village and generally runs northeast to southwest, crossing Main Street at it's mid-point.
<p>
<a href="index.php?action=Pics&name=Daily/20040916.1/DSCN0163.JPG"><img src="Pics/Daily/20040916.1/Small/DSCN0163.jpg"></a>
<p>
This garage used to be where Doug Paille had his business, a small trucking company called Paille Express.  Sadly, it seems to have fallen by the wayside, perhaps it moved to a bigger, better location?  Hope so...  Since Sally Paille died so long ago, we haven't kept up with how the family is doing.  I remember going to her funeral when she passed away, it was so sad.  That must have been almost 15 years ago?
