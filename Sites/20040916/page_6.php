The dairy and the gas station.  Back in the day when I was a kid we called it "The Dairy" because that's what it was, primarily a place to buy milk products like milk and ice cream.  But this seems to be new.  The dairy is no more, a Mother Goose Grocery Store has taken it's place.  The gas station however has always been a Mobil station.  The only major difference is the old Mobil sign was a red horse with wings.  I think I like the old sign better.
