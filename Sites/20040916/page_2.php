After 3rd grade they shuttled grades 4 thru 6 over to the grade school on Drake Street.  I think I was there for 4th and 5th grades then they moved my class back to the elementary school for 6th grade because they finished adding on the new wings to accommodate grades 4 thru 6.  The old school is now used for senior/handicapped housing.
<p>
<b>Note:</b> The old school on Drake Street is actually located further in town.
<P>
I have two prominent memories from 4th and 5th grades.  The first one involves Patrick Meyer.  At that time, teachers were allowed to paddle the students if they misbehaved.  The paddles that had holes drilled in them were particularly feared because they could be swung quicker (less wind resistance) and, as a result, hurt more.  Corporal punishment was a good deterrent and I think it's too bad it's not allowed anymore.  In any event, Patrick did something to piss off old Mrs. Henderson (she was a rather mean woman so it probably wasn't much) and he was told to stand in front of the class to be paddled.
<p>
When Mrs. Henderson was poised to paddle Patrick, with paddle raised high and growing gleam in her eye, Patrick did the unexpected.  He made a mad dash for the door, howling in delight as he ran through the doorway, having successfully escaped her wrath.  I found out the next day that he had simply ran home.  I don't remember hearing if he got in trouble for leaving school, but I thought it was a good action plan on his part, enough to make the event something that I'll never forget.
<p>
My second memory was in gym class where I got the 5th grade school record for the high hurdles.  I remember learning as a senior that I still had the record.  Maybe Coach Goldstein can email me and let me know if it still stands.
