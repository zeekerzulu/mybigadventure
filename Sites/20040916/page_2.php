I really don't remember a whole lot when I was in K thru 3rd.  Just the stupid things, like lifting up my classmate's dresses to expose their undergarments for all to see.  There was also kickball and I think one year we had an Olympics day of sorts where we all competed against each other.  I won a couple of ribbons but don't remember for what.  Oh, yeah, I remember one of the teachers bringing in a cow's heart to science class.  I suppose the more I think about those days, the more that'll come back.  It's amazing how a lot of it is still there, all stored up high and dusty in the back shelves of my mind.
