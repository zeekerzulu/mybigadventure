<p>
The middle-high school was different however.  Seems they had added an addition to the front of the building, needing more space for an expanding student population?  I remember grades 7-12 pretty well but rarely think about them.  Being a loner I never felt a strong connection or affection for the school.  Nor did I have close connections with any of my classmates.  High school was just a right-of-passage for me.  It wasn't a bad experience, but then again I don't hold many fond memories of it either.
<p>
And that's really my fault.  If I had to do it all over again, I'd try to be less shy and uptight.  I would have gotten more involved.  But I have no real regrets.  My time spent there so long ago just seems like a void in my distant past, something that I never really experienced.  My memories feel like half-forgotten TV episodes of someone else's life viewed long, long ago.  I guess you can say I've really disconnected from it all.
<p>
