After passing by the school I encountered Farnsworth Avenue.  Our family friends, the Pailles, lived there and in the summer we would frequently go to their place to swim in their above ground pool.  I used to hang around with Mark Paille, I even worked with him at the local pizzeria, Tony & Maria's Pizzeria.
