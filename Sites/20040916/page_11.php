Here is a view looking back down Gibson Sreet.  I was disappointed to see they cut down a lot of the trees when they widened the road and put in the drainage.  As a kid I remember a good portion of the street was canopied by tall, wonderful trees.  I have to say on average the street has gone a little down hill since I last visited.  And going back even further to when I lived on the street, the difference is even more striking.  But like people, houses age and grow old.  I understand times have grown tougher for the town with the gypsum mine closure.  It's hard to say what the reasons for it's slow decline are.  But just the same it's sad to see it not change for the better.
