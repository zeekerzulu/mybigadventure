At the center of town, where Drake, Pearl and Main Streets form a triangular park, you will find this nice gazebo.  This was here last time I visited but wasn't when I moved away to Buffalo, NY in 1985.  They really did a nice job with the construction and have kept up the maintenance.  I hear this triangle park is the hub of activity every year for the festival they have (sorry, I don't remember it's name).
