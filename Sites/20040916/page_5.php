I continued on Pearl Street until I came upon the un-marked bowling alley.  Now sure why there isn't a sign.  I guess in a small town like Oakfield everyone knows where it is so why bother spending money on a sign.  The bowling alley is the last building in the third picture.  I found this end of Pearl Street to be a bit run-down, more run-down than I remember it to be.
