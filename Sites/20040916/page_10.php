The folks who bought the house from my parents still live there.  I actually talked to the owner on the phone and made plans to visit.  But in the end they fell through, she was sick and couldn't see me.  Which was too bad, I wanted to see what it looked like on the inside.  A few years ago my sister Teresa took a tour and reported back that it pretty much looked the same.  So I probably didn't miss out on anything.
<p>
I think the house looked pretty good and appeared to only need a paint job.  Seeing the house brought back memories of being on the hook as a kid, having to paint one side per year, like clock-work.  The painting wasn't the bad part, it was all the scraping prep work.  I really hate to scrape.
