I was probably 10 years old and I thought it was a school day.  So I got my self up, dressed, ate breakfast, then headed out to the bus stop one street down from Gibson Street.  After I got there I just waited, and waited, and waited.  The bus was just late I thought.  But it seemed strange that I was the only kid there, where was everybody else?  After more waiting, I noticed my family car had pulled near the bus stop and they were motioning to me.  Come to find out, it was Sunday, not Monday, and they were all heading off to church.
