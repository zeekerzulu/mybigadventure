Across the street from the cemetery you'll find the Oakfield Fire Station and the adjacent baseball diamond where the Softball Fire Station Leagues play.  We lived pretty close to the fire station.  At 6pm every day the siren would sound off.  All other times it was an actual call.  It was pretty loud, enough to wake me from a sound sleep.
