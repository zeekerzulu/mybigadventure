Near my old church I spied the village cemetery.  It's a pretty big cemetery, probably dating back to the 1800s.  We used to play at the "newer" end of the cemetery as a kid but since then, people continued to die, and their subsequent burial has slowly swallowed up my old playing digs.  I remember playing football here with the neighbor kids as well as flying kites in the spring.
<p>
One spring I bought a huge, red kite and made plans to tether it with not one but two balls of string.  On a really windy day I decided to fly my new kite.  Reeling out the first ball's worth of string was a smashing success, the kite was really high in the sky.  But I was stupid about how I tied the end string of the first ball with the start string of the second ball.  I tied the start string to the end string but not vicaversa.  Needless to say as the second ball of string started to feed from my hand I had the displeasure of watching my kite break free then quickly ascent to monumental heights as it soared up and out of sight.
