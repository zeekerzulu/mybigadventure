I hadn't paid my old hometown a visit in over 10 years and my long absence made me wonder if everything was still the same.  I had lost contact with everyone I knew there after moving to Buffalo, NY in 1985 so periodic updates on the state of the town were effectively severed.  My last visit before moving to Portland, OR proved that few things had changed, leaving me with a feeling that even in this seemingly ever-changing world, some things -do- remain the same.
