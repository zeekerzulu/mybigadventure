I entered the village on my bike (I did my tour via bike to increase my range of visibility so I wouldn't miss anything) from the northwest and immediately encountered the elementary school.  The school hadn't changed since my last visit.  My first memory of school was my first day of kindergarten when I got off my bus.  I recall my bus was identified as the "blue bird" bus.  Each bus had a unique animal sticker prominently pasted on its side so the children could select the right bus when classes ended and it was time to board for the ride home.  Because when you're in kindergarten, it was possible you didn't know how to read numbers.  I was 5 years old at the time, the second youngest in my class (I think Brian Kingsley was the youngest), and I don't remember if I knew how to read numbers.  I probably didn't.
