"CIRCUS BUILDING: Everybody loves a circus and The House on the Rock is no exception. Over one million pieces comprise the collection of miniature circuses. Even the pyramid of life-sized elephants is overwhelmed by the colossal circus wagon, with its 40-piece animated band.  The Circus Band plays in concert with an 80-piece orchestra.  The 12-piece ensemble took 14 people three years to create and it encompasses 37 miles of wiring, 31 blowers and 2,300 pneumatic motors. The ensemble is complemented by 50 additional life-size mannequins accented in exotic costumes. The room also features the most complete collection of Baranger Motions, which were featured in store windows of many fine jewelry stores during the 20's, 30's, 40's and even 50's."
