I continue my tour of the original House on the Rock.  I have to admit the place is pretty damn cool.  For its time the design is very cutting edge.  I can see why people wanted to pay Jordon to see the place.  Jordon's original intent wasn't a sight-seeing attraction, rather, he just wanted to build a home for himself.  But when word got out about the house's unusual design, people from the all over the local area wanted to see it.  After a while he started to collect admission and that was the start of the attraction.  All the money he collected was put back into the house in the form of new construction and expanding his collections.  Over time as the attraction grew, Jordon was able to charge more and more for admission.  It all snowballed from there.
