<p>
"VILLAGE SHOPS: A village of individual specialty shops constructed outdoors in a garden setting amid blooming flowers and shaded walkways. Clothing, jewelry, and figurines are just a few of the treasures for sale. Also featured are delicious homemade candies."
<p>
"THE DISPLAY GARDENS: The House on the Rock gardens began in 1983. They have grown to become one of the largest display gardens of Wisconsin.  The displays feature 285 different types of plants, over half of which are virtually unknown in the Midwestern states.  The featured flower of The House on the Rock garden in Alex Jordan's favorite flower, the Amaryllis."
<p>
I have to say, after finishing the tour and walking back to the van, I'm still spellbound by all that I have seen and heard.  This attraction is very unique, a truly one-of-a-kind exhibit.
<p>
I rate my tour of the House on the Rock a perfect 5 thumbs-up!  If you ever find yourself in Southern Wisconsin, you have to check this place out.  But make sure you get here early.  There is so much to see and do, it will easily take you all day to go through it all.  I wish I had more time for my tour.  My tour was a whirlwind one since I had arrived late in the afternoon, giving me a scant 2.5 hours before they closed.
