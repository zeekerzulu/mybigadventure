Atop the Capitol's dome is the 19-foot statue <ax href="javascript:myPopup5('http://en.wikipedia.org/wiki/Statue_of_Freedom')">Freedom</a>.  The bronze statue depicts a female holding a sheathed sword on one hand and a laurel wreath and shield in the other.  Hard to see because she's so high up (her crest rises 288 feet above the plaza), many people mistakenly think the statue is that of an Indian because of its crown feathers.  I think I can include myself into that same, uninformed group of folks.
