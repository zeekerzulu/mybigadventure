Wrapping up his talk about the Capitol Rotunda, the tour guide remembers to tell us it's okay to take pictures in the Rotunda.  D-uh!  So I'm forced to take these rushed shots as they move us into the Capitol Building's South Wing.
<p>
The Rotunda is 96 feet in diameter and 180 feet in height.  Wow!  That's a whopping 18 stories.  A total of 8 large historical paintings adorn the walls, above them I find 4 wreathed panels and the busts of 4 famous early settlers.  Lastly, above each of the 4 entrances I spy individual relief panels depicting scenes from early American history.
<p>
<a href="index.php?action=Pics&name=Daily/20041029/DSCN0233.jpg"><img src="Pics/Daily/20041029/Small/DSCN0233.jpg"></a>
<p>
Just below the 36 windows that encircle the dome I find a dramatic <ax href="javascript:myPopup7('http://www.aoc.gov/cc/art/rotunda/frieze/index.cfm')">frescoed frieze</a>.  It depicts American history, from the landing of Columbus to the birth of aviation.  All told there are 19 individual scenes that are specially painted to give the illusion of being sculpted relief.
<p>
<a href="index.php?action=Pics&name=Daily/20041029/DSCN0239.jpg"><img src="Pics/Daily/20041029/Small/DSCN0239.jpg"></a>
<p>
High overhead I see this dramatic <ax href="javascript:myPopup8('http://en.wikipedia.org/wiki/Apotheosis_of_Washington')">fresco</a>.  Here's a better <a name='valid_link' href="javascript:myPopup9('http://en.wikipedia.org/wiki/Image:Apotheosis_of_George_Washington.jpg')">picture</a> of it.  The painting features George Washington, who's draped in a purple robe, and is part of a circle of 15 characters; Liberty, Victory, and 13 women who represent the original thirteen colonies.  All are surrounded by scenes containing various mythical characters.
