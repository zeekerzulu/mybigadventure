After about 10 minutes of waiting the group gets the go-ahead to walk to the South Visitor Receiving Facility.  Once there they tell us to stow away our cameras for the time being.  They then herd us all into the facility, afterwhich we listen to a talk about the do's and don't of attending their guided tour.  Soon enough they march us to a back entrance of the U.S. Capital Building where we enter into the <ax href="javascript:myPopup6('http://www.aoc.gov/cc/capitol/rotunda.cfm')">Capitol Rotunda</a>.  They haven't told us it's okay to take pictures yet, so everyone in the group just listens to the tour guide give his talk.
