The tour brings us into <ax href="javascript:myPopup10('http://en.wikipedia.org/wiki/National_Statuary_Hall')">
Statuary Hall</a>.  For 50 years this place used to be the meeting hall of the <ax href="javascript:myPopup1('http://en.wikipedia.org/wiki/United_States_House_of_Representatives')">U.S. House of Representatives</a>.  Also known as the Old Hall of the House, the two-story, semi-circular room is now the exhibition space for the <ax href="javascript:myPopup2('http://en.wikipedia.org/wiki/National_Statuary_Hall_Collection')">National Statue Hall Collection</a>.
