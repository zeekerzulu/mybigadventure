The tall tower turns out to be an extreme ride called "Top Thrill Dragster."  The ride opened late last season so it's the parks newest coaster.  Just watching the ride in action is enough to make me sick, let alone actually boarding and riding this insane coaster.  I decide I'll ride this coaster first, figuring it's the biggest, meanest, and most popular coaster in the park.  In hindsight, it wasn't a good idea to ride this coaster first.  I hadn't ridden a coaster in years.  I would compare the experience to fasting for a long period of time, then going to McDonalds and pigging out on 5 Big Macs.  It was just too much, too soon.
