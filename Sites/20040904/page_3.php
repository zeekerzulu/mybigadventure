Once 10am arrives a cattle stampede ensues.  Some folks are literally running (hoofing?) at full speed in pursuit of a good line position at their favorite ride.  As I walk into the park, I set my eyes back on the 7-level tower in the distance.  What is it? I purposely didn't do any research on the park, I wish to be surprised.
