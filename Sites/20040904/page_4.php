Near the ride's waiting line there's a grandstand for the less brave who just wish to watch the spectacle.
<p>
Prior to every launch a pre-recorded announcement is played, telling the riders to sit back, hold on tight, and keep all arms and legs in the car.  A thunderous dragster engine recording bellows out of the loud speakers as the "christmas tree" lights flash through its series of colors, from red to yellow to green.  Once the green light is lit, the dragster launches (via 40 hydraulic pumps) down the track with an accompanying tire screeching sound.  In less than 4 seconds the dragster accelerates to a maximum speed of 120 mph.
<p>
<b>VIDEOS:</b> The start of the ride's waiting line is right next to the dragster's launch point.  Here's a <a href="index.php?action=Videos&name=Pics/Daily/20040904.1/DSCN0047.MOV">launch</a> (2.89 MB) of the dragster from a rear point-of-view.  Here's another <a href="index.php?action=Videos&name=Pics/Daily/20040904.1/DSCN0048.MOV">launch</a> (3.19 MB) from a front point-of-view.  In the second video notice the front-row riders raising their hands just as the coaster leaves the launch pad.  The park tells you not to raise your hands on all of their coasters but most people (myself included) don't listen.  <b>Note:</b> I'm not trying to feature the ground at the tail-end of these videos.  I just keep forgetting to turn off the video prior to lowering the camera.
<p>
Upon reaching maximum velocity the dragster shoots up 400 vertical feet.  On the way up, the coaster track twists the cars 270 degrees to a level position atop the tower.  Optimally, at the tower's top, the dragster is supposed to slow down to a near crawl, then gingerly slip down the other side of the tower and accelerate to 120 mph on the way down.   Early on, while I'm waiting my turn in line, the ride operators are busy dialing-in the correct launch pressure.  During their process of trial and error, the dragster sometimes doesn't make it over the top of the tower.  Instead, it falls backwards back to the launch pad.
