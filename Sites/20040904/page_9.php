From the coaster's waiting line I can see Cedar Point's Marina.
<p>
Eventually it's my turn (yay!) to ride and as I board the coaster my anticipation grows.  The slow, clunky ride up the first hill provides a grand view of the park.  The first drop feels pretty steep and is followed by a plunge into complete darkness.  The subsequent hills and turns are exciting and fairly smooth.  After the ride comes to a complete stop and the dust settles, I take my pulse and find it to be somewhat elevated, running at 120 beats per minute.  A good test of how well I liked the ride.
<p>
Sorry, no picture of me on this coaster.  My arm was covering my face so I decide not to get it.  But I did see something interesting. I wish I had taken a picture of it.  Sorry, this might be offensive to some but I think it's worth sharing. Two young couples in front of me had some fun on the ride.  The two guys know where the pictures are taken on the coaster so each put one hand on their girlfriend's breast and did a thumbs-up with the other hand. Now that's something you don't see every day.
<p>
<b>BARF RATING:</b> All in all it was a great ride but I wish I had felt more in my gut.  Maybe the older I get the less I'm affected by such things?  So regrettably, I can only give this coaster a barf rating of 4 barf bags.  If the rating was based on just my general feelings about the coaster it'd have scored quite a bit higher.
