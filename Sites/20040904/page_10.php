<p>
It's too bad we have to wait so long. Imagine if they changed their admission model to where you have to reserve a 2 hour slot. Let's say I buy a ticket for 2pm to 4pm. When I arrive there'll be far less people and I won't have to wait as long in line. Now I can ride all the coasters in 2 hours vs having to wait around all day to fit everything in.
<p>
Sadly, the reality is nothing will change unless people refuse to wait. Here I am along with everyone else. What are we all doing? We're waiting. So nothing is going to change.
