The loading and unloading area.
<p>
When my time comes to get on the coaster, my harness height adjustment is a little too low at its highest position, forcing me to slouch a bit when I buckle in.  It isn't enough to cause much discomfort so I stay on and brace myself for the ride.  I've never ridden a stand-up coaster before, especially one that inverts you.
<p>
The coaster ride turns out to be a blast.  The inverted portions are probably my favorite, causing the most stomach sensations of the ride.  I also like the quick, tight turns and smooth flow of the train as it passes along the track.
