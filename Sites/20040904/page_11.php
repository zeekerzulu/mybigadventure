<b>BARF RATING:</b> I really like the Mantis, especially all the loops.  I give it a solid rating of 6 barf bags.
<p>
The next coaster on my list is Mean Streak.  This coaster is a colossal wooden coaster.  I've ridden it once before years ago and have fond memories of it.  It's old style, all clickity-clackity and jerky, what a wooden coaster should be.  I have to walk a ways to get there and it's during my walk that I realize just how many non-ride attractions the park has to offer.
