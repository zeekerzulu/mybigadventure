In 1980 they had a revelation to market their icy product in pint-sized containers, a packaging decision that stood the test of time and remains standing tall today.  I've never seen it sold in anything other than pint-sized containers.  Let's see, 2 pints in a quart and 2 quarts in a 1/2 gallon.  Given that, a Ben & Jerry's pint costs about $3.50, a 1/2 gallon would cost $14.00 but a volume discount would be in order.  So maybe it would be marketed for $12.00?  Not many people are going to pay that much in one pop, regardless of the volume discount.  I think their decision to sell in a pint container was a stroke of genius on their part.
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0184.JPG"><img src="Pics/Daily/20041004/Small/DSCN0184.jpg"></a>
<p>
Feeling the need to be record-breakers, Ben & Jerry entered the Guinness World Book of Records by building the world's largest ice cream sundae (27,102 glorious pounds) on April 15th, 1983.
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0186.JPG"><img src="Pics/Daily/20041004/Small/DSCN0186.jpg"></a>
<p>
In 1984 Ben & Jerry asked "What's the Doughboy afraid of?"  I haven't a clue what this means.  The Pillsbury Doughboy?  Can't see him being afraid of Ben & Jerry's, he's in the business of peddling dough-based products, not ice cream.
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0187.JPG"><img src="Pics/Daily/20041004/Small/DSCN0187.jpg"></a>
<p>
1986 was a glorious year indeed.  It was the year they opened the Waterbury Ice Cream Factory (the factory I'm touring) but more importantly, they started offering free samples.  I guess back then they didn't charge a touring fee.  You know, I bet they charge the small touring fee now to dissuade folks from taking repeated tours.  Meaning, when their tour ends after getting a free sample, they jump back in line for the next tour, repeating this cycle over and over many times.  Looking on the less dim side of those dark times, at least those folks were good new-hire candidates for guiding their tours, no training would be required. <b>VIDEO:</b> Here's the <a href="index.php?action=Videos&name=Pics/Daily/20041004/DSCN0209.MOV">factory tour</a> (0.81 MB) in full swing.
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0188.JPG"><img src="Pics/Daily/20041004/Small/DSCN0188.jpg"></a>
<p>
One year later in 1987, Ben & Jerry trekked to Wall Street.  Just after the Stock Market took a sharp nose-dive they arrived on the scene to help sooth the economic bite.  They offered free scoops of "That's Life Apple Pie & Economic Crunch" ice cream. <b>VIDEO:</b> Their efforts filled disheartened stock holder <a href="index.php?action=Videos&name=Pics/Daily/20041004/DSCN0210.MOV">piggy banks</a> (0.69 MB) with delicious delights.
