<p>
Two more events to add to the busy year of 1987.  It was the year they offered flavor Cherry Garcia, after the Grateful Dead guitarist, Jerry Garcia.  At present it's their 3rd most popular flavor.  Cherry Garcia and all their other flavors were now available nationwide.  Thanks to improved distribution channels, Ben & Jerry's effectively extended their reach to every American, giving all the opportunity to enjoy the magic of Ben & Jerry's Ice Cream.  <b>VIDEO:</b> Here's their <a href="index.php?action=Videos&name=Pics/Daily/20041004/DSCN0211.MOV">distribution channels</a> (1.16 MB) in action.
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0192.JPG"><img src="Pics/Daily/20041004/Small/DSCN0192.jpg"></a>
<p>
1988 was a huge year for being honored.  Ben & Jerry went to the White House to be named the U.S. Small Business Persons of the Year by President Ronald Reagan.  <b>VIDEO:</b> Supposedly this was the last time Ben & Jerry were ever seen <a href="index.php?action=Videos&name=Pics/Daily/20041004/DSCN0213.MOV">wearing ties</a>. (1.01 MB)
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0193.JPG"><img src="Pics/Daily/20041004/Small/DSCN0193.jpg"></a>
<p>
1989 was the year in which flavor Rainforest Crunch was introduced.  The recipe was vanilla ice cream mixed with a cashew and Brazil nut butter crunch.  Sounds pretty good.  Unfortunately you cannot get it anymore, I recalled seeing it earlier in the Flavor Graveyard.  But it certainly had a good run, it lasted up until 1996.
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0194.JPG"><img src="Pics/Daily/20041004/Small/DSCN0194.jpg"></a>
<p>
In 1990 a milestone was met, Mr. Woo was the millionth visitor to take the factory tour in Waterbury, VT.  To honor the occasion, they made a new ice cream flavor in his honor, "Mr. Woo's Surprise."  It consisted of vanilla ice cream with little shredded pieces of Mr. Woo.  Mr. Woo was pretty surprised when he learned he was going to have to die to get the honor, hence the name for the flavor.  Since Mr. Woo only weighed 145 lbs, it was a very limited time offer, they only had so much of Mr. Woo to go around.
