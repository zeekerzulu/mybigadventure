So here I am, chillin' in my yellow wooden lawn chair, enjoying myself, enjoying life, enjoying my ice cream.  It takes me a good 15 minutes to eat it all.  It's the best triple scoop cone I have ever had, probably because it's factory fresh.
<p>
What can I say, my tour of Ben & Jerry's Ice Cream Factory was spectacular.  I really respect the company for its environmentally and socially conscious business practices.  Not only does their ice cream taste great, it also contains all natural ingredients.  The factory tour was both entertaining and informative.  The list goes on and on.  Well deserved, I give my tour a perfect 5 thumbs-up rating.  If you are ever find yourself in Northern Vermont, you just gotta swing by the Ben & Jerry's Factory in Waterbury, VT.  You'll be glad you did.
