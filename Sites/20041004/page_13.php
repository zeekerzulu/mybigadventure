After the "moovie" we're led upstairs to an enclosed platform that provides an aerial view of the factory floor.  Since the technology Ben & Jerry's uses to make their ice cream is a "trade secret", we are all requested to not take pictures.  Major Bummer!  As a substitute, all I can say is the factory floor is interesting, filled full of strange machinery.  As the tour guide gives his talk about ice cream making, overhead monitors are on-hand to show the factory in action as he steps the crowd through the entire process.
