<p>
It's a nice sunny day, as evidenced by all the ice cream eaters who have flocked outside to eat their ice cream and soak up the rays.
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0220.JPG"><img src="Pics/Daily/20041004/Small/DSCN0220.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0221.JPG"><img src="Pics/Daily/20041004/Small/DSCN0221.jpg"></a>
<p>
I get into line to buy my tour ticket.  Waaaait a minute!  Seems the free samples aren't so free after all.  To take my mind off the admission charge while waiting in line I spy this cool interactive, educational ice cream history board.  It chronicles Ben & Jerry's Ice Cream History from 1963 (1 year before I was born) to 1994, a full 31 years of ice cream happenings.  Most importantly, it has levers and handles you could grab a hold of and move, which effectively adds more spice to the history lesson being told.  Its design is really rather clever, given its ability to amuse and hold the attention of both children and.... and... children.  Okay, I'm just a big kid, I admit it.
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0180.JPG"><img src="Pics/Daily/20041004/Small/DSCN0180.jpg"></a>
<p>
In 1963, Ben Cohen and Jerry Greenfield met in seventh grade gym class.  A natural bond formed between them almost immediately because they both hated gym class.  <b>VIDEO:</b> Here's a <a href="index.php?action=Videos&name=Pics/Daily/20041004/DSCN0207.MOV">video</a> (0.72 MB) of Ben & Jerry doing one of the things they hated to do in gym class, running.
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0181.JPG"><img src="Pics/Daily/20041004/Small/DSCN0181.jpg"></a>
<p>
14 years later in 1977, Ben & Jerry moved to Vermont and took a $5 correspondence course in ice cream making.  Little did they know that their $5 investment would make them multi-millionaires.
<p>
<a href="index.php?action=Pics&name=Daily/20041004/DSCN0182.JPG"><img src="Pics/Daily/20041004/Small/DSCN0182.jpg"></a>
<p>
The guys really took their ice cream making class to heart.  On May 5th, 1978, they scooped their first cone from a small Vermont gas station.  <b>VIDEO:</b> Watch their <a href="index.php?action=Videos&name=Pics/Daily/20041004/DSCN0208.MOV">scoop action</a> (0.77 MB) as they build business up from their humble beginnings.
