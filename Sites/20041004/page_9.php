Wooo Hoooo!  In 1991 Ben & Jerry reached 58 million dollars in sales.  By then they had more than 68 scoop shops in 19 states.  Hmmm.  More than 68 scoop shops?  That sounds a bit strange.  Didn't they know -exactly- how many scoop shops they had in 1991?  If they couldn't accurately count the number of stores they had, I cringed to think just how far off their other accounting numbers may have been.  Maybe it was really only 5.8 million dollars in sales for 1991?
<p>
Actually that's probably what would have happened if Ben & Jerry did the accounting themselves.  There was a time, early on in the business, when things were tight and they were scrounging around for money.  Within a large stack of papers on a desk one of them discovered an old, uncashed check.  Needless to say both were elated.  But their joy was quickly squashed when they discovered 3 bills within the same paper pile that had gone unpaid and when added up exceeded the newly found uncashed check.
