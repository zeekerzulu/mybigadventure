A little more driving takes me right into the center of <ax href="javascript:myPopup3('http://www.capecodweb.com/capeinfo/provincetown.htm')">Provincetown, MA</a>.  It is here the Mayflower first reached landfall in 1620.  Officially incorporated in 1727, Provincetown's population was rather small, and the majority of the residents worked in the fishing industry.  The population exploded after the Revolution however, and the town soon became the most important settlement on Cape Cod in terms of its economic contribution.
