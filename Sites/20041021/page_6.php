The first lighthouse to be constructed on Cape Cod, <ax href="javascript:myPopup2('http://home.comcast.net/~debee2/mass/Highland.html')">Highland Lighthouse</a> was originally a 45-foot wooden tower.  Due to weaknesses caused by the wet climate, the wooden tower was replaced in 1831 with one made of brick.  Originally placed a distant 500 feet from the edge of the bluff, by the late 1850s the ground underneath the lighthouse became unstable due to erosion.  In 1856 the lightkeeper's house was rebuilt and one year later the tower was replaced with the current 66-foot brick tower.   
