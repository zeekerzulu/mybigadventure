Upon closer inspection I learn this is <ax href="javascript:myPopup5('http://web.bryant.edu/~history/h364proj/sprg_00/knm1/')">Cape Cod Canal Railroad Bridge</a>.  Spanning Cape Cod Canal, the 544-foot movable span is usually hoisted 136-feet in the up position to allow for unimpeded naval traffic.  Completed in 1935 at a cost of more than 1.5 million dollars, the total length of the structure is 806 feet and at both ends you'll find 271-foot towers.  A few of the bridge's factoids: contains 110,000 steel rivets, 2.5 minutes to close, two 2.2 million pound counterweights.
