Last stop of my tour was the Outdoor Olympic Speed Skating Oval.  It's located in front of Lake Placid's High School of all places.  There wasn't much to see so I just imagined Eric Heiden flying around the oval with his "bling-bling" (5 Olympic Gold Medals) dangling from his neck.  Can you see him?
