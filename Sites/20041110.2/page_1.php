I've arrived at Beale Street, Tennessee's most visited tourist attraction.  The attraction is moderately small, encompassing only three street blocks.  I see they've erected barriers at either end of the three block section to keep the cars at bay.
<p>
There's so much to see and do here; bars, clubs, restaurants, shops.  First things first, the best I can do for you on this tour is to walk around and capture the many establishments in picture and video.  If anything catches your fancy, just click on the provided link to get more information about the Beale Street business.
