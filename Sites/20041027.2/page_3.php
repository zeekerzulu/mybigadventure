Finally, I arrive at JFK's gravesite.  Ahhh, there is the <ax href="javascript:myPopup5('http://en.wikipedia.org/wiki/John_F._Kennedy_Eternal_Flame')">Eternal Flame</a>.  The idea of an eternal flame isn't a new concept that originated at Kennedy's gravesite, rather, it's an <ax href="javascript:myPopup6('http://en.wikipedia.org/wiki/Eternal_flame')">age old symbol</a> placed in rememberance of someone important, a specific event, or to commemorate a group of brave and/or noble people.  Two examples include the Arc de Triomphe in Paris (burning since 1921) and a Buddhist tomb in Nara, Japan (burning for over 1,100 years).
