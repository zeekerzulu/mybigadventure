On March 4, 1921, the U.S. Congress approved the creation of a burial memorial, the <ax href="javascript:myPopup8('http://en.wikipedia.org/wiki/Tomb_of_the_Unknowns')">Tomb of the Unknowns</a>, better known as the Tomb of the Unknown Soldiers.  Crafted of white marble, inscribed on its Arlington, Virginia eastern facing panel are three Greek figures representing Peace, Victory, and Valor.  Inscribed on its western panel are the words:
<p>
<center>
HERE RESTS IN<br>
HONORED GLORY<br>
AN AMERICAN<br>
SOLDIER<br>
KNOWN BUT TO GOD
</center>
<p>
Below the Tomb sarcophagus resides the grave of the Unknown Soldier of World War I.  Within the grave itself are the remains of four unknown American soldiers who were exhumed from four World War I cemeteries in France and relocated here.  Just west of the sarcophagus you'll find the crypts of unknowns from World War II, Korea, and Vietnam.
<p>
<a href="index.php?action=Pics&name=Daily/20041027/DSCN0834.jpg"><img src="Pics/Daily/20041027/Small/DSCN0834.jpg"></a>
<p>
Serving as one of the sentinals for the Tomb of the Unknown Soldiers is considered one of the highest military honors one can achieve.  Responsibility for supplying the guards falls on the shoulders of the Third United States Infantry Regiment, also known as "The Old Guard."  The Old Guard is one of the oldest and most respected Infantry Regiments in the United States Army.  Admission into its ranks is not easy, over 80% of the soldiers who try out for the duty washout.
