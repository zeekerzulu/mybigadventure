<p>
My second to last picture of the day, my film camera was close to exhaustion.  The White River can be seen off in the distance.  Over the millennium, the White River was responsible for laying down all the sediment as a result of the formation of the Rocky Mountains to the west.  At that time there was a huge, continental lake that slowly drained to the east as a result of the rising Rockies.  Since then, the White River has played a reverse role, carrying away all the sediment that slowly washes out of the region when it rains and hence, forming the Badlands as we know them today.
<p>
I really enjoyed my tour of the Badlands.  One of the things I like most about them is they are deceiving.  I had always thought them to be very hard but in reality they are just soft, pliable clay with layers of soft wormhold sandstone.  Another enjoyable thing about this area is you feel like you're an another planet when you drive through the bizarre formations.
<p>
I rate my tour of the Badlands a solid 10 out of a possible 10.
