After a little more driving I encountered the most colorful section of the park.  Hues of red, orange and yellow were everywhere.  Visitors can climb on any and all formations, it's a regular free-for-all.  There were a number of folks crawling over these formations and I had to wait for them to clear out so I could take these shots.
