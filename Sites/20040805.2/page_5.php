...then suddenly things started to get all psychedelic on me.  In the distance bone white trees could be seen reaching up 

towards an orange, florescent sky. Overcome by feelings of joy and bliss, I could hear the soft, sweat melodies of sitar 

music.  The beautiful music, fueling my already heightened state of mine, had surely come from heaven above.  Something big was 

going to happen, I think the geyser was getting ready to blow...
