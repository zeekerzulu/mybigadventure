This is Black Growler Steam Vent.  "Black Growler Steam Vent, the steady stream of steam on the hill below you, has moved 

several times.  No one knows why it shifts, disappears, and reappears.  But Black Growler always roars back."
<p>
You GO growler GO!!!
<p>
<a href="index.php?action=Pics&name=Daily/20040805/P1010147.JPG"><img src="Pics/Daily/20040805/Small/P1010147.JPG"></a>
<p>
Then I can upon Constant Geyser.  In the distance I saw it spouting water so I walked over for a closer look.  And of course 

it stopped.  So much for being constant.  A better name would be Constipated Geyser.  "Constant Geyser could catch you by surprise.  Its frequent 

eruptions burst 20-30 feet high but last barely 10 seconds."
<p>
Okay, well the trail guide says frequent, so that was promising. 
<p>
Fortunately there was a bench in front of the geyser so I sat down to wait for the next water show.  But then I got to thinking, if there is a bench then 

that means I'm going to have to wait for this thing to go off.
<p>
<a href="index.php?action=Pics&name=Daily/20040805/P1010151.JPG"><img src="Pics/Daily/20040805/Small/P1010151.JPG"></a>
