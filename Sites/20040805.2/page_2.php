"Features throughout the Norris Geyser Basic can undergo dramatic behavioral changes simultaneously.  Clear pools may become 

muddy and boil violently, and some may temporarily become geysers.  Geysers may cease erupting or have altered cycles.  New 

features may enlarge."
<p>
"This sudden activity is know as a 'disturbance' and can last a few days or more than a week.  Gradually, most features 

return to 'normal'".
<p>
"Why this happens is not fully understood.  Features here may be served by multiple plumbing systems at varying depths.  The 

lack of extensive sinter buildup around the surface vents may allow more recycling of hot water into the plumbing system.  

Further study will help unravel the mystery of this phenomenon and lead to a greater understanding of the earth's hidden 

geologic forces."
<p>
Wow, that was a mouthful.  Pretty interesting information though.  Now, let's get on with walking the trail, shall we?
