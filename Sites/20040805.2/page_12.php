<p>
The last exhibit of the trail proved to be Emerald Spring.  "The magnificent color of Emerald Spring comes from the water 

reflecting blue wavelengths of sunlight combined with the yellow of the sulfur-coated pool.  The water in this 27-foot deep 

pool is so hot, close to boiling, that only the most heat-tolerant thermopiles can survive."
<p>
<a href="index.php?action=Pics&name=Daily/20040805/P1010230.JPG"><img src="Pics/Daily/20040805/Small/P1010230.JPG"></a>
<p>
At the trailhead on my way back to the van I noticed three vending machines.  It appears <a href="index.php?action=Stats&stat=Oddities&page=6#O14">Coca-Cola</a> has diversified their product-line to include both water and buffalo milk.
<p>
In summary, my tour of the Norris Geyser Basin was fun and colorful.  Its amazing to me all the different colors I saw, all 

naturally occurring.  Some of the geyser action I saw was nice as well.
<p>
I give my tour of the Norris Geyser Basin a solid 9.5 out of 10.
