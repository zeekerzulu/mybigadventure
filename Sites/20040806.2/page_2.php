I took a seat and decided to wait rather than go out sight-seeing and risk missing the eruption.  When I sat down it was just belching steam.  It still had 45 minutes to go before the predicted eruption at 1:17pm.
<p>
<a href="index.php?action=Pics&name=Daily/20040806/P1010097.JPG"><img src="Pics/Daily/20040806/Small/P1010097.JPG"></a>
<p>
As luck would have it, I was sitting within earshot of a Park Ranger who was giving a talk about the history of Old Faithful.  He said Old Faithful is special for 4 reasons.  1) it's predictable, 2) it erupts in relatively short intervals, 3) its eruptions are pretty high, 4) it doesn't seem to be affected by earthquakes and other geological events, thus it's reliable.  He also talked about past vandalism to the Park's various geysers, people throwing coins and other foreign material into them.  This effectively plugs them up and a few of the Park's geysers no longer erupt for this reason.
