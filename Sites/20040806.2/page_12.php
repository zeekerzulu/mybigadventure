"Watch out if Grotto Geyser is erupting - you could be sprayed as you walk by.  This geyser  erupts about every seven hours and splashes 10 feet for 1-1/2 to more than 10 hours.  The weirdly shaped cone may have resulted from sinter covering the trees that once grew here."
<p>
<a href="index.php?action=Pics&name=Daily/20040806/P1010186.JPG"><img src="Pics/Daily/20040806/Small/P1010186.JPG"></a>
<p>
At this point I had the option to continue on to see even more geysers but I was all geysered-out.  It was time to head back.  I walked so far up the trail that the return trip back along this path was rather long and anti-climatic.
<p>
It was a long haul but well worth it.  Boasting the densest concentration of geysers in the world, how could I give this sight anything less than a 10 out of a 10.
