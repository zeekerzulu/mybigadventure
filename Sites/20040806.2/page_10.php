"The magnificent cone of Castle Geyser is thousands of years old and rests upon even older platforms.  Together, they form one of the largest sinter formations in the world.  Castle's eruption pattern has changed throughout its recorded history; it is currently erupting every 11-13 hours.  A water eruption frequently reaches 75 feet and last about 20 minutes, followed by a noisy steam phase of 30-40 minutes."
