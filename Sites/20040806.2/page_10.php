"If you see a crowd at Grand Geyser and the pool looks full, wait a while.  You might get lucky and see the tallest predictable geyser in the world erupt.  A classic fountain geyser, Grand erupts with powerful bursts rather than a steady column like Old Faithful.  An average eruption lasts 9-12 minutes and consists of 1-4 bursts, sometimes reaching 200 feet."
