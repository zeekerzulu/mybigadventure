<p>
<a href="index.php?action=Pics&name=Daily/20040717/39.JPG"><img src="Pics/Daily/20040717/39_sm.JPG"></a>	
<p>
Unlike in the Western World, in China the bat is a symbol of good luck.  Bat-like shapes can been seen all over the garden.  One of the more obvious places is in the roofing tiles.  The tiles take on the shape of bat wings.
<p>
I really enjoyed my tour of the Dr. Sun Yat-sen Classical Chinese Garden.  The tour guides are knowledgable and friendly.  I'd strongly suggest taking a tour, there are so many hidden things in the garden that only an expert can uncover for you, it's worth the 40 minutes.
<p>
I give the garden the maximum rating, 5 thumbs-up!
