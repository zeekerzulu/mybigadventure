After a thorough examination of the church's adobe construction I make my way to the front of the church.  On the way I soak in the offerings of the left side of the church.  I must say, unlike the gothic cathedrals of Europe, this church proves to be rather terse with its ornamation.  Where are flying adobe buttresses?  Where are the adobe gargoyles?  Stain glass windows?  Sadly, they are nowhere to be found.
