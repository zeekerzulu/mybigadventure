Smooth surfaces from a distance give way to coarse textures up close.  Close inspection reveals the true nature of its composition, it's adobe.  No surprises here, this is the Southwest after all, where everywhere you look is adobe.  If I had a mind to I could easily pluck out numerous pieces of straw.  On second thought, however, I don't think God would appreciate me removing the straw, it's his house after all.
