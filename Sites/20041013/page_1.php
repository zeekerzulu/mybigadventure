<p>
I have to admit, I haven't spent a whole lot of time wandering the floorboards of covered bridges in the past.  However, the opportunity presented itself a few days ago when <a href="index.php?action=Stats&stat=Friends&date=20041008&page=13">Bill</a> and I drove by this covered bridge on our way to hiking <a href="index.php?action=Stats&stat=Hiking&date=20041009&page=7">Mount Chocorua</a>.  With piqued interest in hand, today I have returned to investigate this historical river crossing.
<p>
From atop a modern steel and concrete bridge that runs parallel, looking eastward I get a good "in-stream" view of the wooden bridge.  Spanning 152 feet across the Ossipee River, the Porter-Parsonsfield Historical Bridge was built in 1876 and has stood the test of weather and time with the aid of restoration work performed in 1999.
