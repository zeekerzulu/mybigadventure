I jump in the van and drive over to the north end of the covered bridge.  After parking, I notice what appears to be a <a href="index.php?action=Stats&stat=Oddities&date=20041013.2&page=25">colorful mural</a>.  Surely, someone must have graffitied the image on my van when I wasn't looking.  But, instead of colorful paint, they've leveraged the photo-reflective properties of lightwaves.  Clever.  I think the culprits here are both Mother Nature and God.  They often act together, ya know?
