We finally arrive at the cave entrance.  We all were immediately hit with a strong, cold wind draft coming from the cave's opening.  The Ranger went on to explain the draft is a result of a pressure differential.  The draft happened to be exiting the cave's entrance because the pressure in the cave was higher than the pressure outside the cave.  The reverse draft is possible when the outside pressure exceeds the inside cave pressure.  It was quite amazing, how pressure differential could cause such a phenomenon.
<p>
The Ranger said the size of Jewel Cave can be measured by the volume of air the cave inhales or exhales.  It has been estimated that the passage-ways total a capacity of 5 billion cubic feet.  That boils down to a 16 by 16 foot tunnel 5000 miles long.  Hard to believe.  The reality is the vast majority of the cave will never be explored because of the diminishing returns of exploration.  To get to the furthest reaches of the cave, one has to travel 11 hours.
<p>
<a href="index.php?action=Pics&name=Daily/20040821.1/P8210032.JPG"><img src="Pics/Daily/20040821.1/Small/P8210032.JPG"></a>
<p>
The opening itself is gated for obvious reasons, to keep the human animals out.  When the cave was discovered, this opening was smaller than a basketball.  It was discovered when someone noticed the exhaust of cold air from the opening.  They widened the opening and that was the start of the cave's exploration.  At present there are more than 160 miles of passages that have been surveyed, making it the 3rd largest surveyed cave in the world.
<p>
The cave is mostly an amalgamation of large and small passage-ways.  There are some large "rooms" however, the largest is a whopping 600 feet long by 150 feet wide by 150 feet tall.  Now that's pretty big!  Unfortunately it's about a 10 hour trek to get to it.
