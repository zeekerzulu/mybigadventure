Without a flash, the lanterns failed to provide adequate lighting for my picture taking.  Since it was a lantern tour, I refrained from using my flash often because it would wreck the experience for the other folks.  I was asked to be the last person in the queue which worked to my advantage since I would turn around periodically and use my flash to capture what I could.  Many of the pictures I shot didn't come out so I had to throw them out.  Too bad.
