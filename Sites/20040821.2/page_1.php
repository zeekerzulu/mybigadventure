<b>Personal Rating:</b> 8.5 of 10
<p>
Located near Custer, SD, Jewel Cave is a National Monument.  Since it's discovery in the 1920s, the cave has been extensively explored where 160 miles of passage-ways have been successfully surveyed and mapped.  The monument offers three types of tours and all tours are guided.  The cave is considered a "dry" cave where no significant geological change has occurred in the last 250,000 years.
