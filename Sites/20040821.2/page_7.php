At last!  We've arrived at our final destination, the Dungeon Room.  We've reached the end of the cave passage we've been crawling through for a better part of an hour.  The Ranger had us all blow out our lanterns and we sat there in total darkness while he talked more about the cave.  I got to wondering if I could find my way out of the cave in the dark, having traversed about 1 mile and descended more than 300 feet?  Yeah, right.  I'd be a dead man.  Before the Ranger extinguished his lantern I asked him if he checked to make sure he brought his lighter.  He did, much to my relief.
