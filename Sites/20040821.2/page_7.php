On the way out of the cave I didn't bother taking any pictures.  I just enjoyed my crawling adventure back out to the surface.
<p>
I have to admit, I'm a bit jaded when it comes to exploring caves.  When I was a kid my family and I took a road trip to Arizona and on the way we toured Carlsbad Caverns in New Mexico.  To but it bluntly, Jewel Cave looks pretty tarnished compared to Carlsbad.  But in all fairness, Jewel Cave certainly had it's jewels with all the calcium calcite we encountered.  I rate my Lantern Tour of Jewel Cave a 8.5 out of a possible 10.
