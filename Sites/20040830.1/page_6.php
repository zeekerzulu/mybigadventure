After my little tour of the wax room I head back into the store and buy 11 lbs of fresh cheese curds.  The lion's share I ship back to my friend <a href="index.php?action=Stats&stat=Friends&date=20040825&page=2">Greg</a> in Minneapolis, MN.  I try some of them, having never eaten a cheese curd, and am pleasantly surprised.  They're actually quite addictive.  Plus they're fun to eat because they squeak when I chew them.
<p>
Well that about wraps up my tour of Carr Valley Cheese.  What a wonderful place!  Their mission is quality, over quantity, that's why they're such a small outfit.  But even as small as they are, on a normal day they crank out 4,000 lbs of cheese, and on a busy day it's double that amount.
<p>
I rate my unique tour of Carr Valley Cheese a solid 4.5 thumbs-up out of a possible 5 thumbs.
