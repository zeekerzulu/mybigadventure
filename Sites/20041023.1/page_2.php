Oh well, moving on.  According to the inscription, the enclosure was erected in 1920 on the 300th year anniversary of the landing of the Pilgrims.  However, the actual ribbon cutting ceremony didn't occur until one year later, in 1921, due to delays caused by World War I.
<p>
<a href="index.php?action=Pics&name=Daily/20041023/DSCN0111.jpg"><img src="Pics/Daily/20041023/Small/DSCN0111.jpg"></a>
<p>
Nearby there's a placard proclaiming 180 years of history related to the rock.  It's hard to read but it's interesting, so below I'll try my best to decipher it for you.
<p>
<ul>
<li> 1741 - Elder Faunce identifies the rock as the final landing site of the Mayflower passengers.
<p>
<li> 1774 - The rock is accidentally broken in two while being moved to Town Square near the meeting house.  The bottom half is left in place in the harbor.
<p>
<li> 1775 - Edward Winslow Jr., son of Pilgrim governor Edward Winslow, annotates a map showing the landing site "... upon a large rock" and [something] Island, where Pilgrims kept the first Christian Sabbath.
<p>
<li> 1834 - The rock is moved from Town Square to Pilgrim Hall.
<p>
<li> 1835 - A decorative iron fence, bearing the names of the signers of the "Mayflower Compact" is [something] around the rock.
<p>
<li> 1859 - The original base of the rock is barely visible in the dirt road at the upper end of a busy wharf.  Workmen oblige visitors by sweeping it off from time to time.  The Pilgrim Society begins to acquire land around the rock and a cornerstone is laid for a protective canopy to cover it.
<p>
<li> 1867 - A monumental granite canopy designed by Pilgrim descendant [someone] is completed.
<p>
<li> 1889 - The top of the rock is returned to the harbor and refitted with the base.  "1620" is engraved on the surface, replacing painted numerals.
<p>
<li> 18?? - The Pilgrim Society acquires all the land adjacent to the rock and a [something-or-other] is built.
<p>
<li> 1920 - A new [something] is designed by world-famous architect McKim, Mead, and White of Boston.  During construction and renovation of the waterfront, the rock is removed.  Fragments of the original wharf are found adjacent to the site.
<p>
<li> 1921 - The highlight of the 300th anniversary celebration delayed a year because of World War I is the [something] of the new [something].  After a long journey, the rock is once again at home in the [something] near the high water mark of Plymouth Harbor.
</ul>
<p>
Well, that concludes my tour of Pilgrim Rock.  It certainly was a quick tour, luckily I walked away without any whiplash.  The rock is interesting in regard to how it was first broken, then carted around, then reunited.  As for the sight itself, the Greek temple-like enclosure is kinda nice.  Unfortunately, the star attraction of the show, Plymouth Rock, it just a big ole rock, and a broken one at that!  As a result, out of 5 possible thumbs, I can only give my tour of Plymouth Rock a 4 thumbs-up rating.
