CONCLUSION
</center>
<hr>
<p>
When the dust all settles I find myself outside in from of the USBG Conservatory.  Having seem a multitude of plants in a multitude of simulated environments, I walk away impressed by the care and feeding the USBG provides its 4,000 plant residents.  The exhibits are well thought out and vary enough to give the visitor the feeling that they've toured many parts of the world under one roof.  I like plants, so visiting the USBG was most enjoyable experience.
<p>
I rate my tour of the United Stares Botanic Garden a resounding 5 thumbs-up, a perfect rating!
