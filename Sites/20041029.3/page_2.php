Once inside, I promptly go through security.  I then talk with someone from the visitors center where I learn about a movie that's about to begin in their new auditorium.  I immediately go to the William G. McGowan Theater and settle in for the show.
<p>
Unfortunately, when they were building their new auditorium, they failed to include a popcorn concession.
<p>
The movie turns out to be a good one, enough to make up for the lack of popcorn. It describes the history of the NARA and its recent efforts to restore the Declaration of Independence and other important documents.  It proves to be a rather interesting and informative film.
