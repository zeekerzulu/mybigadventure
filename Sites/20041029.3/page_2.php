Upon arrival I find the rotunda dimly lit.  Light is a bad thing for old, historical documents.  It slowly degrades them, their print fades, and before you know it, there's nothing left to read.  The rotunda is broken down into three primary sections, one section for each of the three important documents.
<p>
Before I take my pictures, I check three times to make sure my camera isn't in flash mode.  Flash photography is strictly prohibited here.  I wonder, what would happen if I indiscriminately snapped a bunch of shots using my camera's flash?
