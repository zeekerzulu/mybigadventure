Ahhh, finally!  The <ax href="javascript:myPopup4('http://en.wikipedia.org/wiki/United_States_Declaration_of_Independence')">Declaration of Independence</a>.  This large, one page document was used by the original Thirteen Colonies to declare themselves independent from the Kingdom of Great Britian.  Written my Thomas Jefferson, the document really pissed off the British Monarchy, so much so, they sent a multitude of troops to the States in an attempt to squash the revolt.
