Devils Tower is America's first National Monument.  Rising 867 feet from its base, it was the featured "mountain" in Close Encounters of a 3rd Kind, a great science fiction movie shot back in the early 1980s.  The tower itself is an igneous intrusion.  At one point it was just hot molten rock (magma) that was encapsulated underground.  After it cooled, millions of years passed by, slowly eroding the surrounding landmass.  Overtime the tower slowly emerged from its underground hiding place to form the spectacular geological formation that we see today.
