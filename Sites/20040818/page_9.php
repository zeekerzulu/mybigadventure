Some last placards and a parting shot of the tower.
<p>
I gotta tell ya, Devils Tower was simply amazing.  Not only was it a beautiful and rare geological formation, you're also allowed to climb all over it.  How cool is that!  It's like being able to sit on the lap of the Lincoln Memorial in Washington, DC.
<p>
Hands down, I rate my tour of Devils Tower National Monument a solid 10 out of 10.
