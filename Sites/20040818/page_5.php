<p>
Looking up from my stalled position, the tower loomed over me.  It was impressive.  There are two rock climbers up on the rock face, they are the tiny specs that you may or may not see.
<p>
At this point I had two options.  Either climb down the boulder field and walk the 1.3 mile paved trail with the masses or strike out on my own and circumnavigate the tower via the boulder field.  Since I love to boulder, I chose the second option.
