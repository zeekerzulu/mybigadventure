<p>
Here's the dude who orchestrated the creation of the memorial, Gutzon Borglum.  He was invited by the South Dakota's State Historian Doane Robinson to come to South Dakota to discuss the creation of a memorial for western folk heroes such as Buffalo Bill Cody , Lewis & Clark, Chief Red Cloud in the Granite Spires along the Needles Highway.  When Borglum arrived, he convinced Robinson to change the location of the sight as well as the dedicated figures.  Borglum figured past presidents have more a national importance.  Borglum chose the 4 presidents himself, no one helped him.
<p>
Borglum chose Washington because he represented the BIRTH of our country since he was our first president.  Jefferson was chosen next and symbolized EXPANSION since he was largely responsible for the Louisiana Purchase in 1803.  Following Jefferson, Borglum chose Lincoln because he embodied the PRESERVATION of the union of states in confronting the challenges of the Civil War.  Lastly, Borglum chose Theodore Roosevelt representing DEVELOPMENT of our country.
<p>
<a href="index.php?action=Pics&name=Daily/20040821.1/P1010073.JPG"><img src="Pics/Daily/20040821.1/Small/P1010073.JPG"></a>
