Hey, it's tour time.  Ranger Gloria was prepping the crowd for an up-and-coming tour of the Presidential Trail.  This trail runs along the front of the memorial and is as close as the public can get to it.
<p>
<a href="index.php?action=Pics&name=Daily/20040821.1/P1010173.JPG"><img src="Pics/Daily/20040821.1/Small/P1010173.JPG"></a>
<p>
Before I start the tour I must pass on an interesting factoid.  The final memorial doesn't match Borglum's vision.  Borglum envisioned a grander memorial that included the chests of the 4 presidents.
<p>
<a href="index.php?action=Pics&name=Daily/20040821.1/P1010138.JPG"><img src="Pics/Daily/20040821.1/Small/P1010138.JPG"></a>
<a href="index.php?action=Pics&name=Daily/20040821.1/P1010134.JPG"><img src="Pics/Daily/20040821.1/Small/P1010134.JPG"></a>
<p>
The problem he ran into was the rock at the base of the mountain turns from Harney Peak Marble (which erodes 1 inch per 10,000 years) to this black rock (whose name I've forgotten, sorry) which is soft and will not hold a shape when carved.  In retrospect, I think that was a good thing.  I feel the memorial today packs more punch with just the heads.  You are forced to focus on their faces, and hence their character.
<p>
<a href="index.php?action=Pics&name=Daily/20040821.1/P1010152.JPG"><img src="Pics/Daily/20040821.1/Small/P1010152.JPG"></a>
<p>
