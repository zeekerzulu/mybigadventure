At the base of Mount Rushmore you will find a huge slope of rubble (talus slope) comprising 450,000 tons of rock debris.  It was formed from all the rock blasting that took place to carve out the memorial.  Approximately 90% of the carving was performed with dynamite.  Once within 12 to 18 inches of the desired contour, the carving would resort to other cutting methods such as jackhammers, etc.
<p>
