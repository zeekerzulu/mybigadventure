After getting my fill of the ski aerobatics I turn my attention to the Ski Jump Complex.  When I think of ski jumping I think of two things immediately.  First, as a kid I recall seeing the television intro to the Wild World of Sports where it showed some poor soul wiping out on the ski jump.  It was near the tail-end.  It was the part where they said ".... and the agony of defeat."  Remember that?  Second, I think of Eddie Eagle who represented I think England in the ski jump many, many Winter Olympics ago.  This guy wasn't all that good but it was his spirit and enthusiasm that really moved the crowd.  He was a regular media darling.  I remember the crowd chanting "Eddie, Eddie, Eddie" before he would jump.
