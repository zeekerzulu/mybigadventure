Down the steps and to the beach I go.  Ahhh, Lake Champlain greets me with meak, ruffling waves.  <b>VIDEO:</b> Here's a <a href="index.php?action=Videos&name=Pics/Daily/20040928/DSCN0066.MOV">video</a> (1.91 MB) of the lake lapping up on the lakeshore.  For as calm as the lake looks now, you'd think it was always a peaceful, gentle place.  But, that isn't at all the case, when looking back at its violent, storied past.
<p>
This place has played host to many a fierce battle between the Algonquin and Huron Indian Tribes.  Moving forward in time, during the American Revolution, Benedict Arnold and his men showed much courage while conducting naval warfare on the lake with the British.  While ultimately defeated, the American's efforts were rewarded by effectively delaying British's invasion attempts by a year, allowing George Washington's army to recover from disease that set in at the Battle of Valcour.
