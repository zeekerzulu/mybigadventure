And the graveyard that fits the bill is Sterling Center Cemetery.
<p>
For some time now I've found myself drawn to cemeteries.  Growing up we had a very large cemetery within eyeshot of our home.  In front of my childhood house, if you stood in the middle of Gibson Street, looked down a ways past where the street bends downhill towards Maple Avenue, you'd see a small snippet of Cary Cemetery.  Not only could I see it, my friends and I would play football and fly our kites at the end of the cemetery that was reserved for future plots.
<p>
I must say there are times when I think about dying.  I've read that "you must die well before you can live well."  Meaning you must first acknowledge and fully embrace the fact that you are doing to die before you can really appreciate your life.  Perhaps my curiosity about graveyards is part of that embrace?
