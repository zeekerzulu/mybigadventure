<p>
Well that concludes my tour of Sterling Center Cemetery.  It was a good tour.  The grounds are well kept, I didn't see any ghosts, goblins, or the living-dead, and the cops didn't hassle me, thinking I'm there to dig up bodies.  My only disappointment is the lack of special inscriptions.  I only found one and I couldn't read it!
<p>
I rate my tour of the Sterling Center Cemetery 4 thumbs-up out of a possible 5 thumbs.  Now had I toured the cemetery on Halloween night with flashlight in hand, it probably would have gotten a higher rating, assuming I had survived the night to see another day in which to write it up and give it a rating.
