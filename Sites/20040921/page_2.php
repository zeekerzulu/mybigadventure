Great!  I've finally found an inscription, BUT I CAN'T COMPLETELY READ IT!  How frustrating.  The stone is so old I can't make it out.  Not unlike the people interned here, the headstones also have a limited lifespan.
<p>
And that gets me to thinking.  What inscription will I have on my gravestone?  Well, actually that isn't going to work for me.  I don't want to be buried.  Why?  At one time I thought being cooked in an incinerator was about the worse thing they could do to my hopefully dead body, but years ago I learned otherwise.  You see, when they bury someone by today's standards, they put the body in something called a hermetically sealed coffin.
