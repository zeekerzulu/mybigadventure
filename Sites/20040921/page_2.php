I just finished reading a great book, "Tuesdays with Morrie" by Mitch Albom.  It's a quick read, I read it in a day.  But its small size is misleading.  It's a fascinating book that serves as a conduit into which the dying Morrie Schwartz can pass on his jewels of wisdom to the masses.  Morrie is in a particularly interesting position, he is dying, and that gives him a unique perspective on life.  It was from this book that I learned my previous quote of "your must die well before you can live well."
