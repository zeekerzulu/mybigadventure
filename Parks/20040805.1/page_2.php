The sign says it's okay to run and jump on the formation... well actually it says "Stay Off" but you can't 

tell that from the picture.  Yellowstone kinda drops the ball on this one.  Many of the signs I see throughout the 

Park's exhibits have light blue lettering, to simulate the color of many of their natural springs I suppose.  In any 

event, it looks nice in person but certainly not in photos.  I suspect many folks get their pictures back from the developer 

only to scratch their heads, wondering what the heck they took a picture of.  It's a shame.
