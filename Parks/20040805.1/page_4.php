<p>
"Both of these terraces display cycles of activity typical of Mammoth Hot Springs.  In 1937, Mound Terrace was called 'the 

most beautifully colored spring'.  Inactive in recent decades, its weathered travertine shows new patterns where chunks of 

the soft rock have broken or fallen.  In the late 1980s. Jupiter Terrace flowed heavily and overtook boardwalks several 

times.  It has been dry since 1992."
