After completing my second tour, I hop into the van once again and head even further out of Lake Placid to the Verizon Sports Complex.  This is where you'll find the multi-purpose facility used for bobsled, luge and skeleton.
<p>
Click <a href="index.php?action=Sites&date=20040926.3&page=1">here</a> for more detail (and pictures) on my tour of the Verizon Sports Complex.
<p>
After my final tour ends I find myself bloated with everything Olympic.  With plenty of fascinating Olympic history swimming around in my head to ponder, I drive back to the campground.  After arriving I settle in for the night, working a bit on my travel writing.  Sadly, tomorrow would be my last day in the Adirondacks.  Before going to bed I draw up plans to tour Whiteface Mountain via the Veteran's Memorial Highway.
