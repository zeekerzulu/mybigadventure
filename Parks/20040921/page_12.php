<b>Saturday, September 24, 2004</b>
<hr>
<p>
I wake with the desire to tour Lake Placid, a small village with a big history.  Lake Placid is best know for hosting the 1932 and 1980 Winter Olympics.
<p> 
<a href="index.php?action=Panoramas&name=Daily/20040924/Panorama/1.mov"><img class='FullPanorama' src="Pics/Daily/20040924/Panorama/Small/1.jpg"></a>
<p>
With plan in hand I jump in the van and drive out to Lake Placid, located just 10 miles from the campground.  Passing through the northeast outskirts of Lake Placid, I notice Kilburn, Sentinel, and Stewart Mountains are alive with colors.  Just look at those reds.
<p>
