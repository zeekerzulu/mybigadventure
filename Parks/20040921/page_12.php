<p>
I arrive for my tour.  The village sports a single, main drag where most of the businesses cater to the tourist crowd.  Home to a portion of the Olypmic Winter Complex, the in-town facility boasts 2 ice arenas, a museum, and administrative offices.  Contrary to its name, located next to Lake Placid you'll find serene Mirror Lake.  The body of water, Lake Placid, is located about a mile north of village center.
<p>
Click <a href="index.php?action=Stats&stat=Communities&date=20040924&page=6">here</a> for more detail (and pictures) of my tour of the village of Lake Placid.
<p>
After the tour I grab dinner then hop over to a brew pub for a beer.  When evening arrives I head back to the campground and settle in for the night.  My knee is feeling much better now.  Hopefully it'll be healthy enough to stand the test of biking down Whiteface Mountain, tomorrow's planned venue.
<p>
<b>Sunday, September 25, 2004</b>
<p>
The morning greets me with a hazy, overcast smile.  The weather looks like it could start frowning with rain at any moment, but I decide to stick with my plan of biking Whiteface Mountain anyway.  My knee is feeling much better today, certainly well enough to challenge the mountain.
<p>
<a href="index.php?action=Pics&name=Daily/20040925.1/DSCN0271.JPG"><img src="Pics/Daily/20040925.1/Small/DSCN0271.jpg"></a>
<p>
After a short drive I arrive at the base of the mountain.  Whiteface Mountain, standing at 4,867 feet, is the 5th highest peak in Adirondack State Park.  Years ago they constructed the Whiteface Mountain Ski Area which boasts a multitude of great ski runs that start as high as 4,416 feet, providing a maximum vertical drop of 3216 feet, which is pretty awesome.
