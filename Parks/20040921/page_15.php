Whiteface Mountain is a pretty place.  As I ride down I stop periodically to soak in the views and to reestablish courage to continue on with the ride.  I crash many, many times.  And I'm not talking about falling over sideways, rather, I'm talking about going over the handlebars!  Really serious life-threatening stuff.
<p>
Fortunately, I complete my biking adventure with only minor cuts and scrapes.  When the dust finally settles I end up riding down the mountainside 4 times, probably covering 10 miles in the process.  Not bad for a first-timer.
<p>
After the ride I mosey on back to the campground to shower up.  I then drive out to Lake Placid for some food where I end up settling for Mexican.  After dinner I trek back to the campground and settle in for the evening.  It was a good day, I had a great time on the bike and I didn't hurt myself.  Life is good!
<p>
Tomorrow I'll visit most of the Winter Olympic Complex.  The complex I'll be touring includes 2 skating arenas, an outdoor speed skating rink, two towering ski jumps, a freestyle skiing training center, and a multi-purpose bobsled, luge and skeleton facility.
