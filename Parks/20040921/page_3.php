On my way I pass by Raquette Pond.  Funny, it looks more like a lake than a pond to me.  It's about 2.5 miles long and 1 mile wide.  Yes, it's definitely a lake. Who ever named it must have lived next to one of America's Great Lakes, causing this body of water to look puny in comparison, hence the "pond" designation?
