<b>Conclusion</b>
<hr>
<p>
Eventually all good things must come to an end.  After spending 7 wonderful days in the Adirondacks, the time for me to push on eastward to Acadia National Park has arrived.  My stay was an active, scenic, and relaxing experience.  This will mark my third visit to the Adirondacks and by far the best.  I rate my tour of the Adirondacks an overwhelmingly solid 4.5 thumbs-up out of a possible 5 thumbs.
