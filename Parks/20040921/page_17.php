<b>Monday, September 27, 2004</b>
<hr>
<p>
Today is my last day in the Adirondacks.  I'll cap off my final day with a tour of Whiteface Mountain.  Getting to the top will require a steep drive up Veteran's Memorial Highway, followed by a short hike to the top.
<p>
<a href="index.php?action=Pics&name=Daily/20040927/DSCN0377.JPG"><img src="Pics/Daily/20040927/Small/DSCN0377.jpg"></a>
<p>
I break camp then head out to the mountain.  The road to the top, Veteran's Memorial Highway, promises to be quite an engineering feat, rising over 2,300 feet in just 5 short miles.  Now, that's pretty steep, even by today's standards.
<p>
After 4 years and $1,250,000, the road was officially opened on July 20th, 1935.  Shortly thereafter, President Roosevelt made a trip up the mountain and in a formal ceremony dedicated the Highway as a memorial to the New York State Veterans of the Great War (WWI).  In 1985 the Highway was rededicated the Whiteface Memorial Highway to veterans of all wars.
<p>
The tour posted here will just cover the scenic highlights of the mountain. Click <a href="index.php?action=Stats&stat=Sites&date=20040927&page=14">here</a> for a more thorough write-up of my mountain top adventure as covered in the sights section of my website. 
<p>
<a href="index.php?action=Pics&name=Daily/20040927/DSCN0659.JPG"><img src="Pics/Daily/20040927/Small/DSCN0659.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20040927/DSCN0660.JPG"><img src="Pics/Daily/20040927/Small/DSCN0660.jpg"></a>
<p>
After turning onto the Veteran's Memorial Highway I drive a little ways before encountering this toll house.  I'm a little surprised when I'm told there's an entrance fee.  It's $9.00, yowza!  Hope there's free food at the top!
<p>
<a href="index.php?action=Pics&name=Daily/20040927/DSCN0413.JPG"><img src="Pics/Daily/20040927/Small/DSCN0413.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20040927/DSCN0414.JPG"><img src="Pics/Daily/20040927/Small/DSCN0414.jpg"></a>
<p>
After paying my admission I drive up the mountainside.  The drive proves to be a very steep one, I certainly don't want to lose my brakes on my way back down. Nearing the end of my drive I see in the distance a weather station and a shelter house atop the mountain.
<p>
<a href="index.php?action=Pics&name=Daily/20040927/DSCN0415.JPG"><img src="Pics/Daily/20040927/Small/DSCN0415.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20040927/DSCN0430.JPG"><img src="Pics/Daily/20040927/Small/DSCN0430.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20040927/DSCN0431.JPG"><img src="Pics/Daily/20040927/Small/DSCN0431.jpg"></a>
<p>
Whiteface Castle sits at the end of the road.  From there tourists can either walk up a stone stairway or take an elevator to the top of the mountain.
