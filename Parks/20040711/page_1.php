As I began my hike to the photoshoot location, I notice it is here the <a name='valid_link' href="javascript:myPopup2('http://www.pcta.org/')">Pacific Crest Trail</a> passes by.  That's the trail folks use to hike from the Mexican border to the Canadian border.  It's a pretty impressive trail. The 2,650-mile long trail passes through California, Oregon, and Washington.  It takes a many months to hike, some people have to split the hike up over 2 years or more just to complete it.
