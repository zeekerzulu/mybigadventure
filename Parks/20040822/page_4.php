I hit some pretty bad washboarding in the road.  To make matters more interesting, it's all downhill, so I ride as fast as I can and in the process get a pretty good body massage.  Then, suddenly out of nowhere, a huge snow storm strikes!  I'm completely taken off-guard as I slip and slide to maintain an upright position on the bike.  The temperature is now hovering around 20 degrees and I find myself entering into the early stages of hypothermia.  I'm in the middle of nowhere and I start to worry if I can make it back... to... the... van... I... am... so... cold... right... now...
<p>
Okay, okay, if truth be told, I actually manage to break my digital camera.  All the jiggling, jogging, and jarring jams my camera's shutter wide open.  As a result, subsequent pictures are now all hopelessly overexposed.  Sorry, no flash snow storm, no story of me almost freezing to death, just a broken camera.  How anti-climactic is that?
<p>
Sans pictures, the balance of my day is spent completing my bike ride.  I continue my ride to Sage Creek Campground, the ride's mid-point, then backtrack to the van.  Following my reunion with the van the evening arrives so I drive back to Sage Creek Campground and settle in for the night.  The evening orchestrates a whopper of a thunderstorm.  Supported by a torrential downpour accompaniment, surely this wet performance rivaled the one experienced by Noah and his faithful Ark.
