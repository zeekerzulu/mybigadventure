<p>
From the Visitor Center, I make my way up to the top of the Appalachian Mountains.  It'll be from there, at the ridgeline, that I'll find the hiking I've been looking forward to for the past few days.  It's proving to be a really steep climb, almost 5,000 feet in a little under 15 miles.  Apart from the popping in my ears due to the elevation gain, the sharp switchbacks in the road are also a good indicator that it's all about up, up, and more up in these parts.
<p>
This ascent reminds me of the time, earlier in my trip, when touring Glacier National Park in Montana, when I put <a href="index.php?action=Stats&stat=Biking&date=20040728&page=9">rubber to the road</a> on my road bike and climbed a dizzying 3,000 feet in about 10 miles.  More than 3 months later, I'm feeling rather out of shape now, so I'm rather glad to be driving the van and not riding my bike up this mountainside.
<p>
<a href="index.php?action=Pics&name=Daily/20041107.1/DSCN0221.jpg"><img src="Pics/Daily/20041107.1/Small/DSCN0221.jpg"></a>
<p>
Finally, I reach the ridgeline near Right Hand Gap.  There's a parking lot here, and from the looks of it, there are a lot of folks out and about today.  Great Smoky Mountains National Park hosts more than 9,000,000 visitors a year.  I'd hate to experience first-hand just how crowded this parking lot gets during the peak summer months.
<p>
I hop out of the van in preparation for my first unobstructed view of the Great Smokies.  Unfortunately, it's my understanding that the Smokies are becoming more and more smoky as time goes by.  Pollution has adversely affected the park, so much so, that you can find it on the 2004 list of America's <a href="javascript:myPopup5('http://www.npca.org/media_center/smokies.asp')">Ten Most Endangered National Parks</a>.
