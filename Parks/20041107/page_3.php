Indigenous to the area, the Cherokee Indians call this place <i>Shaconage</I>.  Literally meaning "land of blue smoke", a natural bluish haze sometimes manifests after rainstorms.  The haze turns thickest on calm, humid days.  The geography of the Smokies works to its disadvantage, however.  Pollution also contributes to the haze; the area's heightened, folding terrain slows the air currents and effectively trap the bad air.  The sequestered pollution decreasing visibility and adversely affects the region's plant life.
