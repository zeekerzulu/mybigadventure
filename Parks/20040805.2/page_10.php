The last exhibit of my tour is Emerald Spring.  "The magnificent color of Emerald Spring comes from the water 

reflecting blue wavelengths of sunlight combined with the yellow of the sulfur-coated pool.  The water in this 27-foot deep 

pool is so hot, close to boiling, that only the most heat-tolerant thermopiles can survive."
<p>
