At the trailhead on my way back to the van I notice these three vending machines.  It appears <a href="index.php?action=Stats&stat=Oddities&date=20040805&page=15">Coca-Cola</a> has diversified their product-line to include both water and buffalo milk.
<p>
In summary, my tour of the Norris Geyser Basin was both fun and colorful.  Its amazing to me all the different colors one can see here, all 

naturally occurring.  Additionally, some of the spouting geysers were nice as well.
<p>
I give my tour of the Norris Geyser Basin a solid 5 thumbs-up, a perfect rating.
