Here's a view of the Porcelain Basin.  "Porcelain Terrace Overlook provides an overview of this delicate and dangerous 

basin.  The ground here actually pulsates from the pressure of steam and boiling water beneath the surface.  Its features 

appear and disappear more often than any other hydrothermal area.  No one knows for sure why.  Even so, some springs and 

