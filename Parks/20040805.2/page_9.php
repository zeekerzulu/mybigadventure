Echinus Geyser and its blood-like entrails. "Echinus Geyser is named for its deposits, which look like the spines of 

echinoderms such as sea urchins or sea stars.  Once very predictable, its eruptions now vary from 1 hour to 4 days.  Even so, 

an eruption of Echinus is worth the wait. [Wait 4 days?  It'd better spit out gold coins if I gotta wait that long!] You can 

observe classic geyser behavior as the pool slowly fills and begins to boil.  Look for the eruption to begin from the back of 

the pool and then watch the show.  Echinus erupts with bursts that reach higher than the upper viewing platforms and send 

waves into Tantalus Creek.  Its performance lasts 3-5 minutes.  Echinus is the largest acid-water geyser known; its waters 

are almost acidic as vinegar (pH 3.3-3.6)."
