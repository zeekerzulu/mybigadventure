"Months and years pass between the eruptions of Steamboat Geyser.  The world's tallest active geyser, Steamboat throws water 

more than 300 feet high, showering viewers and drenching the walkway,  For hours following its rare 3-40 minute major 

eruptions, Steamboat thunders with stream.  As befitting such an awesome event, full eruptions are entirely unpredictable.  

More commonly, Steamboat ejects water in frequent bursts of 10 to 40 feet."
