Ahhh, we see a few small stalactites overhead.  Come to think of it, these are the first we've seen so far on the tour.  Does this mean we'll soon encounter more?  I certainly hope so.
<p>
Stalactites are interesting bunch.  Created by dripping water, with each drop, a small amount of calcium carbonate is left behind.  Over time, the myriad deposits form a stalactite that slowly grows downward from the ceiling.  The drop of water, however, may still contain a portion of sediment when it is released into the air.  The drop hits the ground, and with a splat, deposits the remaining sediment which, over time, creates a stalagmite.  Stalagmites are usually broader than their ceiling-clinging neighbors because the action of the splashing water scatters the sediment across a wider area.  If a stalactite and a stalagmite join together, a formation called a column is formed.
