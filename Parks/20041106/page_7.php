The second and third photos are of a really deep pit.  If a monster was to ever live in this cave, this would certainly be the place.  I wonder, does anything live in this cave?  I haven't see a bit of life anywhere so far on the tour.  Further research tells me that <a href="javascript:myPopup10('http://www.mammoth.cave.national-park.com/info.htm#lif')">200 animal species</a> actually live in the cave.  According to the scientists, there are 4 classifications of life.
<p>
<ul>
<li> <b>Troglobite</b> - Translating to "Cave Dweller", such animals in this group include eyeless cave shrimp, flatworms, isopods, amphipods, cave beetles, and cave crayfish.  These creatures can spend their entire lifetimes in the cave if there is sufficient food.
<li> <b>Troglophile</b> - Literally means "Cave Lover."  Representatives in this group can only live in the dark, cool, and moist places within the cave.  Animals include segmented worms, snails, spiders, mites, millipedes, and cave crickets.
<li> <b>Trogloxene</b> - Translates to "Cave Guest."  These take-it-or-leave-it cave dwellers include bats, pack rats, flies, and gnats.
<li> <b>Incidentals</b> - Creatures which occasionally wander or stumble into the cave.  Animals include raccoons, frogs, and yes, humans.
</ul>
