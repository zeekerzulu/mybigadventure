Out to the surface we pop.  After 4 hours of being underground, it's good to be back in the world of light and fresh air.  We board the bus and are whisked back to the Visitor Center.  At the Visitor Center Ernesta and I part company.  I must say, I really enjoyed her company on the tour.  With my wishing her farewell and good luck with the rest of her travels, I complete my tour of Mammoth Cave National Park.
<p>
What can I say, the tour was simply spectacular!  The tour guide was top-notch, the sights were awe-inspiring, the tour was well planned and marked, and I didn't get bored until near the end of the tour, only to be rescued by the best formations on the route.
<p>
I give my tour of Mammoth Cave National Park 5 thumbs-up, a perfect rating!
