<p>
Our tour guide points out this human artifact, the broken fragments of a bottle from the 1800s.  This is an example of a relatively recent artifact.  The oldest date back 4,000 years ago when the visitors were <a href="javascript:myPopup1('http://www.mammoth.cave.national-park.com/info.htm#arc')">aboriginal people</a> who discovered about 10 miles of the caves.  They came primarily to collect crystals and salt.  I wonder, how did they light their way?
<p>
