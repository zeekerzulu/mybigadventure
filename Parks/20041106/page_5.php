<p>
The cave is slowly widening.  This is about its widest point so far.
<p>
<a href="index.php?action=Pics&name=Daily/20041106/DSCN0518.jpg"><img src="Pics/Daily/20041106/Small/DSCN0518.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041106/DSCN0519.jpg"><img src="Pics/Daily/20041106/Small/DSCN0519.jpg"></a>
<p>
The tour group finally reaches the <a href="index.php?action=zStats&stat=Oddities&date=20041006&page=46">Snowball Dining Room</a>.  Located 267-feet below the surface, here we'll grab lunch before continuing on with our tour.  This is the tour's bail-out point for the weak and weary.  Those who change their minds and wish not to continue on with the rest of the tour (still 3 miles to go) can take the cave's only service elevator to the surface.
<p>
Unfortunately, the tour up to this point has been flat and easy, so folks may very well overestimate their stamina and continue on with the rest of the tour which turns harder really quickly.  There's no backtracking to the service elevator after continuing on with the tour because, to conserve electricity, the lights only stay on with the passage of the tours.
