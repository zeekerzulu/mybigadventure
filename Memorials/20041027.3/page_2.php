Lincoln is known as the great emancipator, the enduring catalyst behind the movement to eliminate slavery from the Union.  How appropriate that, at the top of the steps, I find this marker indicating the place where Martin Luther King, Jr. delivered his famous <i><a href="javascript:myPopup4('http://www.americanrhetoric.com/speeches/Ihaveadream.htm')">I Have a Dream</a></I> speech.  It's a little hard to read, it says:
<p>
<center>
I HAVE A DREAM<br>
Martin Luther King, Jr.<br>
The March on Washington<br>
Jobs and Freedom<br>
August 28, 1963
</center>
<p>
Under a cloudless sky on that fateful day, Martin Luther King, Jr. gave powerful <a href="javascript:myPopup5('http://www.americanrhetoric.com/Streamingfiles/mlkihaveadream.htm')">speech</a> that spoke of many things; the current state of racial discrimination, a peaceful call-to-arms, the forefathers guarantees of freedoms for all, and the hopes and dreams for future racial equality.  I really love this speech, its content and lyrical qualities make it one of the most beloved American speeches.  In my opinion, it ranks right up there with Lincoln's Gettysburg Address.  A quarter of a million people, one-fifth of them white, attended the rally.
<p>
Interestingly enough, King had not planned to deliver his <i>I Have a Dream</I> speech.  Rather, he planned on using a much shorter speech whose content focused primarily on the sufferings of African Americans in their ongoing fight for racial equality.  When King's turn arrived to speak, prompted by gospel singer Mahalia Jackson who shouted "Tell them about your dream, Martin! Tell them about the dream!", King immediately shifted gears.  Drawing upon a number of his past talks, King delivered the most important speech of his life.  Thank you Mahalia Jackson for prodding Martin into action.
