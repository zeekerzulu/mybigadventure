Reads the inscription behind the statue: 
"In this temple, as in the hearts of the people for whom he saved the Union, the memory of Abraham Lincoln is enshrined forever."  Not surprisingly, the statue of Lincoln is the heart and soul of the Memorial.  A compilation of 28 pieces of White Georgia marble, the statue measures 19 feet high by 19 feet wide.  A 10 foot pedestal raises Lincoln, effectively giving him a larger presence within the Memorial's interior.
