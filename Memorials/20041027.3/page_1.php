In the distance, across the <ax href="javascript:myPopup3('http://en.wikipedia.org/wiki/Reflecting_Pool')">Reflecting Pool</a>, I see the Lincoln Memorial.  The Reflecting Pool is actually part of the Lincoln Memorial.  Funny, I used to think it was part of the <a href="index.php?action=Stats&stat=Monuments&date=20041027&page=6">Washington Monument</a> because it does such a bang-up job in reflecting the 555-foot tall obelisk.  Measuring 2,029 feet long and 167 feet wide, surprisingly the pool is fairly shallow; 18 inches on the sides, 30 inches in the center.  Approximately 6,750,000 gallons of water fills the pool.
