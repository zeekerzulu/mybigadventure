Standing within the interior now, I look to my left and see 4 tall columns.  Behind them I find a large inscription of <i><a href="javascript:myPopup7('http://showcase.netins.net/web/creative/lincoln/speeches/gettysburg.htm')">The Gettysburg Address</a></I>, probably Lincoln's most famous speech.
