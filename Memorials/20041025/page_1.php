Just west of the U.S. Capital Building I arrive at the <a href="javascript:myPopup3('http://www.henrymerwinshrady.com/Book_Desc01.htm')">Ulysses S. Grant Memorial</a>.  Unfortunately, I drop the ball and fail to take a decent picture showing the entire Memorial.  Oops, I'm such an amateur.  Click <a href="javascript:myPopup4('https://en.wikipedia.org/wiki/Ulysses_S._Grant_Memorial#/media/File:US_Capitol_and_Grant_Memorial.JPG')">here</a> to get a complete picture of it.  As you can see, it's rather expansive, measuring 252 feet by 70 feet.  At the center of the Memorial is General Grant atop his favorite horse Cincinnati, to his right is <i>The Cavalry Group</I>, and to the left is <i>The Artillery Group</I>.
<p>
This no-holds-barred Memorial strictly shows the horrors of battle, there's absolutely no mention of lofty ideals or principles.  There are no plaques parading Peace, Justice, Hope, Rebirth, or whatever.  What we have here is Hell on Earth, illustrated in bronze on marble.  The two major groups are positioned to run into the center of the Memorial.  In doing so, the visitor isn't an idle sightseer, rather, they are at the center of the battle, an active participant in the Civil War maelstrom.
