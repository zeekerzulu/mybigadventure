Let's first take a look at the Memorial's Centerpiece, <a href="javascript:myPopup5('http://en.wikipedia.org/wiki/Ulysses_S._Grant')">Ulysses S. Grant</a>.  Grant, the 18th President of the United States (serving two terms, 1869-77), had a brilliant military career, attaining the highest rank in the U.S. Army as a 4-Star General.  In commemoration of his exemplary military service, the memorial reflects the struggles of the Civil War and his strong leadership during those troubled times.  The second largest equestrian statue in the world, Grant and his horse, Cincinnati, tower 40 feet into the air.
<p>
During battle, as illustrated by the Memorial, we see General Grant and his trusty horse.  He is calm and composed, as reportedly the nature of his demeanor; supposedly he was once seen whittling on a stick while watching the warfront play out before him.  As you can see, Cincinnati has both front legs planted firmly on the ground, meaning Grant was neither killed (both legs risen) nor injured (one leg risen) in battle.  Rather, he died of throat cancer in 1885 at the age of 63 after his run as President and partaking on two year world tour.
