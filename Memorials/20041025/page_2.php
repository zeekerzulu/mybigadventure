<p>
At the base of the centerpiece pedestal you'll find two panels, both depict <i>The Infantry Group</I>.  These panels are the only part of the Memorial not created by the primary artist, <a href="javascript:myPopup4('http://www.henrymerwinshrady.com/introHMS.htm')">Henry Merwin Shrady</a>.  Shrady died in 1922, these panels were erected in 1924.
