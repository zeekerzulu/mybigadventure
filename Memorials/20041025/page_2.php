<p>
Rushing headlong into battle, six horses and six men compose <i>The Cavalry Group</I>.  In preparation for creating this masterpiece, artist Shrady spent a number of days at West Point studying staged cavalry charges, fervently sketching what he saw in the hopes to capture, both on paper and in bronze, the battle charge reenactment.  I think Shrady did well in this endeavor.  The statue of the lead horse was modelled nine times before Shrady was completely satisfied.  Apparently it is on this horse that you can find his fingerprints.
