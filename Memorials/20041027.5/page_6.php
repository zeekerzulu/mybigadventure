This wonderful sculpture ensemble, created by artist <a href="javascript:myPopup2('http://www.nps.gov/fdrm/memorial/estern.htm')">Neil Estern</a>, is the dominate element in this corner of the room.  FDR looks confident and strong as he sits there, he is ready to tackle any and all obstacles that come his way.  The statue does well to memorialized him as the fearless leader of that troubled era.
