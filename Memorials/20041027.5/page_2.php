There's not much in this room to look at.  It's a little disappointing, actually.  Aside from a few quotes, a small bas-relief panel, and a waterfall, there isn't much else that captures my attention.
<p>
FDR's first term was an important one, however. It was the term where he buoyed the American psyche by laying out a grand plan to aid the ailing Nation.  At the time, America was in the throes of the <a href="javascript:myPopup5('http://en.wikipedia.org/wiki/The_Great_Depression')">Great Depression</a>.  Things were really quite bad, so bad that a few months before FDR took office, there was talk that the country was on the brink of anarchy.  Some believed the government was well on its way to collapsing because a coup d'etats was brewing.  Wow!  I never knew things were that bad.
<p>
Inscribed on one of the stone walls in front of me is the famous quote: "The only thing we have to fear is fear itself."  FDR realized he had to quickly dispel the prevailing sense of hopelessness that had enveloped the Nation and inject new confidence into Americans, to give them the strength necessary to overcome their hardships.  Under the quote is a small bas-relief panel named <i>The First Inaugural</I>.  Created by artist <a href="javascript:myPopup6('http://www.nps.gov/fdrm/memorial/graham.htm')">Robert Graham</a>, the panel depicts FDR riding in a car from his first inauguration, smiling and waiving at the gathered crowds, shining a light of hope into the dark recesses of a distressed Nation.
<p>
"I pledge you, I pledge myself, to a new deal for the American people.", says another inscription.  FDR's <a href="javascript:myPopup7('http://en.wikipedia.org/wiki/New_Deal')">New Deal</a> was a plan to get American back on its feet.  The general thrust of the plan was to stabilize the economy through government intervention (stock market reform, unemployment aid, bailing out the sinking banking system).
<p>
The other two quotes are: "Among American citizens there should be no forgotten men and no forgotten races." and "No country, however rich, can afford the waste of its human resources.  Demoralization caused by vast unemployment is our greatest extravagance.  Morally, it is the greatest menace to our social order."
