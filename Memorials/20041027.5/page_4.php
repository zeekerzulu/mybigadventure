Within eyeshot I see a wide waterfall.  What could this be all about?  The New Deal established many public work projects, one of the most innovative being the creation of the <a href="javascript:myPopup9('http://www.tva.gov/abouttva/history.htm')">Tennessee Valley Authority</a>.  New sources of electrical power were created and efficient distribution systems were put into place.  In addition to providing more electricity to industry to help create needed jobs, electrical service was made available in places where in the past no service was provided.
<p>
More inscriptions, more inspiring quotes: "I propose to create a civilian conservation corps to be used in simple work... More important, however, than the material gains will be the moral and spiritual value of such work." -- "It is time to extend planning to a wider field, in this instance comprehending in one great project many states directly concerned with the basin of one of our greatest rivers."
