Ahhh, FDR's fireside chats.  Becoming a regular staple in his second term, FDR's national radio addresses become one of his trademarks, an excellent way of connecting with the public and providing up to date, easily digestible information on the progress of improving the economy, and hence, the life of the ordinary American citizen.  This sculpture, <i>The Fireside Chat</I>, was also created by artist George Segal.
