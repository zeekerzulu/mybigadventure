The problem he ran into was the rock at the base of the mountain transitions from Harney Peak Marble (which erodes 1 inch per 10,000 years) to this black rock (whose name I've forgotten, sorry) which is soft and will not hold a shape when carved.  In retrospect, I think that was a good thing.  I feel the memorial packs more punch with just the heads.  The viewer is forced to focus on their faces, and hence their character.
