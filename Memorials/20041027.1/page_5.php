I continue around to the Pacific pavilion.  On the way I take a closer look at the pillars, each holds an oak and wheat bronze wreath as well as a sculpted bronze rope.  The wreaths represent America's bountiful resources and the twisted rope represents the bonding of the States that form the Union.
