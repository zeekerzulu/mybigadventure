<p>
Here's the Freedom Wall, it holds 4,000 golden 5-point stars.  Each star represents 100 U.S. military personnel who gave their lives during the war effort.  Looking at all the stars and adding 100 to each, the resulting number is quite staggering!  Even the 4,000 stars, all by themselves, look rather impossible to count.
