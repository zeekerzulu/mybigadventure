I arrive at the Memorial's main entrance.  Immediately, I'm served up with this large stone tablet containing the Memorial's epilogue.  In the distance, I see the large Rainbow Pool with its spurting, opposing fountains.
<p>
The most important ideal the Memorial wishes to convey is the concept of American national unity.  Without the cohesiveness of America in its war efforts against the Axis Powers, the world certainly would have evolved into a different place, one that I'm pretty sure would be far worse than the lot we find ourselves in today.
