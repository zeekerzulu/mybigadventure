<a href="javascript:myPopup2('http://www.vvmf.org//index.cfm?SectionID=110&Wall_Id_No=1033.0')">John H. Anderson, Jr.</a> is the first inscribed name I find on the memorial.  John, from Wellsville, PA, had a ranking of Private First Class (PFC) and served in the Army.  He died at the age of 20 on May, 25 1968 in the province of Thua Thien, South Vietnam.
<p>
<ul>
<li>9 personnel from Wellsville, PA died or are MIA as a result of the Vietnam War.
<li>3,150 personnel from Pennsylvania died or are MIA as a result of the Vietnam War.
<li>14,998 personnel having a ranking of PFC died or are MIA as a result of the Vietnam War.
<li>38,225 personnel in the Army died or are MIA as a result of the Vietnam War.
<li>89 personnel on May, 25 1968 died or are MIA as a result of the Vietnam War.
<li>4,278 personnel died or are MIA in the province of Thua Thien as a result of the Vietnam War.
<li>55,642 personnel died or are MIA in South Vietman as a result of the Vietnam War.
</ul>
<p>
Lord, this is just horrible!  Tears cloud my eyes and roll down my face as I investigate these grim facts and figures.  The statistics, however, only scratch the surface of the horrific tragedies that took place so many years ago.  The indescribable horrors of war.  I was spared that experience, having been born too late in 1964.  I may not have served in Vietnam, but, my heart goes out to all who had to fight the fight, and especially to those who gave the ultimate sacrifice for their country, regardless of the politics behind the war.  Death is death and you cannot come back, no matter what the circumstances are that bring it about.
