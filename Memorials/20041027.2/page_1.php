Near the entrance of the Vietnam Veterans Memorial I encounter the <a href="javascript:myPopup7('http://www.nps.gov/vive/memorial/servicemen.htm')">Three Servicemen Statue</a>.  Commemorating the American soldiers who put their lives in harms way, the statue (and flagpole) serves as a bridge of compromise.  When the Memorial Wall was opened in 1982, many believed the memorial was too gloomy, macabre, and morose.  The monument's black granite and below ground level placement signified shame and non-acceptance of the war.  This division in opinion wasn't just a general public issue.  Sadly enough, it was also a growing issue amongst the veterans themselves.  The monument wasn't healing old wounds, it was reopening them.
<p>
As a way to bring both sides together, artist <a href="javascript:myPopup8('http://www.collectionprivee.com/Hart.htm')">Fredrick Hart</a> was commissioned to create a statue set that would capture the honor, bravery, and spirit of the American soldiers.  In 1984, the statue set was erected to help heal the nation's wounds.  Milt Copulos, a former opponent to the memorial design, admitted in the end that "the wall of the memorial could have been a wall between us," but instead it "became a bridge."
