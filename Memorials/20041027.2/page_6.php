I finally reach the end of the Memorial where I find <a href="javascript:myPopup3('http://www.vvmf.org//index.cfm?SectionID=110&Wall_Id_No=470.0')">Jessie C. Alba</a>, the last inscription on the Wall.  Jessie was a Sargent (SGT) in the Army.  He was from Port Lavaca, TX and died at the age of 20 on May 25, 1968 in Thua Thien, South Vietnam.
<p>
<a href="index.php?action=Pics&name=Daily/20041027/DSCN0529.jpg"><img src="Pics/Daily/20041027/Small/DSCN0529.jpg"></a>
<p>
I finally complete my tour of the Vietnam Veterans Memorial.  A quick look back refills me with great sadness, there are just some many names here, almost too many to comprehend.  How do I feel about the Memorial?  Yes, the controversial Memorial is somber, but I think it is respectful of those it stands in memoriam to.
<p>
I'm so glad America has this Memorial.  With its bumpy beginnings now behind it, this unique Memorial has certainly gone far in helping America reconcile its feelings about the Vietnam War.  Thank you <a href="javascript:myPopup4('http://www.vvmf.org/index.cfm?sectionID=46')">Jan Scruggs</a> for having the foresight to get this Memorial started.  I rate my tour of the Vietnam Veterans Memorial a solid and respectful 4.5 thumbs-up!
