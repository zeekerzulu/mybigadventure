My climb up Saddle Pass Trail takes me from the lower prairie to the upper prairie.  Here's a picture of the upper prairie and off in the distance is a feature called a "secondary table."  This feature is a relatively young formation and was created by erosional sediment that washed here perhaps as early as 10,000 years ago.
The table is held in place by all the vegetation growing on its top.  The prairie grasses can have root systems that extend up to 10 feet below the surface, effectively holding the table in place as it magically "rises" out of the ground by the surrounding erosional forces.
<p>
<a href="index.php?action=Pics&name=Daily/20040824/24.JPG"><img src="Pics/Daily/20040824/Small/24.JPG"></a>
<p>
I decide to climb the secondary table since it is only 20 feet high.  I want to see up close what the vegetation looks like.  This picture is taken from on top of the table.  I'm careful not to step too close to the edge since it looks like it could crumble under my feet.  The vegetation consistes of prairie grass and cactus.
<p>
I wonder, am I the first person to ever set foot on this piece of real-estate?  If you think about it, how often do you step where no one has ever stepped before?  It probably isn't often and if you never travel to remote places, it's probably never.
