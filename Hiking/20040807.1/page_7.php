Okay, I'll come clean. Actually, there's no bear, it is <a href="index.php?action=Stats&stat=People&date=20040807.1&page=10">Dave & Jana</a> who take my picture, a young couple from Regina in Saskatchewan, Canada, who are passing through Yellowstone on their way to Utah.  Operating on very little sleep because of their late night arrival, they decide to go on a hike anyway.  I really admire their spirit of adventure.
<p>
All three of us simultaneously scratch our collective heads, wondering where the trail has gone.  The trail is configured in a loop and according to the trail information we have, we need to head down the mountain's southern face, then turn due east for a steep, downward descent.
<p>
