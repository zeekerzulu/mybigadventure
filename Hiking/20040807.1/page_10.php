We eventually were successful in picking up the trail.  As we made our way down to the trailhead, Dave & Jana talked about their plans to work abroad teaching.  Their passion for traveling "on-the-cheap" was fueling their willingness to work in most parts of the world.  I asked them where they would like to eventually settle down and they both agreed, Canada was their true home.
<p>
We completed the trail and walked to the parking lot.  I gave them both the nickel tour of the van and gave them my travel business card.  I hope they send me an email when they get back home.  I'd like to find out where they eventually land a job.
<p>
My hike of Sepulcher Mountain was a good experience, I enjoyed seeing first hand the regeneration of the forest as I passed through the burn zones on my way up to the mountain top.  The hike was a good mix of open meadow and wilderness, it was difficult enough to work up a good, lathered sweat, and the views from the top were top notch.  And to round things off, I met Dave & Jana, who accompanied me on the hike down, during which we all shared in interesting conversation.
<p>
I rate my hike of Sepulcher Mountain a solid 9 out of a 10.
