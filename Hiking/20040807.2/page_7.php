Brian and I then head down the mountainside and back to the trailhead.  During our descent we happen upon a bighorn sheep, who is browsing and completely unafraid of us as we pass him by.
<p>
After reaching the parking lot, Brian and I exchanged contact information.  He tells me he plans to be back home in Portland, Maine by mid-September.  I will be passing through his neck of the woods when I visit Acadia National Park.  I'll certainly make a point to look him up if I arrive after his planned return.
<p>
In summary the hike up Bunsen Peak provided great views and a good workout.  The only negative was the ungainly radio tower equipment atop the mountain.
<p>
I give my hike to Bunsen Peak 4 thumbs-up out of a possible 5 thumbs.
