This little artful series discusses the importance of proper outdoor stewardship.  In a nutshell, stay on the trails, don't step on the plants (unless they're dandelions of course), care guidelines of your wastes (bodily or otherwise), don't plunk down your tent on fragile environments (delicate meadows, shorelines, alpine tundra, grandma's flower garden), control your pet (they don't say you have to leash your animal so all bets are off on that one), and don't broadcast your hiking intentions lest you may get a little surprise upon your adventure's end.
