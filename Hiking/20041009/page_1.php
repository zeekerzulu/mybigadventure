At the trailhead we're pummeled with an avalanche of trail-related information.  Imagine being forced to read all of these placards before being allowed to hike on the trail?  Can you say "information overload?"  My guess is most folks don't pay much, if any, attention to it. I'm usually one of those folks. However, today will be different. This bulletin board has cartoons on it.
