<a href="index.php?action=Stats&stat=Friends&date=20041008&page=13">Bill</a> and I are ready for some hiking adventure.  According to the sign, we'll be trekking through land that once supported a farm; farmhouse, barn, sawmill, maple and apple orchards.  Hmmmm, there's no mention of an outhouse.  Perhaps the sign maker didn't think it was important enough so they didn't bother putting it on the sign?  Call me crazy, but for me, an outhouse is waaaay more important than a sawmill.  I saw wood far less than I.... well, I think you get the idea.
