<p>
I hike over to the northwest for additional scenic viewing.
<p>
Well the time has arrived, time to go back down the mountain.  I decide not to take any more pictures, I'm all pictured out.  Plus, on the way up I took a lot of "turn-around" shots so in the name of eliminating redundancy, I pack away my camera.  It's actually nice to sightsee without the camera.  When I'm in picture taking mode, I do have to admit I feel a little like I'm "on the job" which does take away from the total sightseeing experience.  But I'm not complaining, I just want to share with you what it's like to be an amateur photo-journalist/travel-writer.  It's mostly good, but it's a responsibility I take semi-seriously.
<p>
