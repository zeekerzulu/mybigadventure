<p>
On the way down the mountain I quickly meet up with <a href="index.php?action=Stats&stat=People&date=20041005.2&page=18">Jean</a> and <a href="index.php?action=Stats&stat=People&date=20041005.2&page=18">Celine</a> from Quebec City, Canada.  I encounter them as they're making their way down the mountain, their progress slowed by their little puppy Dingo.  I spend the rest of the hike chatting with them, talking about everything from careers to geology to politics.
<p>
Sooner than expected, we all find ourselves at the end of the trail, the hike is over.  That's what happens when you chat with someone on the trail, time just flies on by.
<p>
I rather enjoyed my hike today.  It was filled with different scenes, from forest settings to mountainside views of the Atlantic Ocean as well as <a href="index.php?action=Stats&stat=Communities&date=20041005&page=8">Bar Harbor</a>, ME.  I met a few interesting people as well. All in all it was a very good day of hiking.  The only downside was the chilly, windy weather.
<p>
I give my hike of <xa href="javascript:myPopup1('http://www.acadiamagic.com/CadillacMountain.html')">Cadillac Mountain</a> 4.5 thumbs-up out of a possible 5 thumbs.
