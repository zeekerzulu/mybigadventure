<xa href="javascript:myPopup1('http://www.acadiamagic.com/CadillacMountain.html')">Cadillac Mountain</a> is comprised primarily of pink granite.  The Park Service uses it all over Acadia for such things as stone walls, buildings, etc.  The rock is really quite pretty.
