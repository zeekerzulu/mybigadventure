Despite all their stupid rules I start my hike in earnest.  The Park Service erected this gate to keep all vehicles off the road.  Looking at the room around the gate I think I could sneak a riding lawn mower past it if I wanted to.  It's always good to think about beating the system.  It keeps one on their toes.
<p>
Time is of the essence however, I have no time for riding lawnmowers.  I have a sinking feeling it's going to be a close one in terms of finishing the hike before dusk.  I figure it'll take me about 4 hours to reach the summit then another 3 hours to get back.  Putting my completion time around 7pm which is when the sun will start to set.
