I take a little time to register.  It's always a good idea to register if you hike high up in the mountains, especially if you're alone like I am.  If you don't come back for whatever reason, the registration will direct a search party to where you might be.  As I insert my slip into the box I notice it's jammed full of other registrations.  I have to fold my slip in half so I can shove it in.  Apparently my information will be used to locate my -dead- body since no one has emptied the box in quite a while.  So much for feeling like someone's watching my back.  More likely, I'll start getting junk mail from outdoor recreation companies since I supplied my name and home address on the registration form.
