<p>
<a href=http://www.mybigadventure.com/index.php?action=Pics&name=Daily/20041019/DSCN0006.jpg&nocomments=1><img src=http://www.mybigadventure.com/Pics/Daily/20041019/Small/DSCN0006.jpg></a>
