<h1><hr class=Journal2>A WHIRLWIND DAY IN BOSTON - Wednesday, October 20, 2004<hr class=Journal2></h1>
<p>
<a href=http://www.mybigadventure.com/index.php?action=Pics&name=Daily/20041020/DSCN0293.jpg&nocomments=1><img src=http://www.mybigadventure.com/Pics/Daily/20041020/Small/DSCN0293.jpg></a>
<a href=http://www.mybigadventure.com/index.php?action=Pics&name=Daily/20041020/DSCN0332.jpg&nocomments=1><img src=http://www.mybigadventure.com/Pics/Daily/20041020/Small/DSCN0332.jpg></a>
<a href=http://www.mybigadventure.com/index.php?action=Pics&name=Daily/20041020/DSCN0591.jpg&nocomments=1><img src=http://www.mybigadventure.com/Pics/Daily/20041020/Small/DSCN0591.jpg></a>
<a href=http://www.mybigadventure.com/index.php?action=Pics&name=Daily/20041020/DSCN0396.jpg&nocomments=1><img src=http://www.mybigadventure.com/Pics/Daily/20041020/Small/DSCN0396.jpg></a>
<p>
In better spirits today, I drive to Boston for a world-wind tour of the city's historic offerings via the Freedom Trail.  Not wanting to pay an arm and a leg for parking, I park the van many, many blocks from Boston Common, the starting point of the trail.  With only two hours maximum on the meter, I hurry my way across Boston Common and through about a third of the Freedom Trail before I have to zip back to the van to feed the meter.  I end up running back and catch the meter at the 3 minute mark, only to see a meter maid hovering near the van.  Ha!  You didn't get me!  At this point my trip to Boston has taken on a gaming atmosphere, it's me against the parking police!  It's kinda fun actually.
<p>
After feeding the meter, I jog back to where I left off on the Freedom Trail, and manage in less than 2 hours to make my way to the final stop, the U.S.S. Constitution.  The problem I face now is I'm across town from where the van is parked.  With less than 30 minutes left on the meter, I literally run 3.5 miles back to the van where I catch the meter at 3 minutes again!  Ha!  I beat them again!  I feed the meter another 45 minutes to coincide with the time when parking is free.
<p>
I clean up the sweaty aftereffects from my speedy tour, then walk back into the heart of the city to grab something for dinner.  After dinner I notice a frenzy of fireworks popping off in the distance and quickly ask a passer-by what's going on.  He tells me tonight the Boston Red Sox are playing the NY Yankees in New York for the American League Pennant.  Apparently it's the final game of seven (both teams are tied 3-3).  My interest is sufficiently piqued, so I take the subway to Fenway Park and hit one of the local bars to watch the game on the tube.
<p>
When the dust finally settles, the Red Sox win the pennant and afterwards a near riot breaks out in the streets around Fenway Park.  Not wanting to participate, I take the last train back to city center, only to find more celebration going on.  From what I can tell, the entire city is partying and parting hard!  The streets are clogged with cars, fans are waving banners, shouting, it's all rather amusing to watch.  Luckily the van is parked one block outside of the madness so I manage to sneak out of the area unimpeded.
<p>
I drive southward into the early morning and finally arrive in Wareham, MA.  I'm exhaused from my busy day of touring, so I park the van, then immediately settle in for the night.  Tomorrow I plan to tour Cape Cod.
