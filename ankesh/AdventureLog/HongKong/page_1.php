<u>24-AUG-2005 06:30 AM (Hong Kong Time)</u><br>
Trying to make some use of the time we had, we decided to go to Victoria Peak which is the highest point in Hong Kong and also one of the oldest forms of public transportation dating back to 1888.  The tram took us to the top where we could see every part of Hong Kong including the islands.  Off in the distance were many cargo ships indicating the type of business (import/export) that HK was all about.  My Lonely Planet travel guide saved the day.  I had no idea how to get the Victoria Peak Tram and the rail map or city map didn't help much. But the Lonely Planet map had the train stop lilisted.  I had figured this out after passing up our stop 6 stops later. We had wasted another hour just getting our bearings down.  The view was indeed spectacular as promised and we were able to see several of the famous buildings.
