<u>22-AUG-2005 06:22 AM (Hong Kong Time)</u><br>
It takes some adjusting to a substantially different time difference.  Case in point, I was being served dinner at 4 AM on Cathay Pacific Airlines.  I was dead tired and my plan was to sleep but I ate and slept for 8 of the 14 hrs of the flight.  The airplane is an Airbus A300-600 or something like that. It's suppose the be the world's biggest airplane with an 8000 mile capability.  Our trip was ~6200 miles.  Thank goodness, I'm getting air miles for this trip.  It's nice of them to have LCD screens in the back seats with remotes that let you change pre-recorded TV stations, several of the latest movies, and allow you to play games like Mahjong, Hangman, Solitaire, or Virtua Bowling.  But I didn't do many of those things because I needed to sleep realizing that I would have to hit the ground running when I get into HK.
<p>
<u>23-AUG-2005 09:00 AM (Hong Kong Time)</u><br>
The plane arrived 1 hr later, but it was quite a site to be landing with mountains covered with green trees on one side and the ocean on the other.  It finally hit me that I was finally on my dream vacation.  Immigration was super simple, but Customs was not.  Apparently something in one of our bags was setting off the alarm and so we had to get all of our luggage inspected.  Ack!  We walked out of customs and bought an Octopus pass. A pass that lets you take the public train systems called (MTR) unlimited for 3 days.  The boarded the train but at the first train stop we had to get out. Thank goodness I had printed out a rail map so I knew to do this.  There were none on the train (but I had later realized my octopus pass had a tiny little map on the back, however I still prefer mine because it has a bigger font). 
