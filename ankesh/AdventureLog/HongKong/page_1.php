<p>
At night we went around the shopping areas in Causeway Bay. It reminded me much of Chinatown in NYC.  Or even Times Square. There were lots of large neon flashing lights and people here just don't sleep. Out in the middle of the week just looking at all sorts of electronics and clothing.  Electronics shops are a dime a dozen here and the most prominent electronics are cell phones and cameras, followed by laptops and MP3 players.  The most common chains here are McDonalds, 7-11's, and Starbucks.  I had stared at cell phones mostly noting ones that we probably won't see in the USA for another year or two.  Prices are on par with the US though. I didn't really find many bargains on electronics, just tnew features we wouldn't see very soon.
<p> 
I wanted to point out that the people of Hong Kong are very nice. I feel very safe here, even alone at night. So does M.  We got a lot help from random strangers as it was obvious we were lost.  With the exception of only a few rude people most people are very considerate.  The other observation is that this city is very clean. I didn't really see the litter  we are use to in the big cities in the US and very little graffiti.  In fact not one sign of it in the subways.
<p>
Today's adventures include going to several markets like the flower market, bird garden, jade market, ladie's night market, temple street market, stanley market.  Also we'll hit up two temples, Tin Hau and Ma Po.  We want to end the day in Repulse Bay, a nice ritzy area like Rodeo Drive in Beverly Hills, CA.
