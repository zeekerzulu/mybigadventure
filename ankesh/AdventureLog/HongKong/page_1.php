<p> 
Entering into HK, I noticed it comprised of mostly old and new hi-rise buildings and skyscrapers. We wasted about 1.5 hrs just trying to get our US Dollars changes into Hong Kong Dollars (HKD).  We got back on the train and then headed to our hostel (which again thanks to my diligent work, I had pretty easy instructions to.  This would be very useful because the street numbers are mostly written in Chinese here but the street signs have both Chinese and English).  I was warned that the hostel entrance was on the side of the building so I knew to look for it.  I have to say, for a hostel, it is very clean and the staff is particularly helpful. The owner's name is Jackie Chan. No, not the movie star :)  And so after we unpacked a little, and reorganized, we began our day.
<p>
In case anyone wants to know, there is a Portland Street in Hong Kong.
