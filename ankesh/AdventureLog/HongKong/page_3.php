<p>
Today happened to be a misty day but you could still see the giant sitting bronze Buddha. You climb several hundreds of steps before you reach the top and are allowed to circle around the statue and go inside it.  Off in the distance you can see the Buddhist temples. Although of newer constructions, it tries to represent the more original shape of Chinese buildings.  After visiting the Buddhist temple, M and I decided to have lunch at the monastery which consists of a completely vegetarian lunch for an affordable price which I'm sure goes to a good cause. 
<p>
The trip ended up being more than just the few hours I had originally thought. It was an entire day trip consisting of a drive via bus that lasts 45 min.  One thing I didn't know was that the bus requires exact change and I had to ask people on the bus for change.  That and the bus terminus and Tung Chung was hard to figure out which bus to take. 
<p>
I wanted to end the night with a junk boat tour of Victoria Harbour and downtown HK, so I signed up for a booze cruise.  While the ride was nice to relax to and take in the sights, I was disappointed at the junk boat itself. It was suppose to be modelled after an original Chinese junk boats but it felt so commercialized and the tour guide operator didn't really say much. 
<p>
Tomorrow I'm just going to chill in the morning and then catch the MTR out to the airport so I can fly out to Bangkok.  
