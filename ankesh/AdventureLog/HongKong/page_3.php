Today, we decided to go to one of the outer islands called Lantau.  Lantau is very isolated from large skyscrapers and apartment hi-rises. It is mostly a few cities and then more isolated regions fully of monastaries.  The most famous one is called Po Lin Monastery.  Po Lin has a giant bronze Buddha statue sitting down and is the only one know for a sitting buddha outside.  
