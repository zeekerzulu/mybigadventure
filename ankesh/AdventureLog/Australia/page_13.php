<u>13-SEP-2005 11:14 PM</u><br>
The finally day of our 1071 km journey, we still had over 700 km to go.  Yikes, it was going to be a long day of driving.  But we got our continental breakfast which means only toast and coffee in Australia and headed out.  The drive took us closer and closer to the ocean but not quite there, at least until we crossed into the province of Victoria.  What a happy moment to finally cross over too.  But we still had a ways to go.  
<p>
Finally, veering off the path a little, we did see the ocean and she was mightly and dangerous looking.  All along the way we had been keeping our eyes open for kangaroos and koalas because of roads signs that warned of their crossing.  No lucking in spotting them, but we kept on driving to Melbourne.  Melbourne is quite the city. It uses electronic toll passes to get through it faster (no humans involved at all) and even some of the bridges are lit up quite colorfully. However, after calling in to the toll authorities to get a 24 hr pass, I decided to use it a hour out of town to the start of the Great Ocean Road which would be our main attraction for tomorrow.  
