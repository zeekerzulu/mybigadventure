<u>05-SEP-2005 8:31 PM</u><br>
Pretty much an uneventful day, today we left Cairns and flew to Brisbane.  Once we reached Brisbane, we rented a car and drove up 3 hrs or 300 km to Hervey Bay.  Arriving, mostly tired, and in the dark, we got to our rented beachhouse.  The office was closed but they manager left a note for me to get the keys from the mailbox.  Nothing much else. Tomorrow we take a ferry over to Fraser Island, the world's largest sand island.  
