<p>
You don't want to go swimming in the waters of Fraser Island due to the large concentrations of sharks - mainly tiger sharks.  
<p>
The first part of the trip was through the rainforest consisting of strangler figs and grass plants and banksia which was used by the Aboriginese to transport fire.  It was lit and transported ine the paperous bark of the trees in this area.  The lighter colored banksia were used to make a drink similar to lemonaide.  This area of the rainforest, called the Yidney Scrub, was completely untouched by the logging industry unlike other parts of the rainforest on the island.  Anyway, we got out of the bus and walked about 800m to get a closer look at the rainforest.
<p>
Getting back on the bus, we headed to our lunch destination at Happy Valley Resort.  This area is one of the few places left where you can still by land on Fraser Island.  It's a World Heritage site so most of it is protected by the government.
<p>
After lunch, we travelled East along the 75 mile beach to The Pinnacles.  The Pinnacles were an area of the beach where the sandstone had eroded away revealing several different colors of layered sand.  We boarded the bus after 5 min, and headed down to the Maheno shipwreck.
<p>
