<p>
Following the Maheno, we visited the Eli Creek, the largest freshwater stream on the east coast of the island where you are allowed to walk in the creak itself out to where it dumps out onto the beach.
<p>
And finally wrapping up our day on Fraser, we went to one of the pristine, crystal clear lakes on Fraser Island.  The sand is so perfectly round here (and only here and not anywhere else in the world), you can use it to get a rid of try skin on your feet or use it to clean jewelry.
<p>
It was now the end of the trip and we boarded the 4WD bus heading back through the rainforest and to the spot where the ferry would arrive.  The ferry ride itself was spectacular as we had a nice sunset to look at.  What a way to end a great day.
