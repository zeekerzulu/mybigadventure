<u>06-SEP-2005 7:48 PM (AUS Time)</u><br>
Today, M & I are taking a trip out to Fraser Island,  the biggest sand island in the world.  You can only get to the island via ferry and then you must 4WD to get around.  Our bus was custom-made by a German company called MAN, and if you remember how the Germans built tanks, this bus was like a tank.  So after we arrived on the island, we boarded our 4WD bus.
<p>
<img src="Graphics/spacer.gif" height="40" width="1">
<p>
