<p>
The Maheno was a luxury cruiseliner once-upon-a-time, when specifically up until 1935.  The story goes that it was being towed by a smaller ship when a cyclone hit it.  Now, the Maheno could have easily powered up and gotten out of the way of the cyclone, but ship transport laws back then required you to remove he propellers of any ships being towed and so the Maheno was helpful and eventually met it's sandy grave on Fraser.  Over time, it rusted away and sank into the sand.  Currently, several decks are not even viewable anymore as they sit far below the sand.
