<u>10-SEP-2005 10:28 PM(AUS Time)</u><br>
The plan for today was to spot our time around Sydney Harbour.  But we managed to due much more.  Starting out in Sydney harbour, we saw both the Sydney Harbour Bridge and of course the world famous Sydney Opera House.
<p>
The next destination was Mrs. Macqueries Point which required a long walk around the harbour, through the Royal Botanical Gardens and then we finally reached our destination. This was a popular spot to take pictures of both the bridge and the opera house, so we did that and then rested on a bench in the park.  M and started up a conversation with an 83 year old woman who was all along and who also just flew into Sydney. She happened to be from near Eugene, OR.  Wow, another Oregonian.  That' s just crazy. Sweet old lady. I felt sorry for her that she had noone with her. She told us that we made her day.  That's just the kind of people we are :)
<p>
Anyway, we had to head back now as we wanted to see The Rocks marketplace.  Having taken a very very very long walk from Mrs. Macqueries Point to The Rocks, we examined all the arts and crafts.  This place is very much like the Portland Saturday Market.
<p>
The next goal was to walk across the Sydney Harbour Bridge (well at least halfway).  On the way there, we could see the bridgeclimbers, which I would be joining tomorrow.  The bridge gave quite a view of the city and the Sydney Harbour as well as seeing the other unique bridge, called ANZAC (Australian New Zealand Army Call) bridge which is actually a war memorial and a bridge.
<p>
Still full of energy, we decided to try to head back to Sydney Harbour and catch a fairly out to Manly Beach and try out some of the best fries according to something that M read.  The ferry ride was fairly relaxing and we happened to arrive on their 150 year anniversary so there was a little stage setup with local musicians playing, a tiny carnival, and free bus rides.  
<p>
With still some energy left, we wanted to check out Chinatown back in Sydney CBD.  We took the ferry back to Sydney Harbour and walked to the nearby Chinatown.  Only a small area, it was lined with restaurants and shops.
<p>
Time to get home now, we met Ching's coworker, Chris, as Robert had made dinner for them. Chris was also from Melbourne originally, like Ching.  Anyway, we had a nice talk and watched some TV before heading to bed.
