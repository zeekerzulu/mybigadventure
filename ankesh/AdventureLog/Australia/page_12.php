<u>12-SEP-2005 8:30 PM (AUS Time)</u><br>
We wasted a lot of time trying to get the rental car from Hertz and this was mostly because when we went to pick it up you had to walk a little ways into a secured parking gargage to get it.  What we didn't realize was that the rental agent was telling us that the parking garage was actually called "SECURE PARKING" and we kept missing it for 30 min.  But anyway, we got our car and left Sydney.
<p>
Before we start the long journey, we decided to take a trip out to the Blue Mountains and visit the town of Katoomba where you can take a Scenic Railway and visit the 3 Sisters rock formation.  When we go to the top of Blue Mountain and in Katoomba, we found the Scenic Railway.  The Scenic Railway is the steepest in the world and the ride was blast complete with the Indiana Jones theme music blaring in the background.  The other surprise was the change in the weather. It was very cold and we found ourselves getting our cold weather gear out for the first time in the entire trip.
<p>
Upon reaching the bottom, we got out and got treated to a view of the valley and the 3 Sisters which were cone-like rock formations (almost nipple-like).  We walked around for a bit and through the rainforest exploring trees and old rusty metal buckets used to transport coal which had fallen off a rope which had snapped. On the way back up we took the skytram which provide some lovely views and headed back to the car.  That's when I saw the first signs of snow falling from the sky.
<p>
The drive to Melbourne took us through the windy countryside and offered a beautiful sunset.  However, New South Wales is infamous for speed cameras all along the highway.  It guess it's there way to insure speed control but it's stupid if you ask me because they put these signs up telling you exactly where the speed cameras are and all you have to do is read the signs and slow down, pass the cameras, and speed up again.  It seems to defeat the purpose.
<p>
We finally called it a day in Bateman's Bay, a fishing town where we decided to stay at a hotel for the first time in the trip.  Having found the only place open we could eat at which was called Eagle Boys Pizza, we got friendly with the locals running the store and laughed it up as we got a nice deep discount on a very good and yummy pizza.  Do yourself a favour, don't go to Domino's go to Eagle Boys, much better.
 
