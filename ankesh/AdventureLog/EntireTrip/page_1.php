The particular route was picked for a couple of reasons. First I wanted to experience a little bit of Asia. Having always wanted to go, I found two of the most interesting places to be Hong Kong and Bangkok. Not only that but Hong Kong was one of the world's best economic centers and rich with diversity. However, in Bangkok, I wanted to see the Wats (known as temples) and the surrounding ruins. The US dollar however, stretches a long way in Bangkok so with regards to the trip, it wouldn't be that much more and only a short flight from Hong Kong. Australia has always impressed me and I'd been wanting to see the Great Barrier Reef for quite some time as well as the magnificent Sydney. It was also favorably picked because I wouldn't have to learn a new language :) And New Zealand, well if you've seen Lord of the Rings, you know it's all about the scenery. Tahiti was sort of a last minute thing. It was never part of the original itinerary but when my travel agent told me I would have to fly back to Hong Kong and then home, I wanted to fly forwards to a new place and not backwards to a place I had already visited. Logically, it came down to Samoa, Fiji, and Tahiti. And since I had heard so many people saying how Tahiti is Heaven on Earth, I decided to check it out myself.
<p>
<u>21-Aug-2005 6:45 PM Pacific</u><br>
What a way to start off the trip by being selected for an extensive security screening process where they pat you down from head to toe and completely go through your luggage.  Gee thanks, Alaska Airlines, for randomly selecting me, but I was more than happy to oblige.  They made up for it by offering complimentary alcohol later.<p>
<u>22-Aug-2005 01:00 AM Pacific</u><br>
It's quite late here in Vancouver, B.C., but M and I have found a couch to crash on and I have a TV to myself so I'm watching the only movie coming on TV, "Cool Runnings", until the plane to HK gets here at 3:20 AM.
