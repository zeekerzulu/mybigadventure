Due to lack of forward planning on my part, I fail to gain access to the White House during my visit to Washington, D.C.  However, the home and office of the President of the United States is an important sight, one that deserves mention within these electronic pages.
<p>
The history of the White House is rather fascinating and storied.  In the beginning, site selection was completed by President George Washington in 1792, afterwhich construction of the White House was given the all clear and commenced without delay.  Eight long years and $232,371.83 later, the White House was finally completed, providing both housing and that coveted new-house-smell to the second U.S. President, John Adams.
<p>
Originally referred to as the Presidential Palace or Presidential Mansion, by 1811 the general public was calling it the White House, prompted no doubt by its white exterior color.  The stuffy name, the Executive Masion, was a hold on, often used by officials until President Teddy Roosevelt solidified the public reference in 1901 by engraving "The White House" on the his official stationary.
<p>
In 1814, hard times strike Washington D.C. when the War of 1812 spills over into the Nation's Capitol, causing great devastation in its wake.  Many buildings, including the White House, are not spared.  The gutted White House was quickly rebuilt and enjoyed a relatively stable existence, until the early twentieth century when two wings are added to accommodate the President's growing staff.
<p>
Tragedy strikes again in 1929 on Christmas Eve when the West Wing was significantly damaged by fire.  Surprisingly, in the mid-1940 the White House was deemed structurally unsound, requiring President Harry Truman to move out while the house was gutted then retrofitted with steel and concrete.  Years later, after decades of poor maintenance, the interior was given a complete overhaul during President Kennedy's term in office.
<p>
The White House is looming in the distance.  I can see how it got its name, not only is it big, it's pretty darn white!  Come with me to the front of the fenced property while I try to capture as much of this special place as I can.
