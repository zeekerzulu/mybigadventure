Nestled deep within scenic Adirondack State Park in Upstate New York, the Winter Olympic Sports Complex is a mecca for winter sports enthusiasts from around the world.  The hub of this great complex, Lake Placid, New York, was the center of world attention and admiration when it hosted the 1932 and 1980 Winter Olympics.  The complex is composed primarily of three main facilities, namely the skating arenas, the ski jumps, and the bobsled/luge/skeleton runs.  
<p>
Interested in winter sports?  Well you've come to the right place.  Strap on your skis and together let's launch off the 120 meter ski jump that'll take us high up into the air and straight into this tour.
