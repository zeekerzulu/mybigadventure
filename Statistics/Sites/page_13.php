<b><a href="index.php?action=Sites&date=20040926.1&page=1">Ice Skating & Speed Skating</a></b> - Remember the 1980 Winter Olympics when the USA Men's Hockey Team triumphed over the Russians?  Well this is where the "Miracle on Ice" happened and history was made on February 22, 1980, here in the 1980 Winter Olympics Skating Arena.  It was a white-knuckler, the USA won by a single goal, USA 4, USSR 3.  The Olympic Skating Complex also boasts the 1932 Winter Olympics Skating Arena where figure skater-turned movie star Sonja Henie won her second of three consecutive Olympic Goal Medals.  Remember USA speed skater Eric Heiden?  In 1980 he won 5 Olympic Gold Metals for the USA.  On the Lake Placid Olympic Speed Skating Oval he broke 1 World and 5 Olympic Speed Skating Records.
