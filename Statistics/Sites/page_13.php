<b><a href="index.php?action=Sites&date=20040926.2&page=1">Ski Jumping Complex</a></b> - Primarily consisting of two tall ski jumps, the Olympic Jump Complex is a world-class training facility for ski jumping.  The 90 meter and 120-meter jump towers are true skyscrapers where the brave (or crazy) risk life and limb for the love of their sport.  The 120-meter tower features a skydeck that is accessible to the public via chairlift/elevator.  Steps away you'll find the Kodak Sports Park where freestyle skiers train year-round.
