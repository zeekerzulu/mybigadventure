Located in the heart of Boston, MA, you'll find one of America's first historic walking tours.  The brainchild of local journalist William Schofield, The Freedom Trail was created in 1958 to enable easy public access to Boston's rich and interesting history.  The trail will take you on a whirlwind tour of Boston's 16 most significant sights relating to the Colonial Revolution.  Two to three hours is all you'll need to complete the tour, and in the process you'll be dished up with sights of cemeteries, tall ships, historical buildings, monuments, memorials, statues, and much more.  Two and a half centuries of history is covered over the course of 2.5 pancake-flat miles.
<p>
It's really hard to get lost on the trail, just follow the red brick or red painted markers that line the entire route.  Along the way, in addition to the sights themselves, there's a wealth of information to be gained by reading all the placards that are strategically sprinkled across the tour's expanse.  You may go solo on a self-guided tour, or better yet, lean upon the National Park Service for assistance.  They provide a variety of different tours that leave every half-hour from the Park Visitor Center located on 15 State Street across from Old State House.
<p>
Well, my tour time has finally arrived.  I've opted for a self-guided tour, but, that doesn't mean I wish to be alone.  Please accompany me.  I'm now underway, the first stop of my tour will be Boston Common.
