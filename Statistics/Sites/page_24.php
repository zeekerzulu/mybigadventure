I have to admit I'm not much of a baseball fan.  I'm actually not really a fan of any sports.  Why?  I'm not sure exactly.  I must have been hiding behind the door when God was handing out the ever popular sports enthusiast gene?  Regardless, I can certainly make exceptions for important moments in sports history.  I feel they're just as important as any other historical event.  As luck will have it, I stumble into Boston, MA on the day their beloved baseball team, the Red Sox, are to play their arch rival, the NY Yankees, for the American League Pennant.  The series it currently tied at 3-3 and the winner tonight takes all the spoils.
<p>
Normally, such an event is important in the minds of many, but historical?  Well, this time around fate has provided an interesting mix of things.  Never before has a baseball team in post-season play come back from a 0-3 deficit to claim victory in a race for the pennant.  Additionally, it's been like forever since the Red Sox have beat the Yankees in a playoff race for the pennant.  If the Red Sox win tonight, surely, long since deceased fans will be doing victory rolls in their graves in celebration of this once in a life time happenstance.
<p>
The evening has arrived and the fireworks are now popping over Fenway Park, the celebrated home of the Boston Red Sox.  Although tonight's final game will be played in New York, I guarantee you there'll be one hell of a party going on down at Fenway.  I'm in the process of making my way to the park now.  Meet me there if you like, and together we can experience what may very well be a monumental event in the rich history one of America's most beloved pastimes, baseball.
