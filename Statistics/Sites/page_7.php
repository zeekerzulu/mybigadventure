Wall Drug is an interesting place.  Founded in 1931 by Dorothy and Ted Hustead, the drug store hadn't expanded much until 1936.  In 1936 on a hot July Sunday, Dorothy had a revelation, why not give away free ice water.  Since that hot day, Wall Drug has grown on the premise of offer people something they need and serve it up with good humor, great service, and enticing deals.  Today, Wall Drug is world-renowned, it's as much a visitor attraction and museum as it is a store.  Millions of people flock to the drugstore every year.
