Over time, rocks and stones have played an important role in mankind's efforts to memorialize past legends and events.  Take Ireland's <ax href="javascript:myPopup3('http://www.sacredsites.com/europe/ireland/blarney_stone.html')">Blarney Stone</a> for example.  Sitting high off the ground in the battlement of Blarney Castle, kissing it is supposed to give you good luck.  Be forewarned, however.  Rumor has it the local youth sometime sneak into the castle at night and urinate on it, so you may want to reconsider how you plan to experience that unique treasure.
<p>
How about the <ax href="javascript:myPopup4('http://www.rampantscotland.com/know/blknow16.htm')">Stone of Destiny</a>?  Supposedly, in biblical times, it was the pillow of Jacob and subsequently, the rock upon which Scottish Kings were crowned.  Then there's the <ax href="javascript:myPopup5('http://www.crystalinks.com/blackstone.html')">Black Stone of the Kaaba</a>.  Delivered by archangel Michael to patriarchs Abraham and Ishmael who were building the Kaaba, the stone is now set into a wall of that religious shrine.
<p>
As everyone knows, America's famous rock is Plymouth Rock.  With over a million visitors a year, Plymouth, MA is a place to go if you're into historical Pilgrim stuff; rocks and all others.  It is upon this rock the Mayflower Pilgrims first set foot so many centuries ago in 1620.  All the other previous mentioned stones memorialize legend.  Certainly Plymouth Rock is the real-deal, genuine, bona fide artifact!  Right?
<p>
Well, I'm ready to check out Plymouth Rock, come with me now as I tour this special, historic rock.
