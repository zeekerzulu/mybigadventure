<p>
Adolph Coors and Jacob Schueler opened their brewery in a converted tannery on the banks of Clear Creek in 1873, when Golden was still the capital of the Colorado Territory.  The water came down from the Rockies, the barley from local farms, and the beer went out by wagon.  Today the Golden plant is the largest single-site brewery in the world.
<p>
The brewery outlived Prohibition by making malted milk (most of it sold to the Mars candy company) and porcelain, and it outlived a long stretch of being the big beer you couldn't buy east of the Mississippi.  The tour walks you from the malt house to the packaging lines and ends, as all good tours should, in the hospitality lounge.
<p>
Thirsty?  Me too.  The shuttle bus is pulling up, come along for a look at how a few million gallons of beer get made.
