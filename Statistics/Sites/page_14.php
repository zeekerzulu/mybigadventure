<p>
Whiteface Mountain, located near Lake Placid, NY in Adirondack State Park, is the 5th tallest peak (4,867 feet) in New York State.  Of the 40+ High Peaks (mountains 4,000 feet or higher) within the Adirondack Region, Whiteface Mountain is the only mountain peak accessible by car.
<p>
Completed in 1935, access is provided by the Whiteface Veterans Memorial Highway, a 5-mile stretch of pavement that reaches up the mountainside more than 2,300 feet from start to finish.  From the summit parking lot a short stair climb or elevator ride will take you to the treeless summit which hardily greets you with an unobstructed 360-degree view of hundreds of square miles of spectacular forest, lakes and mountains, stretching from Canada to Vermont.
<p>
Do you like views from lofty places?  How about breathing in fresh, clean, cool air?  Well, I've got the place for you, Whiteface Mountain.  I'm driving up to the mountain top now, jump in the van and let's go.
