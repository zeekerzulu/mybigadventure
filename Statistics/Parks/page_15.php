Located in Waterbury, VT, the Ben & Jerry's Ice Cream Factory offers a glimpse into the world of ice cream making with it's year round factory tour.  Ben & Jerry's has been making ice cream since 1978 and has been growing steadily ever since.  It all started back in 1978 when Ben Cohen and Jerry Greenfield opened their first Scoop Shop in a converted Vermon gas station after taking a $5 correspondence course in ice cream making.  From the very start until present day, the company history proves to be both interesting and storied.
