Located 60 miles southeast of Seattle, WA, Mount Rainier National Park is America's 5th oldest national park.  Incorporated into the park system in 1899, the park is comprised of 235,625 acres, 97% of which is designated as Wilderness.  Such designation not only recognizes the park for its primeval character and influence, it also affords it all protections as outlined within the Wilderness Act passed by Congress way back in 1964.  
<p>
Mount Rainier is a massive mountain, reaching 14,410 feet skyward and blanketed by 35 square miles of ice and snow.  But don't let its icy coating fool you, there's a tiger within its depths.  Sitting atop the <a href="javascript:myPopup1('http://www.crystalinks.com/rof.html')">Ring of Fire</a>, the mountain is actually considered an active volcano.  The mountain's splendor coupled with such features as old growth forests and sub-alpine meadows attract nearly 2 million people a year to the park.
