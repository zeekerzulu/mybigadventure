Located in Upstate New York, Adirondack State Park is a massive complex rivaling the size of Vermont.  A patchwork quilt of public and private lands created in 1882, collectively the park is comprised of over 6 million acres.  The park has everything for the outdoor adventurer, including 2,000 miles of hiking trails, hundreds of miles of canoeing, tall peaks (42 over 4,000 feet), camping, bicycling, swimming, fishing, alpine and nordic skiing, snowmobiling, skating, dog sledding, and snowshoeing.
<p>
The park supports a variety of wildlife including black bears, beavers, white tailed deer, bald eagles, common loons, bobcats, coyotes, fishers, mergansers, brook and lake trout, and land-locked salmon to name a few.  Hardwood and softwood forests cover the park's expanses, including black cherry, maple, beech, hemlock, balsam fir, red pine, and several varieties of spruce.
<p>
I'll be spending 7 days in the Adirondacks.  During my visit I plan to road bike, mountain bike, hike, and tour the entire Winter Olympic Complex in and near Lake Placid.
