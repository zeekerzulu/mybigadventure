<p>
Being on the road has helped lessen a burden I didn't know I had until now.  This burden is the use of mirrors.  Since my trip started, I've probably averaged looking in my mirror about once a week and that's only out of practicality, I need it to shave.
<p>
Mirrors, when used for self-viewing, is an activity fraught with peril and danger.  Typically, we all use a mirror to get a bead on how we look.  The mirror tells us if we are overweight, how many wrinkles are on our face, reminds us that our hair really looks messy, has fallen out, or is turning gray. For some people it's a huge vice, it's a vital tool for vanity and self-worship.  By and large it's mostly all negative stuff.
<p>
And what do we do after inspecting themselves and deciding we don't like what we see?  Do we go to the plastic surgeon to get a tummy tuck or botox?  Do we get a toupee or hair weave?  Do we buy expensive creams, makeup, and other elixirs to combat or hide our wrinkles?  The bottom line is the mirror allows us to compare ourselves to others and pulls us away from appreciating the more important things in life, like the beauty that's inside ourselves and inside others around us.
<p>
Imagine a world where mirrors exist (because they -are- valuable in the medical, optical and other fields) but they do not reflect images of the human form.   How would the world be different?  Would it make for a better place?  Think about it.
<p>
Count how many times you look into a mirror on a daily basis, I think you may be surprised at the number.  And how much time do you spend looking?  What are you doing with the impressions formed when you look at that face that stares back at you?  Are you comparing yourself to others?  Does what you see drive your mood?
<p>
Limiting time spent in front of the mirror may effectively shush those little self-critical voices that tell you you don't measure up, that tell you you have to look a certain way to be happy.  In doing so, you may find you'll be less critical of others and more tolerant and perhaps even appreciative of all human shapes and forms.
<p>
P.S. I dropped the mirror a week ago. No bad luck so far, fingers crossed.
