Looking for a little high elevation biking fun near Bozeman, MT, I spy a trail on the Internet called Emerald Lake.  Not terribly far from Bozeman, the mountain bike trail promises a lung-punishing ascent up to almost 10,000 feet!  Geeze, maybe I need to take bottled oxygen to help push me along up the trail?  By far, this ride will be my trip's highest biking ascent.
<p>
I must say, I really have been blessed so far with good biking health.  Inspite of all the biking I've thrown myself into, I have yet to experience any major physical problems as a result of all the riding I've done so far.  Is it preparation?  Well, we know the answer to that one.  No!  No pre-trip bike training happened.  How about great genes?  Ummm.  I doubt it.  I'm just an average Joe with average abilities.   Hmmm, what does that leave me with?  I know, it's just plain ole dumb luck, yeah, that must be it.  But, whatever the reason, I thank God above for watching over me.
<p>
When I think about it, I could have easily died on some of the bike rides I've done so far.  Remote mountain bike rides, such as the one I'll be doing today, are probably the most dangerous ones.  I always ride alone, so if an ill-fated crash doesn't kill me, the waiting around for the help that never comes certainly will.
<p>
Well, it's best not to think about that now, especially since I'm about to do another remote bike ride all by my lonesome.  I tell ya, it'd be nice to have a riding companion, if only to break up the sometimes monotonous trail.  But that's okay, riding alone has its advantages, like changing your mind on a dime and not having to worry about needing to get it okayed with someone else.
<p>
Hey!  I'm rambling...  The time has arrived to push on up the trail.  Looking for some fresh, thin air today?  If so, come on along, there'll be plenty of that plus great views once we bike up to Emerald Lake.
