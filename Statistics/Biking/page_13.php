<p>
The Badlands, what an interesting name.  From what I understand, no indigenous community has ever lived here.  This area is just a damned and unforgiving place, God forsaken is probably a better description.  But, it's certainly an interesting place to visit and explore.  I've just arrived at Badlands National Park and am raring for a bike ride.  From what I've read, riding one's bike on the paved road here could be hazardous since there's no shoulder to speak of.  Plus, since this is such a bazarre and attention grabbing place, I can imaging the following scenario happening:
<p>
A couple with two kids are driving down the road looking at the scenery pass on by.  Everyone is totally engrossed by the outside eye-candy, including the driver.  As they proceed down the highway in full-gawk, the car hits something on the edge of the road, proceeds to run it over with a bump and a lurch, then keeps on going without really noticing what happened.  Looking back down the road, there I am, all lifeless and flattened, not given the same opportunity to see the wonderful sight the car spectators just saw because I got hit!  Hmmmm.  I think I'll stick to wide, less-traveled gravel roads.
<p>
As luck would have it, there is just one such a gravel road, and it runs along the northern border of the park.  After a little more map looking and head scratching, I decide to make that my route for the day.  Since the riding surface will be gravel, my bike of choice will be my mountain bike, of course.  The road traverses westerly a ways, then dips down to the southwest corner of the park.  I will ride the road until reaching the park's primative campgounds (no water, so camping is free!) then turnaround and come back.  The total ride will be about 20 miles and won't be too hilly.  Good thing, it's almost 100 degrees out now and there is no shade in sight.
<p>
Well, the clock is ticking and the sun is now on a downward slide.  Time to get cracking.  Do you want to bring your bad self along to checkout the Badlands with me?  Sure you do.  So, let's mount our bad selves upon our sturdy steel steeds and ride off for some new adventure.
