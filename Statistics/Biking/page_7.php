I'm feeling a little nutty today.  I've been slacking lately in the biking department and it's driving me a little crazy.  My last two rides were big on scenery (Vancouver, BC) but small on mileage and biking challenge.  So, to up ante, I've decided to ride 100 miles today.   Yeah, sounds a bit extreme, but I'm up for the task.  The century I've planned won't be too hard because it'll be flat as a pancake.
<p>
The Centennial Trail is what I have in mind.  The trail runs between Spokane, Washington and Coeur d'Alene, Idaho and the round trip ticket says about 100 miles.  This'll be my second 100 mile bike ride ever!  My first took place many months back in Portland, Oregon.  Having not trained at all for the first one, I feel pretty confident that my second should be less painful and much more enjoyable.
<p>
After shoving multiple handfuls of dried fruit and energy bars into my backpack, followed by it filling with almost a gallon of water, I find myself ready for the ride.  How about you?  Ever ride 100 miles?  Are you curious?  It'll be a long ride, and I certainly could use the company.  So come on, let's get this party started!
