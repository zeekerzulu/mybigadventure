Today I'll be touring Downtown Seattle by bike.  I've visited Seattle a couple of times in the past and have always enjoyed the city.  Seattle is such a pretty city. So much so, I've decided to officially tour it, so I can bring you along on my ride so you can experience Seattle too.
<p>
I'll be riding my mountain bike on the tour.  Having enjoyed my past two biking venues in nature, I thought I'd give the mountain bike a spin around town.  It has what's called a "granny" gear that's designed to assist when climbing steep inclines.  If you've ever visited or perhaps heard anything about Seattle, you may already know that city center is situated atop a steep hill that draws down into Puget Sound.
<p>
Seattle is a pretty large city and has a heathly metropolitain feel to it.  However, being located in the Northwest, it provides certain advantages for bikers.  Most folks who drive here are considerate of bikers, Seattle is a bike-friendly town.  So, as I tour the town, I'll certainly bike defensively as I always do but I probably won't be having any close-calls per say.
<p>
