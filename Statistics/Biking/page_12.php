This is my second bike ride in as many days.  Yowza!  I'm on a regular roll this week.  Today will be a road biking day, the fourth road biking adventure of my trip.  It's a gloomy day today, the rain clouds are threatening, but that doesn't dampen my enthusiasm.  Hey, I'm within spitting distance of the Grand Tetons, the most rugged and oddly beautiful mountain range I have ever seen.  They just stand out on their own, seemingly having sprung upwards from nowhere.
<p>
I wish to ride as much distance as I can today.  The ride I've chosen will take me to Signal Mountain.  To get there, I'll be riding east of the Grand Tetons in a northward direction.  For the most part, the route I've chosen is fairly flat.  However, Signal Mountain, situated next to expansive Jackson Lake, is around 600 feet tall and portions of the short road to the top promises a steep challenge.
<p>
The storm clouds are gathering in the distance, I'd better get the show on the road.  If you aren't afraid to get a little wet you should come on along for the ride.  No excuses for you not coming along, I have an extra rain jacket you can borrow.  So, come on, let's go.
