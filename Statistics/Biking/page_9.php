I'm in Glacier National Park right now.  As I look around I'm struck with child-like awe, the rugged beauty and majesty of the park has left my mouth agape and eyes wide open with surprise and wonder.  Who would have thought such a place exists in Montana?  When I think of Montana, I think of big-sky country and wide-open spaces.  But here I'm greeted with tall, inspiring mountains and lush, green forest.  Certainly I have found Heaven on earth here at Glacier.
<p>
Looking at the map I was given when I entered the park, I notice there's a long, winding road that traverses clear across the park.  The road, Going to the Sun, runs through Logan Pass which reaches up into the sky 6,680 feet.  Hmmm. If I bike this road up to the pass and back, I will have bagged 30 miles and 3,280 feet in elevation.  Well, that sounds like a great challenge.  The thing that really gets my juices flowing is learning the ascent doesn't actually start until 5 miles into the ride, which means my upward trek will take place in just 10 miles.  Oooooh, now that piques my interest!
<p>
Sometimes I wonder if there's something wrong with me.  I always seem to sniff out rides that are brutal given my current physical shape.  I'm not feeling out of shape per se.  All the biking on my trip so far has added to my endurance and cardiac ability.  However, this ride will be, by far, the hardest of my trip so far.  Add to that narrow, steep, and winding roads filled full of tourist traffic.  Oh well, as they say, "no guts, no glory."
<p>
I've readied myself for my bike trip.  Come along if you dare.  The climbing will be tough, but the scenery will certainly take your attention away from looking down at your hill pumping knees.  So, come along with me, and let's have some fun!
