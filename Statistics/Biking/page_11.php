Wow!  It's been 2 whole weeks since I last biked.  I'm more than a month into my trip and already I'm finding myself turning into a slacker.  Not a good thing at all.  So, what is a guy to do?  Lets see.  How about go on a bike ride?  What a novel idea indeed.
<p>
I actually haven't been slacking.  I've been holed up in Jackson, Wyoming travel writing this past week.  It's the nature of the beast, travel writing that is.  In order to write you first have to travel.  After you've travel a bit, you sit down and write about it.  Repeat this cycle, over and over and over again.  Since I wish to keep you all informed of my adventures as soon as they happen, I have to remain firmly glued to this repetitious, sometimes naggingly insane cycle.
<p>
Today I good news to share with you.  I'm all caught up with my travel writing so I'm now free to seek out new adventure.  I'll start things off with a mountain bike trek, I've selected a trail north of Jackson, just outside of Grand Teton National Park.  Shadow Mountain is the venue, it'll be a short ride that's big on elevation and scenery.  The day is sunny and warm, just perfect for some mountain peddling.
<p>
I'm all hyped up and ready to rock and roll, or is that ride and roll?  Come with me as I cycle up a mountainside for some great westerly views of the Grand Tetons.
