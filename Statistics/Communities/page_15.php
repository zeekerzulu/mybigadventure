Golden City was laid out on June 16, 1859, in the first weeks of the Pike's Peak gold rush, as a supply town at the mouth of Clear Creek Canyon, and named for Thomas L. Golden, one of the prospectors camped there.  From 1862 to 1867 it was the capital of the Colorado Territory, until Denver, the upstart down the road, took the title for good.
<p>
Golden kept busy anyway.  Adolph Coors opened his brewery here in 1873, the Colorado School of Mines arrived in the 1870s and is still here, and Buffalo Bill was buried on Lookout Mountain above town in 1917.  Today it's a college town of about 20,000 at 5,784 feet, with a creek running through the middle, an arch over the main street that says Where the West Lives, and the smell of barley on the breeze.
