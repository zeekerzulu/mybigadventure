Located 100 miles north of London, England, Boston of Lincolnshire is an ocean away, but it was close enough to the hearts of many to be the inspiration for the naming of Boston, MA.  Massachusetts Bay Colony was founded in 1629, and shortly thereafter in 1630 the capital of the colony was given its official name, Boston.  From that point forward, Boston has been given many names, including "The Hub of the Universe", "The Athens of America", and "Beantown."  But, whatever you call her, there's no denying the fact that Boston is rich in both history and culture.
<p>
The city provides myriad opportunities to learn more about the life and times in Colonial Boston.  In addition to its great museums and exhibits, the city offers The Freedom Trail, a 2.5 red-lined route that runs through its historic heart.  The trail features 16 interesting sights relating to America's early history.
<p>
I'm getting a late start today, but I'm hopeful to get an eyeful of Boston before the day is done.  I'm about to tour the city, come with me this late-morning as I prepare to soak in its many offerings (churches, cemeteries, meeting halls, statues, memorials, landmarks, monuments, sailing ships, parks, and government buildings).  And walking Boston's Freedom Trail is just one of the many items on my sightseeing agenda.
