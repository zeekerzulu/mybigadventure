The nation's smallest state capital, Montplier, Vermont is located within the heartland of pictureque Vermont.  Providing employment for over 2,300 state employees, the city is a cradle of government activity with the architecturally pleasing State House as its central hub.  Montplier's historic look and feel, intimate size, and surrounding valley give a warm, hearty welcome to those who stay for a day, a month, or a lifetime.  The city is best known for its historic and architectural riches, its many institutions of higher education, its national insurance company headquarters, and its close proximity to great ski resorts like <a name='valid_link' href="javascript:myPopup3('http://www.stowe.com')">Stowe</a> or <a name='valid_link' href="javascript:myPopup4('http://www.sugarbush.com')">Sugarbush</a>.
