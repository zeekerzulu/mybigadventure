The town of Jackson, Wyoming was founded with the help of the beaver pelt trade.  Fashionable beaver pelt hats were all the rage in the 1820s and 30s.  Places like Jackson, abundant in wildlife, helped fuel the hat making business.  When the 1840s rolled around, silk hats replaced beaver hats and the beaver trade went belly-up.  The area was rediscovered by many settlers in the late-1880s as a good place to raise cattle.  The town of Jackson Hole was officially named in 1894.  Many of the buildings of that era are still standing in and around Town Square.
<p>
Today the town and surrounding community embraces tourism as its largest source of commerce.  Located in a valley, Jackson is surrounded by tall mountains.  The majestic Grand Teton Range to the west serves up great views. Things to do include camping, hiking, biking, fishing, hunting, and mountain climbing.  The three major ski resorts in the area have made Jackson a world-class ski destination.
