Nestled within the eastern confines of Mount Desert Island and neighbor to Acadia National Park, Bar Harbor was originally a fishing community that depended upon the vast seafood riches of the sea to support its economy.  By the 1840's the small town had developed a flair for the artistic who arrived to paint its beautiful scenery and share with the world the splendor that the small town and surrounding area possessed.  Soon thereafter the word was out and many visitors from around the world flocked to the region to experience in person what they had only previously seen on painted canvas.  Today Bar Harbor is primarily a tourist town, catering to visitors who come from far and wide to experience the area's unique character and beauty.
