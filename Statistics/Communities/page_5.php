Everyone grows up somewhere and for me that place was Oakfield, NY. A small community nestled between Buffalo and Rochester, NY, Oakfield was a good place to live and raise a family. The primary industry during my tenure there was a gypsum mine, a paper mill (where they made paper for wallboard), and farming. I'm not sure how many folks lived there when I graduated from high school. I could fish around on the Internet for the boring census figures but why bother. It's enough to say my graduating class had only 95 kids in it and there was a single traffic signal at the center of town where you'd find a bank, a drug store, a hardware store, a post office, and a pizzeria. And from what I can remember, not much really changed during my childhood and adolescence. Things just grew smaller as I grew bigger.
<p>
Come join me now as I travel down memory lane in my old stomping grounds, Oakfield, New York.
