Located in Adirondack State Park in New York, Lake Placid is a crown jewel of winter sports.  The community gained worldwide attention and popularity by hosting the 1932 and 1980 Winter Olympic Games.  Its winter sporting facilities are world-class and numerous, including 2 ski jumps, 2 ice arenas, bobsled runs, and a multitude of others.
<p>
Lake Placid is a small tourist town, overflowing with abundant lodging, shops, and restaurants.  Many visitors use Lake Placid as the launching point for a myriad of outdoor activities including hiking, biking, boating, skiing, fishing, snowmobiling, snowshoeing, and camping.
