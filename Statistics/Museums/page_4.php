Named "Top Tourist Destination in New Mexico" in 1996 by the Tourism Association of New Mexico, the International UFO Museum and Research Center (IUFOMRC) is a must see venue if ever passing through the southeastern reaches of New Mexico.  Founded in 1991 by Walter Haut, Glenn Dennis and Max Littell, the IUFOMRC has since grown by leaps and bounds, moving in 1997 to its current location at 114 North Main Street in Roswell, New Mexico.
<p>
A clearing house for information relating to UFOs, the IUFOMRC is a one-stop-shop that caters to a variety of folks, ranging from the curious tourist who is casually interested in UFO phenomenon to hardcode researchers who are searching for indepth, detailed information concerning their areas of study.
<p>
A good portion of the museum is dedicated to information pertaining to <a href="javascript:myPopup5('http://en.wikipedia.org/wiki/Roswell_incident')">The Roswell Indicent</a>, the famous 1947 summer event that quickly evolved into a supposed government cover-up of an alien spacecraft crash site.  The rest of the museum contains a variety of interesting displays, all with the intent of educating the public on the mysteries and intrigue of UFO phenomenon.
<p>
Are you interesting in learning more about UFOs?  I know I am.  Come with me now as I make my way to the museum's entrance.
