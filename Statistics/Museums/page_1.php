Located in Bozeman, Montana, the Museum of the Rockies was founded in 1957 as a part of Montana State University (MSU) to begin the study and interpretation of this extraordinary region.  The museum is distinguished by the quality of its services to the people of the Northern Rocky Mountains, especially to the rural communities which are characteristic of this region. The Museum today is the largest natural history museum in the region with 94,000 square feet under roof. It includes the only Digistar planetarium in the Northern Rockies and has developed a fully interpreted Living History Farm on 11 adjacent acres. 
