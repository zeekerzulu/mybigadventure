William F. Cody died in Denver on January 10, 1917 and was buried that June on top of Lookout Mountain above Golden, a decision the town of Cody, Wyoming, which he founded, has disputed ever since.  The museum beside the grave tells his story: Pony Express rider, Army scout, buffalo hunter, and for thirty years the showman behind Buffalo Bill's Wild West, which played for Queen Victoria.
<p>
The museum closes at five, and the sun was setting when I pulled in, so this visit is all grounds: the grave, the information boards, the gift shop's locked door and a view over Denver that goes on until the lights come up.  The grounds and the grave are free and open after hours, which is how I saw them.
<p>
Come with me up the hill for a look around, and a story about why there's concrete on the grave.
