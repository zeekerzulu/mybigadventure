<p>
Being the second of my two hikes in Badlands National Park, this one will be a quick jaunt.  It'll be a short 1 mile round trip, with a 200 foot elevation gain up and over the eroding formations.  This hike promises more views of hoodoos, more so than on the first hike.  Funny name, a hoodoo.  It sounds like a name coined by a California surfer.  Regardless of the name's origin, a hoodoo looks like a rock mushroom of sorts.  The crown is composed of sandstone rock and the stem is comprised of clay sediment.  The unequal rates of erosion cause this odd, seemingly unstable structure.
<p>
When most people think of the Badlands, they think of the eroded formations.  Well, I've got news for them, the park itself holds so much more.  A good portion of it is actually grassy flatlands.  The geology of the area is rather interesting.  There's a lower and an upper grassland plain, and in the middle is where you'll find the eroding formations.
<p>
My hike today will take me from the lower plain, up through the formations, then to the upper plain.  It's fascinating to me just how quickly I will traverse the varied geological zones.
<p>
Are you ready to blast through multiple zones of geology with me in record time?  You are?  Great!  I'm off now, catch me if you can.
