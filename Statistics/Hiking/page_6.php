I've never spent much time in Maine, let alone in such a wonderful place as <a name='valid_link' href="javascript:myPopup5('https://www.nps.gov/acad/index.htm')">Acadia National Park</a>.  A crown jewel of America's Eastern Shoreline, the park's loftiest offering is the pink granite <xa href="javascript:myPopup6('http://www.acadiamagic.com/CadillacMountain.html')">Cadillac Mountain</a>.  She's not a tall mountain.  On her tippy-toes she barely stretches 1,530 feet skyward, but, she is special just the same.  How so?  The top of <xa href="javascript:myPopup7('http://www.acadiamagic.com/CadillacMountain.html')">Cadillac Mountain</a> is the small parcel of land within the U.S. that receives the first rays of the rising sun.  How cool is that?
<p>
My hike today certainly won't be fashioned around a sunrise summit effort.  It's afternoon now, and anyway, I'm not a morning person.  But, I may just make the effort to see the sunrise before I leave the park.  Doing so will give me bragging rights of being the first person to see the sunrise in the U.S. for a given day in my life.  Plus, I'm pretty tall.  Standing at 6'4", I'd probably be taller than anyone else who shows up for the same bragging rights, so, I'm sure to win!  Hmmm, maybe I should bring something to stand on, just to be sure.
<p>
