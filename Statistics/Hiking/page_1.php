<p>
This is my first "official" hike of the trip.  It's been a long time coming, because today is the 31st day of my trip.  Good Lord, you'd think I'd have hit a hiking trail eons ago, but no, biking has taken precedence.  In more ways than one, biking is more fun, but hiking is an enjoyable activity as well.  Bears certainly like it, running even more. Running gives them an opportunity to catching you.  Ahhh, just kidding.  I've been told that most bears are more afraid of people than we are of them. I know, it's hard to believe.
<p>
To mitigate a sudden, unexpected bear encounter, I'll be bringing along my new bear bell that'll hopefully alert them of my passage through their forested dining room.  The idea is they'll run away when they hear me jingling in the distance as I make my way down the trail.  Either that or they'll think Santa Clause has come early this year.  I wonder if bears eat reindeer?
<p>
Make no bones about it, my hike of Sepulcher Mountain is going to be a tough one, it'll be both long and high.  Throw in a couple of bear encounters and you've got yourself a great recipe for terror-filled, hardcore exercise.  Now that's exactly the kind of adventure meal I'm ordering from today's hiking menu.
<p>
I see my daylight is burning quickly, there's no time to waste, no room for haste.  I've got plans for another hike today as well as a tour of Yellowstone's Canyon Area.  So let's get this hiking party started.  Come along with me, but stick close, because the bears will be watching and waiting.
