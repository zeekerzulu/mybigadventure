<p>
While hiking in Adirondack State Park near Lake Placid, NY I have the pleasure of making the acquaintance of Alma and Hilde.  I catch up to them on a hiking trail that leads to a place called Marcy Dam.  At the time, Hilde are talking a picture of Hilde and as I pass them by Hilde asks me to snap a picture of them both.  I happily oblige and from there all three of us hike together and have ourselves a good little chat.
<p>
From North Carolina, Alma is visiting Hilde who lives not far away, in Tupper Lake.  Turns out Alma and Hilde's friendship traces all the way back to their childhood, both grew up near Munich, Germany.  They both met American military men, married, and emigrated to the States years ago.  Both have a multitude of children, Alma's live in North Carolina and Hilde's live in Oregon of all places (where I live).  Hilde has plans to move there to be close to her boys sometime within the year.
<p>
Sadly, both are widows, Alma being the most recent.  Her husband died about 6 months ago of cancer.  And being the good, caring daughter that she is, she has plans to move back to Germany for a while to care for her ailing mother. 
<p>
All in all they both are in great spirits.  Certainly the wonderful day has contributed to their good cheer. It's nice to see two people whose friendship has spanned the test of time.  Surely, Alma and Hilde's friendship will continue on strong, despite the soon to be increasing distance apart that life's twists and turns are aiming to take them.
