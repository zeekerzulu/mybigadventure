<p>
Winding down from a busy day of touring downtown Seattle on my mountain bike, I step into the <a href="index.php?action=Pics&name=Daily/20040712/50.JPG">Hopvine</a> for a brew and some great live music whilst updating the website via my laptop.  While feverishly working away on the laptop Ted appears on the scene and asks me if I'm "connected."  No, he's not wondering if I'm single, rather, he's wondering if I'm connected to the Internet wirelessly.  I say no, and from that point on we chat for a while.
<p>
Ted turns out to be a rather funny and animated person, an interesting conversationalist indeed.  We share a common thread of beer, live music (Hopvine is his favorite bar), computers, and pets.  He's a System Administrator for Puget Sound Energy, babysitting servers and stuff, mostly Windows and some Linux. He has 4 dogs, 4 finches, 4 betas, 1 cat, and a 90 gallon saltwater Reef Tank.  Ted and his girlfriend of 9 years spend a lot of time watching the fish tank (probably a better alternative to TV) and taking care of it. He says it's a fun but expensive, time consuming, and addicting hobby.  He tells me he doesn't recommend owning 4 dogs, however, it's complete insanity at his house. They are all Labs too, which means they're not small and they're somewhat hyper.  But, his love for the furry beasts inspired him to name his website after one of them (<a name='valid_link' href="http://www.theduker.com">www.theduker.com</a>).
<p>
Soccer is a passion for Ted and his girlfriend, they play 2 to 3 times a week.  They also spend a lot of time working on the house they bought 2 years ago.  Being a logical computer guy, the art of construction must come easy to him.  Last year he added a 11x11 patio and a 16x20 deck and is skilled in floor tiling and window installation.
<p>
