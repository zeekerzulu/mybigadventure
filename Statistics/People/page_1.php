<p>
While slowly riding my bike in Seattle, Washington near Pier 66 and looking for things to snap photos of, I encounter Alexander. He's sitting near the curb but I don't notice him until I pass by and hear the clicking and ringing of his manual typewriter.  Intrigued as to why someone owns a manual typewriter, let alone sits on the curb banging away on one, I turn around to investigate.
<p>
Turns out Alexander is typing out flash cards of inspiring scripture passages to help commit them to memory, although he jokingly claims early Alzheimer's and says he forgets more than he remembers. On one side he types a scripture passage and on the other the scripture's reference.  Alexander is homeless, but not in despair.  He has an interesting background.  College educated, he used to work for Microsoft as a technical account manager with a really healthy income, but his work entailed a lot of pressure and stress.  Over time, it took its toll.  Three heart attacks later and warnings from his doctor to get out of the business or die, he took the path of less stress.  We doesn't go into any details but 10 months ago he lost his place and has been homeless since.
<p>
He tells me he isn't worried about anything though, his trust is with the Lord.  In the past, the Lord has worked wonders for him, helping him beat a drinking addiction.  Alexander's goal now is to ready himself to minister to homeless folks who have drug or alcohol addictions.  His flash cards are an aid for him in preparation for his life's next journey.  I like talking to Alexander, he's a very interesting person.  I wish him well, he says he'll email me with an update, I hope he does.
<p>
<b>UPDATE:</b> Since meeting Alexander, I've managed to keep in contact with him via email.  On March, 29th, 2005, I received wonderful news from him.  He is no longer living on the streets and has secured employment.  Right on Alexander!
