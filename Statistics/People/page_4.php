Yesterday, Paula and her sister Rosemary were whale watching at Lime Kiln Point State Park on San Juan Island when I first make their acquaintance.  By chance, I happen run into them today on the ferry ride back to Anacortes, Washington.  I learn both are on a little vacation, Rosemary is in town from Connecticut to see Paula and and to soak up the sites in the San Juans.
<p>
Paula has been a Park Ranger since 1985, working primarily in the North Cascades.  She has a Masters in Environmental Education and is an Education Coordinator.  She loves to teach and travels to area schools to instruct the next generation on the wonders of the environment and how to ensure it stays wonderful.  I wish I could sit in on one of her classes, she proves to be a wealth of information.  We talk a bit about her work and how money is getting tighter.  The Park Service has to let go a number of seasonal employees this year to make ends meet.  Hope next year they can hire them back.
<p>
Rosemary is a marketing consultant for non-profits.  She likes to keep busy and is very social, loves to do volunteer work as well.
<p>
Paula has traveled all over the US and parts of Canada, Mexico, and the Cayman Islands.  She would like to visit Italy, Spain, and Greece someday.  Rosemary has traveled all over the US and parts of Mexico. She would like to spend more time discovering what Southern California has to offer.
