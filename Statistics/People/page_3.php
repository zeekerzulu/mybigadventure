<p>
Biking long distance can be exhilarating but it also makes one real thirsty.  My 50 mile tour of San Juan Island comes to an abrupt halt at the 24-mile mark when I come upon a lemonade stand at the side of a country road.  Turns out, Christine and Ingrid are selling not only lemonade, but cookies as well.  Having a distributed product line makes good business sense, especially in these times of economic stagnation.  Last year they also sold lemonade and apparently did a better business compared to this year.
<p>
Today they are selling regular lemonade (other days they sell pink and strawberry lemonade) so I step up and slap my money down on the barrelhead for a tall cool one.  The lemonade is good, made from a secret family recipe of powder and concentrate, it really hits the spot.  We chat for a while.  Both girls are heading into 8th grade, Christine goes to public school (class size 65) and Ingrid goes to private school (class size of 13).
<p>
There are a lot of farms on the Island and it's no surprise both girls live on family farms.  Both farms raise animals and Christine's family grows produce as well.  Last year was a poor year for their vegetable stand though, the sheep got into their 1-acre of plantings and wrecked the crop.
<p>
Since this is a travel website, I feel it's appropriate to ask about their traveling adventures.  Both Christine and Ingrid have traveled quite a bit west of the Mississippi, Ingrid a little more than Christine.  As for traveling futures, Christine would like to go to Hawaii some day and Ingrid would like to travel to South America because she loves hot weather.
<p>
Christine & Ingrid, thanks for the lemonade and keep up the good work!
