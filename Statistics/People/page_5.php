<p>
While walking around downtown Vancouver B.C. I meet Monica on the sidewalk, she's providing palm reading and tarot card services from a card table.  She has a shop across the way and likes to set up shop on the sidewalk to help advertise her services.  She has been in the business for 8 years (since she was 13) and tells me she is the 6th generation to provide such services.
<p>
I've never had my palm or tarot cards read before but figure my time is due.  This trip of mine is partially about self-analysis, so why not enlist the help of Monica.  She's a little hesitant at first to let me snap a picture of her (past bad experiences) but lets me after we chat for a bit and I give her my business card advertising my website.  I decide to go with the tarot card reading because it provides more detail than the palm reading.
<p>
I'm told to shuffle the tarot card deck and select 10 cards.  The 10 cards are good ones (no devils or demons) and indicate a number of things about me.  First, I will live a long, healthy life, and in the end, I will find peace.  I have an old spirit that gives me the fortitude to handle adversity alone, I'm a very independent soul.  I will not be rich, but rather economically comfortable, this'll happen because of good saving habits.  I have to watch who I tell my secrets to because people are talking about me behind my back.  There's a move for me in the near future and I have a healthy, positive aura.
<p>
Funny thing is, of all the 10 cards I pulled, nothing speaks of love relationships.  Because of this, I have to pull 2 more cards from the deck and one of them is the soulmate card.  Apparently, in the past a soulmate crossed my path, but I failed to recognize her as such.  Since I didn't pull anything about a love relationship in the first 10 cards, this indicates a current negativity about the love relationship aspect of my life.  No time soon will I be finding anything serious, my focus is more about freedom and adventure.  Hmmm, that's what my trip is all about, seems like I'm on track.
<p>
Focusing solely on my own self-analysis, I neglect to ask Monica where she's traveled to and what places in the future she'd like to visit.  If you ever read this Monica, please email me this information, as well as anything else you'd like me to say about you in this profile.
