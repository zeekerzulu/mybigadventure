<p>
I cross paths with Ranger Jim Lovelace at Badlands National Park in South Dakota.  Jim has had a passion for nature for a long time, going all the way back to his childhood.  His family moved to Tennessee when he was in third grade, and as fortune would have it, his folks moved right next to a large park.  From that point forward, Jim's family knew he was going do something park related, he was always playing in the park.
<p>
Jim was formally introduced to the National Park Service when he became a Junior Park Ranger.  His interest in nature increased over time to the extent that he graduated from Middle Tennessee State University with a degree in Outdoor Recreation and Public Land Management.  4 years ago he interned for a summer in the Badlands, under the "Badlands in the Classroom" program.  Since then he has been working 9 months out of the year for the National Park Service in the Florida Everglades and in the summer he heads to the Badlands for a 3 month tour.  He said the best way to get into the Park Service is to either volunteer or do an internship.
<p>
When I meet Jim he's working on plans to spend the next few summers in Olympic National Park in Washington State.  One of his goals, formed at the outset of his career in the National Park Service, has been to float around in the summers, staying at a particular park for a few seasons to learn all he can about what a particular park has to offer.
<p>
Having spent the last 3 summers here in the Badlands, his presentations and tours are really quite polished and very informative.  The man is not only enthusiastic about the Badlands, he is also chocked full of great information about the area.  I can see he's a good, attentive student of the Badlands.  He knows much.
<p>
Jim is a hulk of a man and has a big presence.  He played football and rugby in both high school and college.  I can see him wrestling one of Badland's big horned sheep.. and winning!
<p>
Jim has traveled extensively in the US, having spent a good chunk of that time exploring the west and southeast.  Jim would like to travel to Olympic National Park (his next summer gig), areas in Utah, Bighorn National Park in South Dakota, and the Bitterroot Mountains in Idaho and Montana.
<p>
So, the next time you find yourself at one of the National Parks, keep an ear open for the name of Ranger Lovelace.  And if by fortune he is indeed at the park, do yourself a big favor and attend one or more of his presentations or hikes, you'll be glad you did.  I know I was.
