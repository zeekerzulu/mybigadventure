<p>
While mountain biking Gold Hill North Trail near Sandpoint, Idaho, I meet Katie and Ron.  They're both taking a little rest break on their way up the trail, while I'm on my way down, all jacked up from my thrilling and fast downhill singletrack riding.  I notice they're both riding full-suspension bikes called "boing, boings" in mountain bike lingo. All the while, my ride sulks a bit after being called a "hard tail" by my new acquaintances.  However, I don't mind at all, they're comparing me to Peter Fonda in Easy Rider, his bike, Captain America, was a "hard tail."  It's a compliment, I'm in good company.
<p>
Katie & Ron are acquaintances themselves.  Ron is in town on vacation from Alberta, Canada with his family and Katie is from Naples, Idaho and is in the area seeking biking adventure.  Apparently, they met up with some roadies (slang for road bikers) but they were the only folks riding mountain bikes, everyone else had a road bike.  So, as I understand it, they rode with the group for a while, but broke off at the start of this trail's trailhead and together headed up hill and into my life.
<p>
They reminisced about past bike injuries.  Ron expressed concern about catching some hell from his better half if he hurts himself on today's vacation mountain biking.  In the past, he's broken a collar bone and some ribs.  Katie pipes in and rells me about doing a superwoman (slang for a woman flying over the handlebars when the bike suddenly stops but she doesn't) less than 2 weeks earlier and hurting her ribs. She wonders whether or not she broke anything because they still hurt her.  But, being the tought biker she is, she forges ahead with a bike ride on this beautiful, sunny day.
<p>
Before departing Katie asks me to mention she and a couple other folks just formed a local biking club called the Pondaray (spell?) Peddlers.  Not sure if they have a website yet.  But, with Katie's enthusiasm and passion for cycling, I'm sure it'll be a success.  Good luck.
