<p>
I have the good fortune of meeting Dave and Jana atop Sepulcher Mountain in Yellowstone National Park.  I first notice that couple is following me as I crest the mountain top, they're about a 1/4 mile behind.
<p>
Once at the top, I review the trail information I brought along and immediately determine it fails to match what I'm seeing, so I wander around a bit, searching in vain for any remnants of the trail as it supposedly turns south.  Having failed to find the trail, I walk over to the couple who are then sitting and enjoying the view.
<p>
That's when I meet Dave and Jana from Regina in Saskatchewan, Canada. After inquiring about the trail, it appears we're both unsure about where it disappeared to.  We decide to team-up and make an attempt to find the lost trail.  During our hike down, I learn the couple, having met in college, have been married for 5 years. Jana tells me there was an instant connection between the two of them when they met and that same chemistry is still going strong today.
<p>
Jana has been a grade school teacher for a while now and this coming year will be teaching 2nd and 3rd graders instead of her usual 7th graders.  She quips she'll have to reign in her sarcasm since she'll be working with younger children.  Dave, on the other hand, has gone back to school to get a degree in teaching and he'll finish his studies in less than a year.  The couple wants to teach abroad and are flexible as to where they will go.  Jana says she would like to travel to India someday, so perhaps with a little luck, they'll land some work there.
<p>
Dave and Jana have extensively traveled America's West Coast and parts of Canada.  They are on their way to Utah to try their hand (and feet) at a sport called canyoneering.  That's the sport where you traverse very narrow rock formations and may climb as high as a hundred feet.
<p>
I really like Dave & Jana, too bad I won't have another opportunity to hike with them.  Maybe we can stay in touch via email, I'd like to find out where in the world they eventually find work.
