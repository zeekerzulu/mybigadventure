While biking the Centennial Trail near Spokane, Washington, I make the acquaintance of 4 fellow riders. They tell me they all left Port Townsend, Washington many days ago and are on their way to Great Falls, Montana.  I learn they passed through the North Cascades via SR-20 just as I had, I probably passed them on my way to Spokane.
<p>
John (second picture) is the group's leader.  A highschool math teacher of 30 years from St. Paul Minnesota, he planned the 2 week trip and recruited past student Patrick and Patrick brought along his friend Adam (first picture) and Adam's father John.  In the past John has biked a few tours.  His most impressive tour was in 2000 when he biked from Portland, Oregon to St. Paul, Minnesota, now that's some serious distance.
