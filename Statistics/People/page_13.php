I run into this motley crew in a small town park in Cody, Wyoming.  I'm in the park when they arrive and after settling in they really start whooping it up down the way.  I actually laugh a few times at what they are saying, being close enough to be within ear-shot and them being loud enough to be easily heard.
<p>
I meet Marc first as he's returning from the public restroom.  Thinking he's a local, I ask him about the Cody Nite Rodeo, where to buy tickets, and where the rodeo arena is located.  He tells me all I need to know and after exchanging names he goes on his way, back to the rowdy party.
<p>
While leaving the park, I drive by their <a href="index.php?action=Stats&stat=Oddities&date=20040816&page=16">pickup truck</a> and notice there's writing all over it (WARNING: if easily offended, DO NOT CLICK THE LINK).  In black marker someone or perhaps many people have penned various quotes and prose.  Now that seems interesting to me, so I go to over to investigate and get the full story on this odd happenstance.
<p>
That's when I meet the entire crew.  Kevin, Chris, and Marc were from Olympia, Washington, passing through on their way to Key West, Florida.  Kristie is a local who's just hanging out for the day.  There arw a couple of other local folks hanging out as well but I'm not introduced.
<p>
Seems Kevin, Chris, and Marc are homeless, Kevin for one year and Chris and Marc (brothers) for eight months.  Chris tells me opportunity is knocking in Key West for them all.  His Uncle owns a charter boat in need of a captain.  Idle for the past eight months, the three of them are going to Florida to make a go of it in the charter boat business.  When I ask Chris about Hurricane Charlie and what impact it has had on the Keys, Chris says he heard about the hurricane but doesn't want to know all the details, he just wants to get down there and get to business.  I hope for his sake and the other two that the Uncle's boat is still in one piece.  I think they don't want to know, because if by chance the boat is lost, they will have to cut their adventure short, knowing the opportunity is no longer there for them.
<p>
