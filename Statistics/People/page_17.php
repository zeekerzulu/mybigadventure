<p>
While hiking up Cadillac Mountain in Maine's scenic Acadia National Park, good fortune smiles upon me and I run into Laura and Jonathan.  From Cape Cod, they too are in the area for a few days, both thoroughly enjoying the sightseeing opportunities Acadia has to offer.
<p>
Like me, they are on their way up the mountainside, so we decide to team up and chat while continuing on with our ascent.  I learn Laura, an 11th generation Cape Codder, has had an interesting past, checkered with horses, massage, and landscaping.  An accomplished horse rider, apparently back in the day she was a member of the US Olympic Riding Team.  To pay the bills, years ago she was employed as a massage therapist but now owns and operates a landscaping company called <a name='valid_link' href="javascript:myPopup3('https://web.archive.org/web/20041009195937/http://capecodtoday.com/floralinnovations/')">Floral Innovations</a>.  After browsing her website, it's pretty obvious this woman is packing some floral talent given her 10 years in the landscaping business.
<p>
Jonathan is a life-long resident of Cape Cod as well.  Working for 5 years as a short order cook and now employed as a land surveyor, he has plans to go to school for massage therapy, possibly studying in Thailand.
<p>
Laura and Jonathan met 4 months ago when her landscaping and his surveying intersected at a jobsite.  Moving 4 months henceforth and looking at the two of them now, I can see they've got a pretty nice little thing going on, for I sense much good energy between the two.  Good for them!
<p>
I really enjoy chatting with them, both prove to be really friendly and energetic.  After we reach the mountaintop we say our goodbyes then go our separate ways.
