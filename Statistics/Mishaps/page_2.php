I've found that wearing a watch is a very useful thing, especially when you go biking.  So, wearing it on my trip's first bike ride (<a href="index.php?action=Stats&stat=Biking&date=20040709&page=1">Lewis River</a>) is no exception.  I strap on my good ole watch and off we go.  I check my watch from time to time so I know, well, the time of course.  At one point during the ride I look down and guess what?  Exactly! My bike computer has convinced my watch to take a mini-vacation as well.  Earlier in the ride I lost my bike computer but went back and luckily found it.
