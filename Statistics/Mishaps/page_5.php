I wish I could say I was riding 30 mph and fell off the bike when I heroically veered to avoid a small child that wandered onto the bike trail, but no, I cannot.  Rather, the bike is not moving at all, it is stationary, and I'm attempting to take a picture of the Spokane River.  One foot is clipped into one peddle, the other is not.  I twist around to take a second shot of the river and lose my balance.  I can't get my clipped-in foot unclipped in time, so in slow motion I fall over on my knee.  It looks worse than it is.  The important thing is no one on the path saw me fall.  Nothing worse than looking stupid in front of strangers.
