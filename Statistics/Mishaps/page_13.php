<p>
While mountain biking Whiteface Mountain in Adirondack State Park near Lake Placid, NY, I manage to have a little incident on the bike, or rather, off the bike.  While going down a steep singletrack trail I have no business being on (I'm a newbie to mountain bike riding), I fly over my handlebars head-over-heads after hitting a large rock with my front wheel.  It's just amazing how quickly these things can happen.  One second you're cooking right along without a care in the world and the next second you're on your back.
<p>
I manage to scrape up my left shin and elbow pretty bad.  It happens on my 4th run down the mountainside and is my signal to quit for the day.  This is similar to how I ski.  Near the end of the day when I'm getting tired skiing down the slopes I usually take a pretty nasty spill.  Whenever that happens, I always call it the day.
<p>
The last photo is the next day after my accident.  It has scabbed over nicely and is now only uncomfortable when I slept on my left side.
