<p>
Basically, picture a redneck in a pickup truck on the above stretch of parking lot.  While driving, he holds onto a cart with his left hand, speeds to the curb, releases the cart at the last second, veers his pickup away from the curb, and the cart crashes into the curb.  Get it?  Stupid, eh?
<p>
<center>
<a href="index.php?action=Pics&name=Daily/20041022/DSCN0010.jpg"><img src="Pics/Daily/20041022/Small/DSCN0010.jpg"></a>
</center>
<p>
Sadly, this is the place where the cart met its demise.  It hit so hard it actually chipped the curb.
<p>
Curious to find out if this crashing of carts is some sort of underground sport, I take to the Internet.  Unfortunately, after much searching, I find nothing.  However, I do find this <a href="javascript:myPopup1('https://web.archive.org/web/20040423154146/http://www.rabidhardware.net/index.php?id=27')" name='valid_link'>amusing writeup</a>.  It's a shopping cart racing extravaganza of sorts, 4 guys test drive 3 different kinds of carts (Home Depot, Walmart & Safeway) and post their results.  Good stuff!
