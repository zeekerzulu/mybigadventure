<p>
Ever get a muscle cramp when you're sleeping?  Do you know how to uncramp it to gain instant relief?  Well, it's pretty easy, you just stretch the muscle and its involuntarily contraction relaxes.  Now, that's all fine and dandy, that'll take care of your garden-variety cramps.  But, what happens if opposing muscles severely cramp at the same time?
<p>
<center>
