<p>
Well, after a day of strenuous mountain biking, I find out exactly what it's like on my second night of the trip.  I wake to massive cramping, both my left calf as well as the muscle that's next to my shin bone on the other side of my leg are in a tug-of-war for my attention.
<p>
What does one do in such a situation?  Relieving one of the muscles by stretching it may further aggrevate the other.  However, I'm forced to pick one of the muscles to stretch because it's impossible to stretch both at the same time.  I have to choose wisely. I toss the dice and choose my shin muscle to stretch.  Luckily, my cramped calf isn't upset with my ignoring it, and I end up quieting the pair by spilling out of bed and sitting on my legs with my shins on the floor and my feet pointing backwards. Will I be sore tomorrow from all this cramping?
<p>
I wake in the morning and discover I'm good to go, my muscles are back on task and making nice with their owner. I'm free to pursue my next adventure.
