Early in the morning I'm pulled from my slumber by a thumping, bumping noise.  What could the noise possibly be?  After throwing on come clothes, I sleepily spill out of the van's side doors to investigate.  OH MY GOD! I'm parking lot camping next to a funeral home on wheels! When I went to bed earlier in the evening, I recall hearing a large truck park beside me. I didn't think anything about it.
<p>
Could that bumping, thumping noise I heard have come from this truck? God, I hope not. 
<p>
According to this <ax href="javascript:myPopup1('http://www.vfda.net/pressrelease_thackerexpansion6_9_05.html')">article</a> on the Internet:
<p>
"Thacker Caskets, Inc. has experienced unprecedented sales growth in recent years with unit volume up 76% since 1999. Vice President of Sales & Marketing, Michael Beardsley says that they like to refer to themselves as “the Southwest Airlines of the casket business”. He continues, “quietly, Thacker Caskets Inc. has grown to become America’s 4th largest casket manufacturer and 2nd largest family owned casket maker”."
<p>
Now that's strange.  I thought more and more people were getting cremated these days. So, what's up with their hefty increase in sales?  I don't see anything in the article about them transporting the dearly departed in their company trucks. Apparently, the noise I heard came from somewhere else... or did it?  Hooo Hooo Haaa Haaa Haaa! (evil laughter)
