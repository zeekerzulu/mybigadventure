After eating breakfast at McDonalds in Albion, NY, I leave the restaurant and notice Ronald McDonald is waving a fond farewell to me.  But something just isn't quite right with old Ronald, he appears to be hide something.  The first photo shows he's hiding his left hand behind his back.  What is he doing?
<p>
Curiously, I approach Ronald and take a look at him from behind.  Well, no wonder, poor Ronald has had an accident.  And his left arm is just too short to cover things up.  Seems like maybe he's had one too many strawberry shakes?  But, I have to give him credit, he's a real trooper.  Despite his embarrassment and failed attempt at concealment, he's still all smiles and waves.
