I manage to run afowl with the law in Rapid City, South Dakota.
<p>
While parked in a neighborhood and uploading content updates to the website on a borrowed Internet connection, I receive an unwelcomed visitor. It's a resident, demanding do know what I'm doing in the van.  I tell him my story and mode of operation, he takes my business travel card and leaves in a huff, saying he'll be checking out my site.
<p>
After completing my uploads, I pull out of the neighborhood and make my way to a nearby car wash to wash the van. That's when two police cars pull me over.  I somewhat surprised the resident ratted me out, even after talking with the guy and him saying he'd look at my website.  What a clown, but I guess the joke is on me.
<p>
I roll down the window and begin to explain to the officer what I'm doing in the neighborhood.  He quickly cuts me off and pipes in, telling me there have been problems with people hyjacking Internet connections to surf child-pornography.  Geeze, you gotta be kidding me! The officer is 1/2 accusing me of surfing child-porn. I start to wonder if they'll confiscate my laptop. If they do I could be stuck in Rapid City for days, waiting to get it back. God, I hope not.
<p>
I keep my cool (what else can I do) and just go along with his little interrogation.  In the end, I get my license back and am asked when I'll be leaving town.  Well, that's a nice thing to ask.  I tell him I can leave town ASAP but would prefer to stay another night before heading out to the Badlands, as it's late in the day.  He tells me if I plan to overnight again then I need to park in a different neighborhood.
<p>
I have to admit, I wonder what would happen if I parked back in the forbidden neighborhood tonight? I suppose I'll have another mishap to write about tomorrow, eh? However, I find police interrogation a rather unpleasant experience so I think I'll take a hard pass on that idea.
