Ahhhh, biking.  That activity was the initial theme of my cross-country trip.  The plan was to spend 3 months on the road, with the lionshare of activity directed towards biking.  But, time just flew on by, and after 3 months I found myself in Vermont in early October with only 25% of my trip under my belt and way behind schedule.  Yikes!  So, a shift of gears was in order and my trip's theme migrated toward sightseeing, no more travel writing, and certainly no more biking, it was getting too cold.  I'm a fair weather biker after all.
