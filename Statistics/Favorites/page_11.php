On my trip I saw a handful of very inspirational memorials.  Not surprisingly, all, save one, are in Washington, DC.  Memorials are, by far, the most emotional-packed venues on anyone's sightseeing list.  A few times, while touring the various war memorials in DC, I would find myself tearing up a bit, feeling a bit overwhelmed by all the human pain and suffering so elegantly encapsulated within the memorials.  Alternatively, I found the presidential memorials inspirational, showing me a glimpse into the character and soul of so many great men long since past.
<p>
It's really is a wonderful thing, this concept of memorials.  Like history written with pen and ink, memorials are written in stone, erected to remind us of all the people and events that have shaped our country, our world.  May we never forget them, may we always learn from them, and may we persist to stand tall upon their strong and wide shoulders.
