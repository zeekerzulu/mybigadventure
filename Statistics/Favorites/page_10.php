What exactly is a monument?
<p>
According to www.dictionary.com it means:
<p>
Monument (m<img src="Graphics/obreve.gif" height="15" width="7" align="bottom">n<img src="Graphics/prime.gif" height="22" width="4" align="bottom">y<img src="Graphics/schwa.gif" height="15" width="6" align="bottom">-m<img src="Graphics/schwa.gif" height="15" width="6" align="bottom">nt) - 1) A structure, such as a building or sculpture, erected as a memorial. 2) An inscribed marker placed at a grave; a tombstone. 3) Something venerated for its enduring historic significance or association with a notable past person or thing. 4) An object, such as a post or stone, fixed in the ground so as to mark a boundary or position.
<p>
I saw many different monuments on my trip.  From a volcano, to a cave, to a war memorial, to a desert theater.  I must admit, I had experienced a good stretching of the definition of monument on my trip.  But, it was all good, all monuments were interesting and each had unique a character all its own.
