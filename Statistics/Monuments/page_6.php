Taking over 37 years to build and plagued by controversy, the Washington Monument is a heightened tribute to <a href="javascript:myPopup3('http://www.whitehouse.gov/history/presidents/gw1.html')">George Washington</a>, America's first President.  Rising 555 feet skyward, the monument is a far cry from the original designed proposed by architect <a href="javascript:myPopup4('http://en.wikipedia.org/wiki/Robert_Mills_(architect)')">Robert Mills</a>.
<p>
The original plan was to also build a circular colonnaded building 100 feet high and 200 feet in diameter, from which the obelisk was to take root.  Inside this circular pantheon, a repository for statues of Presidents and national war heroes was planned, topped off with a massive statue of Washington himself.
<p>
For a variety of reasons, the monument was whittled down a bit in both scale and scope.  However, the resulting structure is certainly nothing to sneeze at.  Dominating the Washington D.C. skyline, it provides spectacular views of from its soaring, observation deck.
<p>
The monument is closed today, so all I can do is take pictures of it at a distance.  No worries though, my tour of the monument will go on uninterrupted, I'll just have to talk more about its storied history.  Are you ready to learn more about this tall pointy structure?  Yes?  Well, come with me.
