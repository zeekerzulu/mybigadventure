At Pilgrim Memorial State Park in Plymouth, MA, you'll find a magnificent and colossal solid granite monument.  Inspired by Victorian era beliefs and values, 69 years after initial conception, on April 1, 1889, the monument was finally dedicated to America's Forefathers.
<p>
The monument itself is a composite of many things.  Most prominent is the central figure, Faith, who weighs 180 tons and stands 36 feet tall.  Looking downward as if addressing a crowd, with one foot placed solidly upon <a href="index.php?action=Stats&stat=Sites&date=20041023.1&page=26">Plymouth Rock</a>, she holds an open Bible in one hand and points to the Heavens with the other on an outstretched finger that measures well over two feet long!  She seems to be telling the masses that they would be best off it they placed their trust in God.
<p>
Sitting around the 45-foot pedestal are the 4 ancillary figures of Morality, Education, Law, and Liberty, each weighing in at a hefty 20 to 25-tons and standing approximately 15 feet tall.  Together, they represent the 4 most important principles upon which the Pilgrim Forefathers wished to found the new American Commonwealth.
<p>
Even from a distance the monument looms large and impressive.  Come with me, and together let's explore this inspirational memorial to America's Pilgrim Fathers.
