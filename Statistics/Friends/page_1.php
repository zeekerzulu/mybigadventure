<p>
Gil is one of my closest friends.  I've known him for going on 6 years now, 
initially meeting at Sequent Computers in Beaveron, Oregon.  At that time, I was an orphan of 
sorts, my computer talents weren't being used to their fullest.  Realizing this, he came to 
my rescue, pulling me into his workgroup and effectively under his wing.  From that point on, 
a friendship immediately catalyzed and then, over time, solidified between us.
<p>
I consider Gil as a mentor of sorts.  He's a renaissance man, well-versed, knowledgeable, and 
talented in many things big and small.  I've always enjoy talking with him and learning new 
things from him about the world around me.  The man has a certain disarming charm about him, always 
helpful and willing to go the extra mile to help out a friend.  He's very passionate about 
the outdoors and is an avid steward and supporter of environmentally friendly practices.  He 
loves to immerse himself in outdoor activities including skiing, biking, and 4x4ing in his 
tricked out Jeep CJ5.
<p>
Just to give you a small glimpse into how he has positively influenced my life, I only have 
to look at the trip I am on now.  In preparation for my trip, I needed help figuring out my 
options for an RV.  I put out an SOS and Gil came to my immediate aid, shared with me his 
experiences building a camper from scratch.  Additionally, he tipped me off about the State 
of Oregon's practice of liquidating their surplus vehicles on eBay.  Without his sage advice 
and support, I never would have found the wonderful <a href="index.php?action=Pics&name=vanProfile1.jpg">van</a> that I did and I never would 
have spent quality time with my father and mother building my <a href="index.php?action=Build-A-Camper">camper</a>.
<p>
Gil is a lucky man because of his better half, <a href="index.php?action=Pics&name=Friends/GilAndWilla.JPG">Willa</a>, keeps him out of trouble.  Willa is a proposal writer for Getronics in Liberty Lake, Washington.  Meeting through friends, they have been together for a little more than one year now.  Willa is a very sweet, easy going woman, who has an endearing affection and open heart for animals, both great and small.
<p>
Currently, Gil is pursuing a new career in real estate.  Only in the business for 6 months, he has been generating some impressive momentum with his creative ideas and people 
winning ways.  I predict he'll be very successful in the business indeed.  All he has to 
do is just be himself and everything else will fall into place.
<p>
Unfortunately, there is some distance between us now, Gil living in Spokane, Washington and I living 
in Portland, Oregon. Fortunately, it hasn't had any affect on the quality of our friendship.  I always 
look forward to visiting or being visited by him.
