Sofia is a bundle of fun-filled energy.  Passionate, talkative, enthusiastic, these are just a few words that describe her bubbly personality.  We met at work, National Fuel Gas, sometime around 1991, and she was immediately recruited by yours truly to join <a href="index.php?action=Stats&stat=Friends&date=20040905&page=3">Dan</a>, <a href="index.php?action=Stats&stat=Friends&date=20040908&page=3">Tim</a>, and a cast of many others, to partake in our weekend outings to the various dance clubs sprinkled in and around Buffalo, New York.  I think all of us would agree, those times were some of the very best.
<p>
I never had the pleasure of working with Sofia, she always worked in a different group within the IT Department, but that didn't hinder my getting to know her better.  Between the weekend dance club outings and having lunch from time to time during the workweek, our friendship grew stronger.  In the process, I came to appreciate her kind nature and gentle heart.
<p>
Always cracking a joke with an accompanying smile, Sofia can be serious as well.  She is a hard worker, both in the workplace and at home.  She is now the proud mom of three boys.  If memory serves me correctly, I think she was expecting with her first child and was close to the delivery date when I made my escape from Buffalo.  Her partner in domestic crime is her soulmate Ziggy, who not to long ago built the family a new home out in the country.
<p>
Every once in a while Sofia and I will swap email banter, some things just never change.
