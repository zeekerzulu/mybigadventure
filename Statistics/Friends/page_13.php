<p>
I've known Bill for the better part of 15 years now.  We met way back in the day at an old workplace in Buffalo, New York, we were both programmers at the time, working on the same project.  From the start I enjoyed Bill's humor and knowledge of many things great and small.  He used to be a volunteer tour guide for the American Museum of Natural History (the largest museum in the world) in NYC so he's filled to the brim with interesting facts and information about history and such.
<p>
Early on we spent a good measure of time together in the pursuit of outdoor activities, including hiking, backpacking, camping, and canoeing.  Before I moved west, Bill and I visited New York's Adirondack State Park numerous times.  Together we climbed the various mountain offerings there, including Algonquin, Phelps, and Whiteface Mountain.
<p>
Bill has an interesting educational background.  He holds 3 degrees; BA in International Affairs, BS in Biochemistry, and MS in Computer Science.  He is currently employed as a computer analyst for a financial software firm in Boston, Massachusetts.  I have to say, Bill is really good at what he does.  But, don't ask him, his modesty would never acknowledge such a happenstance.  Bill really excels in the areas of troubleshooting and bug fixing.  Fortunately, Bill can telecommute from his home in Southern Maine, and only has to visit the Boston office just a few times a month.  Since he works from a home office, I get to visit with him on his breaks.
<p>
Born and raised in Kittery, Maine, fresh out of high school Bill joined the Navy and served for 6 years, 4 of those years in the Navy Reserve.  Unfortunately, while in the service Bill didn't partake in international travel.  That, however, would come later in life with trips to the cities of Montreal, Paris, and London.  He's spent some time in various areas of the US as well - New York City, Colorado, Montana, Oregon, Minnesota, and Western New York.
<p>
Needing to be near his ailing mother, in 1996 Bill moved back to Maine from Buffalo.  Since moving to Maine, I've visited Bill twice and he's visited me once in Portland.  From time to time we chat on the phone to retighten the bonds of friendship and to talk about things of interest and passion.  Bill's passions include old movies, formula one racing, shooting, biking, and hiking.
