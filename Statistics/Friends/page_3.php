<p>
Ever have one of those friends who you'd do anything for, at any time, on any day, for any reason?  Well, Dan is one of those few, precious friends.  Heck, I'd help him load bodies into a car trunk if he asked me to.  Dan is one of the funniest, thoughtful, considerate, and giving people I know.  He never forgets to call or send a card on my birthday.  He is the only person who, from day one, I have kept in constant contact with since leaving Western New York 8 years ago.  I consider him the brother I never had.
<p>
I've known Dan for almost 13 years now, we met years ago at National Fuel Gas in Buffalo, New York.  Both of us were hired at the same time and soon thereafter we found ourselves hanging out together, especially at lunch time.  The first thing I noticed and liked about Dan was his humor.  Early on he exhibited an infectious, quick wit, and creative mind.  On many of those early lunch outings I really busted a gut listening to him.
<p>
Over time we grew closer as friends and started doing fun things after work.  I remember one time we both bought acoustic guitars and took lessons at the community college.  We didn't get very far with our playing, but regardless, we had a lot of fun trying.
<p>
Halloween was another favorite, fun-filled activity.  One year we dressed up as Hans and Franz (the Saturday Nite Live "Pump-You-Up" Guys).  We used packing peanuts to stuff our gray gym sweats but I sensed something was missing.  I recall we were getting ready at Dan's apartment and I spied a rolled up pair of his gym socks, the really long kind that go up to your knee.  Well, I had a revelation that not only should Hans and Franz be very muscular but also well endowed.  So we packed our man-hoods and headed out to a friend's house party.  At the end of the evening, we found ourselves at the Marriott, on stage, competing for a prize in a Halloween costume contest.  We didn't win a prize, but we certainly had a lot of fun with the crowd.
<p>
One of my fondest memories I have are of all the times we went out clubbing with the "crew."  There were about 8 of us and almost every weekend we would hit the dance clubs and/or bar hop.  Since bars close at 4am in Buffalo, we would close the bars then go out of an early breakfast.  Sometimes we wouldn't get home until 7am.  Yes, those were the days.
<p>
Before I left town for Portland, Oregon, Dan met a wonderful girl.  Pam and Dan fell in love and eventually they wed, but not before I was invited back to Buffalo to be Dan's best man.  It was such an honor to stand up for Dan.  That was 5 years ago, how time flies.  Since then Dan and Pam have had two great sons, Donald and Daniel.  Derek, Pam's son from a previous marriage, is part of the crew as well.  During my visit I enjoyed meeting and hanging out with all the kids.
<p>
I hope someday Dan and Pam can come out to Portland for a visit.  I miss spending time with Danny.  But, you can be rest-assured, that we will continue to be friends, through thick and thin.
