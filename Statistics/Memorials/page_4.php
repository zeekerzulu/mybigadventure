Commemorating America's least popular war, the Vietnam Veterans Memorial pays tribute to the 58,249 deceased and missing American military service personnel who paid the ultimate price in a war that played out far from America's shores.
<p>
Due to the controversial nature of the conflict, no attempt was made to model the memorial against a backdrop of political statements.  As a means to that end, a minamalist, nonpolitical design by 21 year old artist <a href="javascript:myPopup4('http://ohiobio.org/lin.htm')">Maya Ying Lin</a> was selected from a pool of over 1400 design submittals.  After a bit of controversy, construction of the memorial at the foot of the Lincoln Memorial was finally thrown into motion in the spring of 1982.
<p>
Rewinding back 3 years earlier to 1979, Vietnam veteran <a href="javascript:myPopup10('http://www.vvmf.org/index.cfm?sectionID=46')">Jan Scruggs</a> had a revelation.  Fund a national memorial to commemorate Vietnam's fallen and missing through public donations.  Forming the Vietnam Veterans Memorial Fund (VVMF) shortly thereafter, Scruggs and a group of fellow Vietnam veterans were initially the butt of jokes.  Many thought Scruggs was crazy, believing that no one in their right mind would want to memorialize an unpopular war.  However, the VVMF persevered, and in the end collected more than $8.4 million in private donations from more than 275,000 individuals.
<p>
The <a href="javascript:myPopup5('http://www.nps.gov/vive/memorial/wall.htm')">Memorial Wall</a> itself is quite expansive.  Covering over 493 feet and reaching a height of more than 10 feet at its midsection, the overall shape of the symmetrical wall is a tapering of sorts.  The midsection high point gradually decreases along two opposing arms, both reaching outwards and concluding to a point at reaches end.  Build of black granite from Bangalore, India, the memorial contains 70 separate inscribed panels, plus 4 at each end without names.  The inscribed lines per panel varies with its height, running between 1 to 137 lines.  The number of names per line runs a fairly constant 5 to 6 names.
<p>
Initial reactions to the memorial were not all good, many believed it failed to properly honor the veterans due to its terse and morbid design.  In response to the criticism, a compromise solution was put into place.  In 1984, the <a href="javascript:myPopup6('http://www.nps.gov/vive/memorial/servicemen.htm')">Three Servicemen Statue</a> was erected near the entranceway to the memorial.  Nine years later, in 1993, the <a href="javascript:myPopup7('http://www.nps.gov/vive/memorial/women.htm')">Vietnam Women's Memorial</a> was placed to honor all the women who valiantly contributed to the war effort.
<p>
Given all that I've learned from reading up on the history of the memorial, I can't wait to see it in person.  Come with me as I venture a visit to this long overdue tribute to the fallen and missing soldiers, to those who played a fateful part in a war that was filled with so much controversy and disillusionment.
