Of all the sculptures in Washington, D.C., the memorial to Ulysses S. Grant is one of my favorites.  The memorial is massive in stature (252 feet long and 70 feet wide), easily taking the prize as the largest statuary group in Washington.  However, it is not it's size that captivates my imagination, rather, it's the sculptors fine attention to detail with the sculptures themselves that pull me into the Civil War, into the emotions of that grand and fateful struggle.
<p>
The memorial itself is comprised of many different elements.  Most prominent is the brilliant Civil War Veteran General Grant atop his favorite horse, Cincinnati.  Around Grant and his trusty horse, reclined at each corner, you'll find 4 noble lions.  Located to Grant's left is "The Cavalry Group" sculpture, to the right is "The Artillery Group" sculpture, and on both sides of the pedestal supporting General Grant you'll find two large panels depicting "The Infantry Group."
<p>
The memorial took artist <a href="javascript:myPopup4('http://www.henrymerwinshrady.com/introHMS.htm')">Henry Merwin Shrady</a> the last 22 years of his life to complete.  Shrady conducted an immense amount of research designing the memorial, including conscripting folks from West Point to perform special drills to assist him in his study.  The sculptures are made of bronze and have long since turned a dark green from their original golden brown as a result of the ongoing effects of oxidation.
<p>
Hey, join me, I'm about to tour this spectacular tribute to an individual who was both a fine military general as well as the 18th President of the United States.
