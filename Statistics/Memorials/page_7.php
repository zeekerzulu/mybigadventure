<b>Design Architect:</b> Lawrence Halprin
<p>
<b>Highlights:</b> 7.5 acres of space, 4,000 granite blocks, a multitude of inspirational sculptures, a myriad of famous quotes, chronicles the life and times of the FDR as America's only four-term President.
<p>
<b>Lowlights:</b> Existing controversy between the builders of the Memorial and certain handicap advocacy groups surrounding the Memorial's attempt to reconcile the history of FDR hiding his disability from public view.
<p>
