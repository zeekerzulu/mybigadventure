Filling tenure as the American President during the throes of the Great Depression, followed by total immersion into the trying times of World War II, the Franklin Delano Roosevelt Memorial pays homage to Roosevelt's extraordinary efforts at holding together an imperiled Nation.
<p>
Born of wealth and privilege, Roosevelt learned at an early age that wealth brought with it the responsibility to help those who are less fortunate.  Fortunately, that lesson made a lasting impact, for Roosevelt brought to the White House in 1933 his great plan to pull America back from the brink of chaos, <a href="javascript:myPopup4('http://en.wikipedia.org/wiki/New_Deal')">The New Deal</a>.
<p>
The Memorial not only commemorates Roosevelt's grand plan to rescue a sinking America, its spacious 4-room outlay also pays tribute to his many other contributions during his 4-term Presidency; each room correlating to a specific term.  Comprised of over 4,000 granite blocks, many of which are inscribed with FDR's famous quotes, the Memorial is the result of efforts by many commissioned artist, together contributing a variety of sculptures that tell the story of FDR's life and times as the 32nd President of the United States.
<p>
FDR's struggles were both public and private.  His public struggles manifested in many ways, including his efforts to provide employment to the beleaguered masses, to change government to provide much needed social services, and to assist in the prevention of world destruction during World War II.  His private struggles focused on dealing with his severe physical paralysis, resulting from contracting polio at the age of 39 and continuing on unabated until his eventual death many years later in 1945.  Many have said it was the courage and strength gained early on in facing his illness that gave him the ability to lead the troubled Nation.
<p>
Subsequent to the Memorial's dedication, an epilogue was added in 2001 to the Memorial's entrance to better represent Roosevelt's illness.  Seated in a wheelchair in his characteristic rumpled suit, pince-nez, and fedora, erection of the statue and accompanying inscription was an attempt to nullify complaints from a number of handicap advocacy groups who claimed the Memorial hid FDR's condition, just as FDR has done so well himself.
