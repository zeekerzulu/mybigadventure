<p>
Nestled within the northwestern confines of Montana, Glacier National Park preserves more than 1,000,000 acres of forests, lakes and alpine meadows.  Home to over 70 mammal species and over 260 bird species, Glacier offers 700 miles of maintained hiking trails for those who wish to attain deep contact with the great outdoors.  The park abounds with Historic Sites (350 structures) and 6 National Landmarks.
<p>
In partnership with Canada, in 1932 the Canadian Waterton Lakes National Park was intertwined with Glacier National Park to form the Waterton-Glacier International Peace Park.  Together the parks in 1995 were recognized as a <a href="javascript:myPopup3('http://www.worldheritagesite.org/')">World Heritage Site</a>.
<p>
Glacier National Park turned out to be one of my trip's biggest highlights.  I had so heard many great things about the park and was curious to see if the word-on-the-street was true.  My time at the park was spent primarily on the saddle of my road bike, riding up to Logan Pass via the steep, twisting and winding Going to the Sun Road.
<p>
Come join me now as I arrive at the park in preparation for my up-and-coming biking adventure.
