<p>
My visit to Memphis was short but sweet.  Having only a day to spend in this great southern city, I was wise to choose Graceland and Beale Street as my sightseeing venues.  There's a reason why these two sights are so popular.  It's because they're really, really good!  I wish I had a little more time to investigate the city.  However, I was fortunate to have enough time between venues to visit the <a href="index.php?action=DailyEvents&date=20041110&page=2">Mississippi River</a> where I took in the sights of the river as well as 4 really nice riverboats.
<p>
I give my tour of Memphis 4.5 thumbs-up out of a possible 5 thumbs.
