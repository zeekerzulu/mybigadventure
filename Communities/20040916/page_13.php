I can't leave town without a quick look-see at my old Little League stomping grounds.  I played for two years on the Yankees.  We were the league champs during my second season, beating out 7 other teams.  The ballpark is now named after some Elroy Parkins guy.  I never heard of the dude.  I notice they've erected a new concession (second picture, blue building on the right).
<br><br>
Note: On July 3rd, 2009, out of the blue I get the following note from a gentleman by the name of John R. Showalter. Thank you John!
<p>
Jeff-
<p>
The Elroy Parkins for whom the Oakfield, NY, park is named was
owner of a trucking firm in Oakfield in the 1940's-1950's. He hauled a
lot for the Haxton canning plant, used almost exclusively Brockway
trucks, and lived at 28 Cary Ave. in a former Haxton Co. house. His daughter,
a supervisor of nursing at a NYC hospital, still lives there when in
Oakfield.
<p>
Elroy was president of New York State Lions Clubs in 1966-1967
and served on the Oakfield town council. He was a steady member of the
Presbyterian Church on Main St. and was, I believe, an elder in the
church. He drove only Hudson cars (and very rapidly; I recall seeing 3
figures on the speedometer of his '54) until they stopped building them,
then finally had to switch to Chryslers. Never knew him to be ticketed;
the troopers that patrolled the Thruway got nice boxes of candy and
similar on a regular basis, part of the cost of running a trucking
business!  He was a steady cigar smoker and the funniest human being I
ever knew. He could say things in a deadpan way that had you rolling on
the floor with laughter, was a great card player, and very definitely
"one of the boys" in the local power structure. He died of cancer in the
1970's or 1980's...I visited him in the Batavia hospital just before he
died. Most folks in the Oakfield of the period knew "Parky". You'd have
probably enjoyed him if you knew him.
<p>
So now you know who he was!  My dad was pastor of the
Presbyterian Church in Oakfield from 1943-1951 and I grew up those years
there, starting kindergarden and leaving during 1st grade when we moved
to Ohio. I've lived near Asheville, NC, for 40-some years now. 
<p>                                                                       
-John Showalter
