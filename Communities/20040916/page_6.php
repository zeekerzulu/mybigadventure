Santinos.  This is the local pizza and sub joint.  This was here when I last visited.  It used to be a gas station long ago.  After working at Tony & Maria's Pizzeria (that was located further up Main Street) for some time while in high school then in college, Santinos opened their store and took a big bite out of Tony's business.  I thought we had better food but the town couldn't support two pizza parlors.  The owner of Santinos had more money so he could ride out the storm while Tony lost his shirt.  True capitalism in action.
