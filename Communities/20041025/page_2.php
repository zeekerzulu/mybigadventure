<a href="index.php?action=Pics&name=Daily/20041029/DSCN0431.jpg"><img src="Pics/Daily/20041029/Small/DSCN0431.jpg"></a>
<p>
Established by Congress in 1820, the <a href="javascript:myPopup7('http://www.usbg.gov/')">United States Botanic Garden</a> is the oldest botanic garden in North America.  Approximately 4,000 plants reside within the premises, together representing a variety of mini-ecosystems, including jungle, forest, and desert.  Unseen by visitors, a fully automated climate control system works behind the scenes to monitor the outside weather and to adjust the inside conditions for optimal plant health via misting, shade cloth, heating, fans, air-handling equipment, and window venting.
