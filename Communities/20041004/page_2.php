Yowza, I'm in Victorian House Heaven.  Montpelier has its fair share of them and more.  Victorian homes have always held my fascination and admiration.  My firm belief is anything that looks remotely like <a name='valid_link' href="javascript:myPopup1('https://static1.moviewebimages.com/wordpress/wp-content/uploads/2021/12/Munsters.jpg')">Herman Munster's house</a> is all right in my book.  Believe it or not, some folks in Waxahachie, Texas love the design so much they've painstakingly <a href="javascript:myPopup2('http://www.mortystv.com/munster_house.shtml')">replicated</a> the house for themselves.
<p>
Times up!  Time to push on down the road.  My short stay in Montpelier has been both scenic and enjoyable.  As I leave I'm left with a feeling that I could see myself living here, if only for a little while.  Only problem is it snows here way too much in the winter for my taste, effectively slotting this community in my minds-eye as a great destination to visit outside the winter season.  I rate my tour of Montpelier, Vermont a solid 4.5 thumbs-up.
