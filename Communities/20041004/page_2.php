I must say, I really love the city's architecture.  The city is doing a great job of preserving their architectural treasures.  As I look around I feel as if I've stepped back in time more than 100 years.  Taking this feeling a litte further as I think more about going back in time, my feelings immediately turn from wonderment to fear.
<p>
Why?  Well imagine me in Montpelier in the mid-1850s, driving my van down the street, people looking at me in disbelief, pointing, shouting, all red-faced and angry.  Pulled from my van I am ceremoniously dragged through the streets before being thrown in jail.  From my jail cell I continually entertain all who will listen with crazed stories of prophacy and future inventions.  WWI?  WWII? Atomic bomb?  Airplanes?  Velcro?
<p>
So as I stand here enjoying some yesteryear flashbacks I make sure not to delve too far back into my imagination.  But who knows, maybe they would instead treat me like a prophet and make me State Governor.  It's anyone's guess!
