Located in downtown Montpelier, the State House is truly the centerpiece of Montpelier.  This particular State House is Vermont's third.  Built in 1859 and costing $150,000, the building took two and a half years to complete and reflects the Renaissance Revival style that was popular at the time.
<p>
Only $150,000 to construct this incredible building?  That makes me laugh (or cry).  Today you can't buy a halfway decent house for $150,000 in Portland, Oregon.  It's interesting how inflation has degraded the value of the dollar over time.  Back in 1859 I wonder how much a gumball cost?  A penny would probably buy you a bunch of them, assuming they had gumballs back then.  Did they even have pennies back then?
