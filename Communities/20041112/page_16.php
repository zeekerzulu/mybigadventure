Having finished my drinking and Karaoke watching, I join the growing crowd outside in the street.  While walking around an interesting thing happens.  Within the crowd I notice two guys who're trying to spread the word of Jesus.  Talk about shooting fish in a barrel?  Here we are, all of us sinners, in dire need of redemption.  Well, I'm thinking I don't need to talk to either of these two guys, I believe in Jesus (whether that'll get me into Heaven is entirely another matter), so no need to talk to me, right?  Wrong!
<p>
One of the guys, Tony, locks his sights on me and hunts me down.  Once within his grasp and in machine gun fashion, he tells me all about his sorted past and how Jesus saved him.  I swear, the guy must be on speed or something, he's talking way too fast and is acting somewhat possessed.  After listen to all that he had to say and taking some of his literature, he finally lets me go.
<p>
