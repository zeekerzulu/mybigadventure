<center><b>CONCLUSION</b></center>
<hr>
<p>
It's midnight and I'm now feeling quite tired.  It's time to head back to the van.  I must say, my time spent in New Orleans has been thoroughly enjoyable.  There is so much to see and do here in the Big Easy, I wish I had another day to check things out.  I think one of the most enjoyable things about the French Quarter is the old and varied architecture, it's everywhere you look.
<p>
I give my tour of New Orlean's French Quarter 5 thumbs-up, a perfect rating!
