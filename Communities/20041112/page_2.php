A major landmark in the French Quarter, the <a href="javascript:myPopup4('http://www.frenchquarter.com/history/StLouisCathedral.php')">St. Louis Cathedral</a> is the oldest continuously active cathedral in the United States.  Build in 1853, the cathedral is the third substantial church in the square; the first burned and the second was replaced with the current structure.  Given the reputation of the French Quarter, it's odd to see this grand Catholic cathedral amidst of all the surrounding hedonism, from the sex shops to the all-hours bars to the crazy and wreckless behavior.
