Formerly named the Place des Armes, <a href="javascript:myPopup1('http://www.atneworleans.com/body/js-square.htm')">Jackson Square</a> is a city-block sized open park located at the old center of New Orleans.  At the northwestern reaches of the park you'll find a statue of <a href="javascript:myPopup2('http://en.wikipedia.org/wiki/Andrew_Jackson')">Andrew Jackson</a>, who led his troops to victory in the <a href="javascript:myPopup3('http://en.wikipedia.org/wiki/Battle_of_New_Orleans')">Battle of New Orleans</a>.  This place used to be a famous gathering place for painters of various talents who would set up shop around the perimeter of the square.  Since then, the tarot card readers, fortune tellers, and mimes have largely driven them away.  The mimes?  You've gotta be kidding!  Aggressive, pushy mimes?  For some reason I can't picture that.
