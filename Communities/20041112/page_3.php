Outside St. Louis Cathedral in Jackson Square Mall I take in a magic show.  The Bird Man is preparing to captivate his audience with his disappearing bird trick.  When he initially starts the show, he pours a semi-circle around his outdoor stage from a charcoal lighter fluid bottle to keep his audience at bay.  I really get a good chuckle when he does this.  The crowd is drawn into believing he's going to light it.  The Bird Man eventually admits the fluid is only water.  Ha!  The joke's on us!
<p>
The trick itself starts with the Bird Man taking the white dove from the cage and placing it into a red bag.  After doing this, he sets the bag on the ground and starts stomping on it, the crowd is aghast!  He then picks up the bag and turns it inside out, revealing no bird guts, nothing.  Where did the bird go?  The Bird Man recruits a young girl from the audience to help him find the bird.  They both go over to his red table and to everyone's surprise, the bird is in the chrome container!  Wow!
