Here's <a href="javascript:myPopup3('http://www.nps.gov/bost/OSMH.htm')">Old South Meeting House</a> where an open-air market is now in full swing.  Built in 1729, the meeting house was one of the first buildings in the US to be designated as a historic site.  The largest meeting place in Boston at one time, it was where the multitudes gathered to debate and act on the issues of the day; The Boston Massacre, impressment of American sailors in the British Military, launching point of the Boston Tea Party.
