In terms of monumental events that have hit Boston, tonight ranks near the top.  Boston hasn't won the American Pennant since 1986.  So far, they've managed to comeback from a 0-3 series deficit to tie the series 3-3.  No team has ever won a pennant after being in such a deep hole.  If the Sox win tonight, and no less against their longtime arch rival, the NY Yankees, they will have made baseball history by completing the biggest comeback in Major League post-season history.  And that's a huge thing, considering how fanatical Boston is about their beloved Red Sox.
