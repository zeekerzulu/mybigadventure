My time spent in Boston turns out to be a short one.  Having only spent a single day and evening in the city, I walk away from the experience feeling as though I must visit again someday to take in Boston's sights and sounds at a more leisurely pace.  But, I'm certainly not complaining, I covered a lot of ground today, thanks to The Freedom Trail and the Massachusetts Bay Transportation Authority.
