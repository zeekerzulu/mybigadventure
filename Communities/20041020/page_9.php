<p>
The ever present <a href="javascript:myPopup8('http://www.sec.state.ma.us/trs/trsbok/trstour.htm')">Massachusetts State House</a> is easy to identify by its gold dome.  I'm not sure what's more impressive, the brilliant dome or the huge "Go Sox" banner which attests to Boston's craze for America's favorite pastime, baseball.  Completed in 1798, the Massachusetts Legistlature still conducts its business within the elegant confines of this historical structure.
