<p>
Next to King's Chapel you'll find Boston's <a href="javascript:myPopup2('http://www.oldcityhall.com/history.htm')">Old City Hall</a>.  Now a restaurant and first class office building, in its political heyday, Old City Hall saw the comings and goings of 38 Boston Mayors over a period of 128 years. 
