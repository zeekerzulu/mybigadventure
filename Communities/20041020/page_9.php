Boston's oldest public building is the <a href="javascript:myPopup4('http://www.nps.gov/bost/bost_lographics/oldstate.htm')">Old State House</a>.  Built in 1713 and used by Massachusetts colony, county, and town governments, it was a beehive of activity during colonial times.  Having the foresight to encourage the public's understanding of the government's inner-workings, a visitor's gallery was added in 1766 to accommodate a public audience while the legistlature was in session.
