The only memorial I have time to visit is the <a href="javascript:myPopup5('http://www.nga.gov/feature/shaw/home.htm')">Shaw Memorial</a>.  It is here where you'll find the starting point of the <a href="javascript:myPopup1('http://www.nps.gov/boaf/')">Black Heritage Trail</a>.  This memorial is dedicated to <a href="javascript:myPopup6('http://www.medalofhonor.com/RobertGouldShaw.htm')">Colonel Robert Gould Shaw and the African-American Massachusetts 54th Regiment</a>.  On May 28, 1863, Colonel Shaw and 1,000 black soldiers, the fifth African American troop to be organized during the Civil War, marched past Boston onlookers and into the war.
