Anchored at the <a href="javascript:myPopup1('http://www.nps.gov/bost/Navy_Yard.htm')">Charlestown Navy Yard</a> you'll find the <a href="javascript:myPopup2('http://www.ussconstitution.navy.mil/index.htm')">U.S.S. Constitution</a> (aka "Old Ironsides").  The shipyard has a long and rich history of shipbuilding where, from 1800 to 1974, the shipyard constructed, repaired, and outfitted U.S navel vessels. Old Ironsides was a pretty big ship for its time, its length spans a whopping 204 feet from bow to stern.  Launched October 21, 1797, the ship sports three masts, the tallest reaching 220 feet in the air.  
