The first level of <a href="javascript:myPopup5('http://www.masstourist.com/faneuil.htm')">Faneuil Hall</a> is a huge indoor market.  Taking two years to complete, the original structure was finished in 1742 and provided ample space for a public market and meeting hall.  The version you see today is a replacement of the original two-story structure which burned to the ground in 1761.  Rebuilt in 1763 to its current four-story configuration, it was used so frequently by the American Patriots that it was quickly dubbed the "Cradle of American Liberty."
