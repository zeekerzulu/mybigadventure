The town has an interesting mix of people.  I see many, many bikers, yuppies, families, and quite a few Japanese tourists.  Cowboy Bar is a favorite hangout for the biker crowd.  The vast majority of bikers in town seem to be 40 or older, old enough to know that wearing a helmet makes good sense.  But I rarely see any of them wearing one.  And seeing bright red sunburn on their faces is commonplace, I guess they think sunblock is for wimps.
