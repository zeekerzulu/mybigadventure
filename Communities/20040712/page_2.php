Bordering <a href="javascript:myPopup3('http://www.northwestplaces.com/WaState/P-Sound.htm')">Puget Sound</a>, Seattle provides a <a href="javascript:myPopup4('http://www.wsdot.wa.gov/ferries/')">multitude of ferries</a> to island retreats across the sound to the west.  You can	walk, bike, or drive to your ferry of choice which all run from early morning to late in the evening.  The above sequence shows a ferry coming into dock.  There's even a <a href="javascript:myPopup5('http://www.ferrycam.com/dcseabrem.htm')">live ferry cam</a> that'll give you the blow-by-blow on all the happenings around the ferry docks.
