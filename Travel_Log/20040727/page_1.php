As the bird flies it's a little more than 100 miles to Kalispell from Sandpoint.  Unfortunately, not being a bird, I find myself stuck driving the van and at the mercy of government's road planning ways.  The quickest way to get there is to head North towards Canada for a bit then swing downward due Southeast, then East, effectively adding an additional 80 miles or so to my drive.
