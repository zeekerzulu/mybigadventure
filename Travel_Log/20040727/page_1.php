I finally get all caught up on my sleep.  After spilling out of bed I head to Sandpoint City Beach to cook a breakfast of scrambled eggs and oatmeal.  After eating I walk over to Starbucks to webmaster the site, adding content covering the previous day's activities.  Later in the afternoon I push off to Montana, destination Kalispell.
