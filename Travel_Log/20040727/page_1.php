I encounter quite a bit of haze on my way out of Sandpoint, ID and it hangs around for pretty much the rest of the trip.  I wonder if there are forest fires burning somewhere, belching out smoke and contributing to the poor visibility.  As I drive to Kalispell, MT the Forest Service's "Smokey the Bear" signs are successively warning me of fire danger.  In the areas I drive through the indicator hand (looks a little like the Twister's spinnable color indicator) always points to either moderate or high.
