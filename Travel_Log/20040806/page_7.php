During the tail-end of hiking the scenic geyser trail I noticed the weather was turning grayer and gloomier by the minute.  Back in the van, as I drive to my next destination, West Thumb Geyser Basin, the clouds surrender and release a torrent of rain.  I suspect the temperature has dropped at least 20 degrees. So much so, I'm forced to turn off the air conditioning and turn on the heat. It's a somewhat odd experience.
