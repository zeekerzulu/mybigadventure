My route starts from the Norris Campground and takes me on a counter-clockwise spin around the park.  Fast forward to day's end, I run out of daylight and fail to visit the Canyon Area, that will have to wait until tomorrow.  The dogleg up and out of the park to Gardiner, MT is taken to avoid paying the $14 campsite fee. Gardiner isn't that far of a drive plus I have to be up in that part of the park anyway for the two hikes I've planned for tomorrow.
