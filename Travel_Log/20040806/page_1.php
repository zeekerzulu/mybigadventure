While getting ready I accidentially break my camping mirror.  Ooops, does that mean I'll have 7 years of bad luck?  If I had my druthers, I'd just do without mirrors all together, they are such a hassle.  That got me to thinking, would the world be a better place if people didn't use mirrors so much?
