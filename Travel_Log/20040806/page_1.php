My goal for today is to see all of Yellowstone's remaining major sights.  Up to this point, I have seen only 2 of the 7 sights, Mammoth Hot Springs and Norris Geyser Basin.  Those that remain included 1) Fountain Paint Pot Area, 2) Old Faithful Area, 3) West Thumb Geyser Basin, 4) Mud Volcano, 5) Canyon Area.  It is an aggressive plan so I take great care in plotting my route to eliminate all unnecessary driving.
