The spectacle turns out to be a grazing elk.  Fortunately, there's a stream separating the elk from the amorous crowd, an effective safety buffer that calms the elk and permits it to remain at task.  In the distance there's another elk grazing as well.
<p>
If the tables were turned, what would you do if a group of elk crowded around to watch you eat?  Probably after many benign, repeat encounters, you'd probably just ignore them.  So I guess we're a little like the elk after-all.
