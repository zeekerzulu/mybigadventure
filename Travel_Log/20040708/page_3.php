On down the road a little ways I encounter my day's second oddity, which proves to be a pair of HUGE <a href="index.php?action=Stats&stat=Oddities&date=20040708&page=2">tire rubber marks</a>, never have I seen such a long rubber marking in my 22 years of driving.  And I've even made a few myself, but nothing close to the magnitude of this one.
<p>
<a href="index.php?action=Pics&name=Daily/20040708/25.JPG"><img src="Pics/Daily/20040708/25_sm.JPG"></a>
<p>
I next pass through Cougar WA.  I don't know much about the history of Cougar but I'd bet there aren't any outdoor child daycare centers in this neck of the woods, if you know what I mean.
<p>
<a href="index.php?action=Pics&name=Daily/20040708/16.JPG"><img src="Pics/Daily/20040708/16_sm.JPG"></a>
<p>
My next sight is Swift Dam.  This earthen structure dams the Lewis River, effectively filling the Swift Reservoir.  Yale Lake is located immediately downstream from the dam.  The water in the reservoir must be consumed by the folks in Southwest Washington State.
<a id="Ref1"></a>
<p>
<a href="index.php?action=Pics&name=Daily/20040708/12.JPG"><img src="Pics/Daily/20040708/12_sm.JPG"></a>
<p>
Moving along, I spy Mount St. Helens from afar.  Unfortunately, given my routing today, I'll only see her from this distance, which I estimate to be about 25 miles.  Did you know she's not as lofty as she used to be?  Yes, volcanic anger got the best of her when, in 1980, her seismic emotions boiled over, prompting her to blow almost 1,500 feet of solid rock off her top.  Wow!  Now that's a lotta rock.
