Soon I come upon this informative sign.  For some reason, largely unknown to science but secretly coveted by those sneaky marketing folks, bears not only have a good sense about the fire volatility of forests, they also like to communicate said facts via billboard signage.  The most popular spokesbear, Smokey the Bear, says the fire danger today is "low".  This will change once summer sizzles on with little or no precipitation.  It gets really dry here near summer's end when the potential for wildfires is a real concern for many folks living in or near the forest.  Apparently, the bears are concerned as well.
