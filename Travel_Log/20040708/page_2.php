On a whim my first stop is the Speelyai Bay Recreation Area.  This park and apparently many others down the road are maintained by the public utility, Pacific Power & Light Company.  A number of fish hatcheries are operated by the conglomerate as well.  The park serves up a lake, a boat launch, a little beach and many picnic tables, pretty much standard fare in these parts.  It borders Lake Merwin which turns out to be a fairly large lake.  Now that it's later in the evening, aside from the boat being taken out of the lake, no other watercraft are in sight on land or in the water.
