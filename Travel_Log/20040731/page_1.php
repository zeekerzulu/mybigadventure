While my meal is cooking a black VW pulled up alongside.  I notice the driver is packing a lot of biking gear so I say hi and ask if he's on a road trip just like myself.  What transpires thereafter is about 3 hours of in depth conversation that focuses primarily on his biking adventures and life experiences in general.  <a href="index.php?action=Stats&stat=People&date=20040731&page=8">Patrick</a> turns out to be a very interesting fellow with an unquenchable thirst for extreme biking adventure and a high tolerance to the twists and turns that life sometimes throws at you.  I admire his ability to roll with the punches.
<p>
After talking with Patrick I get down to business webmastering the site, spending a good portion of the afternoon and evening playing catch-up.  Other than that I just take it easy and enjoy the day.
<p>
Tomorrow I have plans to visit the Museum of the Rockies.  They've got dinosaurs there!  Dead one's of course.
