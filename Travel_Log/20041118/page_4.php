Yikes!  Check out that lazy eye.  Whatup wid dat?  Can you say Bell's Palsy?  Bell's Palsy, what a fun experience that was... NOT!  In 1997 I contracted the condition, initially I thought I had suffered a stroke because the left side of my face was completely paralyzed.  That's right, completely paralyzed.  A quick visit to the emergency room indicated otherwise, I was suffering from an aliment that strikes 1 out of 5,000 people.  Perhaps you know of someone who has had it?
<p>
That was a scary time for me.  Fortunately, the odds were well in my favor, the vast majority recover from the paralysis in about a month's time.  As for me, between the slurred speech, the difficult eating, the having to sleep with a taped eye because I couldn't close it on my own, the condition continued on for two months without improvement.  Was I in the small minority who don't recover?
<p>
Into the third month things finally turned around for me.  Within about a day's time I magically regain about 90% muscle function in the left side of my face, I'm ecstatic!  10% of my muscle function is still missing to this very day and is most evident when I smile.  So, there you have it.
