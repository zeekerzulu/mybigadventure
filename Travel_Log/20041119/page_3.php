After filling up I head out of Taos with plenty of fond memories and an itch to perhaps return again sometime in the future, although it's rather difficult to say if I'll ever return.  With so many things to see and do in this world, it seems almost foolish repeat things if the urge to return is just an itch, as it is in this case.
