My busy day of sightseeing has finally come to an end.  The time has arrived to hit the road and head north to Colorado, the 31st state on my cross-country travel master plan.  I set my sights on an evening of driving, and with more than 300 miles between me and my destination, I certainly have my work cut out for me. Staying awake should be the most challenging part of it I suspect.  My good friend Paul lives at trip's end, just south of Denver in the suburb of Littleton.
