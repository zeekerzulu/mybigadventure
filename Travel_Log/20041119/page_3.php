Did you know Taos Pueblo is a <a href="javascript:myPopup1('http://en.wikipedia.org/wiki/World_Heritage_Site')">World Heritage Site</a>?  This is a pretty big deal considering only 830 total sites world-wide are on the list.  Does 830 seem like a big number to you?  Well, it shouldn't, considering how many things there are to see in this world.  It's actually a mighty small number when you think about it.  By the way, there are only 20 World Heritage Sites in the United States.
