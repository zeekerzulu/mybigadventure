Returning from my tour of the museum I have a hankering for some beer.  All that history has really made me thirsty.  A good friend of mine went to grad school here at Montana State and told me about a great bar called the Montana Ale Works, so I go check it out.  I bring my laptop and work on the site while drinking my organic porter.  The bar/restaurant is a pretty hip place.  I can see why my friend likes it so much.
<p>
