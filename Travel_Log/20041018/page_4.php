<p>
After feeding the birds, we stumble across the <a href="javascript:myPopup1('http://portlandme.about.com/cs/mainehistory/a/Observatory.htm')">Portland Observatory</a>, and find ourselves wanting to climb to the top to get a better view of the surrounding area.  Unfortunately, it's closed for the evening.  It stands 88 feet high and, in its heyday, was used to identify ships entering the harbor.  Supposedly, the telescopes used at that time could see 30 miles out to sea on a clear day.
<p>
Well, the day winds down into evening and we find ourselves eating dinner on a floating restaurant called <a href="javascript:myPopup2('http://www.dimillos.com/restaurant/')">Dimillo's</a>.  Located on an old, retired ship, it's permanently moored on Casco Bay at Portland's Waterfront.  I order the works, deep fried everything, and can only manage to finish half of my meal.
<p>
Soon enough, I drop Monica off at the airport, then I drive to the local Walmart where I settle in for the evening.
