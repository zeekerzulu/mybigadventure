Popping out of the subway station, I soon pass by <a href="javascript:myPopup1('http://www.faa.gov/')">Federal Aviation Administration</a>.  Established in 1958, according to their website, the FAA's mission is to:
<p>
<ul>
<li>Regulating civil aviation to promote safety 
<li>Encouraging and developing civil aeronautics, including new aviation technology 
<li>Developing and operating a system of air traffic control and navigation for both civil and military aircraft 
<li>Researching and developing the National Airspace System and civil aeronautics 
<li>Ensuring toy balsa wood airplanes actually fly, the rubberbands don't snap, and the wings don't break off during extreme maneuvers
<li>Developing and carrying out programs to control aircraft noise and other environmental effects of civil aviation 
<li>Regulating U.S. commercial space transportation
</ul>
