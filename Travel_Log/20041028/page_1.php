Today will mark my third full day of touring the Capitol.  Being a pilot, I'm feeling rather excited right now.  Why?  Because I have plans to visit the world famous Smithonian's National Air and Space Museum.  The museum is a mecca for not only pilots, it's also a destination for anyone else who's interested in activities that fight gravity and do not require support from terra firma.  If I have time afterwards, I'll try to squeeze in a tour of the U.S. National Archives and Records Administration.
