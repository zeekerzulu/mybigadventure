The Smithsonian <a href="javascript:myPopup4('http://www.nasm.si.edu/museum/')">National Air and Space Museum</a> contains the world's largest collection of historic air and spacecraft.  The origins of the museum trace back to 1946 when the National Air Museum was established.  Back then, the museum was actually housed in a shed in the south yard of the Arts and Industries Building.  Since then, the museum has been renamed to reflect more modern times and in 1976 it was given a new place to hang its hat.  And quite a palatial place at that.
