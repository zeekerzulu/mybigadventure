My drive to Minneapolis, MN is uneventful but as I draw closer to my destination I grow more excited.  I'm going to stay with my friend <a href="index.php?action=Stats&stat=Friends&date=20040825&page=2">Greg</a> and his family for a couple of days.  I haven't seen Greg in over 4 years but we've kept in touch occasionally via phone/email.
<p>
The plan is to meet Greg and his wife Meri for dinner at an Outback Steak House near their home.  I pull into Outback's parking lot and run across the street to get a few things from the supermarket.  Upon returning I open the van side-doors and lean inside with my groceries.  And in true form, Greg sneeks up from behind me and tries to shut my legs in the doors.  It is truly a Greg-style welcome.  It's good to see the big guy again.
<p>
After he introduces to his wonderful wife Meri, we all settle in for some red meat, margarettas, and serious catching-up.  After dinner I follow them back to their home and Greg lets me park the van in his spacious, park-like front yard.  I plan to stay with them for a couple of days.  I just want to hang out, relax, and have some good conversation.  And at day's end that's exactly what we do, and we all have a lot of fun!
