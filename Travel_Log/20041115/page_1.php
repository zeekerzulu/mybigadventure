I wake at 8:30 to my second morning in the <a href="javascript:myPopup1('http://en.wikipedia.org/wiki/Texas')">Lone Star State</a>.  I find myself faced with uninspiring views of yet another Walmart parking lot that looks like all the other Walmart parking lots I've camped in since I starting doing so back in Massachusetts.  Looking on the bright side, they're free and I don't get busted by the police for camping on the street.  This parking lot is starting to look really good now, what a great place to be.  Sometimes it's helpful to review the reasons for one's actions.  It's so easy to lose sight, especially when alone and without someone to point out misplaced rhymes and reasons.
