As I get closer to Choteau, MT, signs start popping up announcing the Old Trail Museum, which to my pleasure happens to be a dinosaur museum.  I've always been fascinated by dinosaurs so I feel obliged to swing in and take a looksee.  Upon arrival I'm pleased to see they have plastic replicas lurking around outside, adding to its already heightened appeal. But when I try to enter the building I get spanked, they closed at 6pm and I'm late.  Too bad, I'm kinda bummed.  Looking at my travel book I learn that Bozeman, MT has its own dinosaur museum, so maybe when I pass through there I'll check it out.
