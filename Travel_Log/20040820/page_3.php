My next and last task for the evening is to find a "safe" neighborhood to park in.  One far away from the neighborhood I've been banned from by the police.  I'm 1/2 tempted to overnight in the banned neighborhood because doing so is legal.  I don't like being told I cannot do something that's perfectly legal.  The road is for public use and last time I checked I'm classified as the public.  But after thinking about the Patriot Act and how my rights can now be whisked away pretty much on a whim, I decide not to play with fire and find a nice little place to park my van, far, far away from the little troll and his fancy neighborhood.
