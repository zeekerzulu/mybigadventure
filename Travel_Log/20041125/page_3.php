The City and County Building is already decked out for Christmas, tree and all, and the Greek amphitheater at the park's edge has a crowd in front of it.
<p>
<a href="index.php?action=Pics&name=Daily/20041125/DSCN0159.jpg"><img src="Pics/Daily/20041125/Small/DSCN0159.jpg"></a>
