For the most part, I spend the day travel writing.  But I do take some time to checkout a sunset.
<p>
Throughout my stay in Jackson I've noticed a tip of the Grand Teton peeking over one of the surrounding hills.  Even as an adult, I sometimes get the urge to climb things, and the ever-peering mountain has been coaxing me to revert back to my childhood ways.  So, a challenge has been placed before me.  Climb the hill and checkout the sunset. And that is exactly what I do.
