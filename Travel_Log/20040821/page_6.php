The evening has arrived and I'm still far from the Badlands.
<p>
Long story short, I drive a ways into the Badlands but strike out on finding an overnight location.  All the dirt roads that spider-leg out from the paved highway are gated, effectively making them inaccessible, something I hadn't expected.  I have the option to just park the van on the side of the paved highway but that would leave me feeling rather exposed and vunerable.
<p>
So I backtrack to a small town I had passed through earlier and encounter dirt side-streets where no one is parked, everyone is parked in their yard.  I get a bad feeling about the place and decide to head back in the direction of Rapid City, SD to see if I can find someplace safe and unexposed to park.  Well, much to my displeasure, I find myself back in Rapid City, SD, the place where I had the run-in with the police the evening before.
<p>
This time I take care to just park on the outskirts of the city.  After parking I just sit in the van waiting for the police to show up, not a pleasant feeling (this night proved to be my most paranoid overnight of the trip). Fortunately, the police never materialize, and I manage to get some shut-eye in before the morning light.
