I drive through Custer, SD.  You know what?  I don't know about you but when I think of General Custer, I think bad things.  All the horrible directives he followed through on, like the wholesale murdering of Indian women and children.  Some people probably say he was just following orders.  But so were the soldiers in the concentration camps in Nazi Germany.  And we all know what a massive crime against humanity that atrocity was.  So I guess the lesson learned here is, above all, question authority.
<p>
Having said all that, it seems strange they'd name a town after the guy.  If I lived in or was from Custer, SD, I don't think I'd want to admit it.  God, I hope the townsfolk don't immortalize him, now that would be pretty disturbing.
