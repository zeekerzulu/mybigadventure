As I drive to Mount Rushmore I'm continually peppered with signs advertising various sights, including Big Thunder Gold Mine, Bear Country USA, Sitting Bull Crystal Caverns, Old McDonalds Petting Zoo, Christmas Village, Rapid Ride Go Kart Park, President's Alpine Slide, and Rushmore Cave, just to name a few.  It's somewhat discouraging to see all the commercial enterprises aggressively riding the coat-tails of Mount Rushmore.  So much so if I had a family, I think I'd have to blind-fold my kids on the drive.
