Just a stone's throw away from the Lincoln Memorial you'll find the  <a href="javascript:myPopup10('http://www.nps.gov/kwvm/home.htm')">Korean War Veterans Memorial</a>.  On initial take, the memorial exhibits a heavy, solemn, and macambre mood.  A total of 54,246 American lives were sacraficed in the conflict, and the memorial is here to remind the present and future generations of all the sacrifices the brave soldiers made in the defense of South Korea.
