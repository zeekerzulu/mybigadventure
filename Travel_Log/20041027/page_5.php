After a short walk I arrive at the next memorial on my map, the <a href="javascript:myPopup4('http://www.wwiimemorial.com/')">National World War II Memorial</a>.  Opened to the public less than 6 months ago, this colossal memorial really chokes me up as I walk around its stony expanse.  So many theaters of battle, so many lives lost.  The elegance and grander of this place is something I'll never forget.
