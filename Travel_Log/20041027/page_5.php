Swinging my attention 180 degrees from the National Christmas Tree, I see <a href="javascript:myPopup1('http://en.wikipedia.org/wiki/White_House')">The White House</a>.  Located at the famous address of <a href="javascript:myPopup2('http://mappoint.msn.com/(qktlju55rvyrvxa3rw2540yt)/map.aspx?L=USA&C=38.89869%2c-77.03563&A=7.16667&P=|38.89869%2c-77.03563|1|1600+Pennsylvania+Ave+NW%2c+Washington%2c+DC+20006|L1|')">1600 Pennsylvania Avenue</a>, construction of the 55,000 sq foot structure was completed on November 1, 1800 after 8 slow years at a cost of a little more than $232,000.00.  When adjusted for inflation, it rounds out to about $2.4 million.  It just goes to show you, they didn't pay construction workers very well back in the day.
