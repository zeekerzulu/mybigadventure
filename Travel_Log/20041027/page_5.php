Making my way westward, I encounter a memorial called <a href="javascript:myPopup3('http://www.kittytours.org/thatman2/search.asp?subject=122')">The Second Division</a>.  Erected in 1936 in memory of those within the Second Division who lost their lives in WWI, the open gateway represents the entrance to Paris and the fiery golden sword represents the Allied Forces who prevented the Germans from permanently occupying the city.  Memorials to Division members who lost their lives in WWII and the Korean Conflict were subsequently added, and are manifested as wings on either side of the gateway.
