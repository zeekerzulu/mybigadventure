On the way to the subway station I become really excited!  I start shouting "Show me the money!"  Well, the <a href="javascript:myPopup5('http://www.moneyfactory.com/')">Bureau of Engraving and Printing</a> will show me the money; nice, crisp new ones, if only I take their tour.  Established in 1862 with 6 employees working in a cramped basement room, today the bureau has grown to 2,500 employees that are spread across two large buildings in Washington, D.C. and a new facility in Fort Worth Texas.
<p>
Here are some interesting facts:
<p>
<ul>
<li> 37 million notes are produced a day, totaling approximately $696 million.
<li> 95% of the notes are produced to replace old, worn out currency.
<li> 45% of the notes produced are $1 bills.
<li> The first paper currency was issued in 1861.
<li> Paper currency size was reduced to 2/3's of its former size in 1929.
<li> A stack of $1 bills would contain over $14.5 million.
<li> Average life spans of various bills:
<ul>
<br>
<li> $1 ------ 22 months
<li> $5 ------ 24 months
<li> $10 ----- 18 months
<li> $20 ----- 25 months
<li> $50 ----- 55 months
<li> $100 ---- 60 months
</ul>
</ul>
