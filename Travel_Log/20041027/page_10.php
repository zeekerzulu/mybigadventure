<a href="javascript:myPopup7('http://www.arlingtoncemetery.org/')">Arlington National Cemetery</a> is one of the most visited tourist sights in the Washington, D.C. area, hosting an upwards of 4 million visitors every year who come to pay their respects to America's many fallen military men and women.  Home of the Tomb of the Unknown Soldier and the Kennedy grave site, Arlington is the final resting place for veterans and exceptional individuals spanning from the Revolutionary War to the present-day military conflicts in Iraq and Afghanistan.
