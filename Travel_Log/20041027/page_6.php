I'm getting close to the Vietnam War Veterans Memorial now.  Hey!  Look at that black squirrel.  He's hard to get a picture of because he's pretty darn skittish.  Did you know that black squirrels are not native to this area?  18 Canadian black squirrels were released near the National Zoo early in the 20th century.  Since then, their population has grown to exceed that of the gray squirrel.  Reason being, it's an evolutionary process kinda thing say the <a href="javascript:myPopup6('http://www.washingtonpost.com/wp-dyn/content/article/2005/05/18/AR2005051802251.html')">experts</a>.  Their black coat gives them an advantage over their gray cousins during the cold weather months.  Their darker coats absorb more heat from the sun, thus enabling them to use less energy to stay warm.
