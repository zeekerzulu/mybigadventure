I finally arrive at the <a href="javascript:myPopup7('http://www.nps.gov/vive/home.htm')">Vietnam War Veterans Memorial</a>.  Almost 500 feet long and more than 10 feet tall at its highest section, the black granite memorial stands in remembrance to the 58,249 Americans who died in the conflict.  The magnitude of the monument, with all its inscribed names, is rather overwhelming.  It has a far more personal touch, as compared to the National World War II Monument.
