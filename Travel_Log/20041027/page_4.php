Ever hear of the <a href="javascript:myPopup9('http://www.nps.gov/whho/pageant/')">National Christmas Tree</a>?  Located in President's Park, the tradition of the National Christmas Tree started way back in 1923 during the Calvin Coolidge Administration.  From its beginnings up until 1973, the tree has always been a cut tree.  On October 20, 1978, a live Colorado blue spruce was trucked in from York, PA and planted, thus permanently changing the holiday tradition to use a live evergreen tree.
