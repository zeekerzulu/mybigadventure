My next stop is The White House, home of <a href="javascript:myPopup8('http://www.whitehouse.gov/president/gwbbio.html')">President George W. Bush</a>.  On the way, I walk along the perimeter of a landmark called the Ellipse, which is also known as <a href="javascript:myPopup8('http://www.nps.gov/whho/welcome.htm')">President's Park</a>.  They even have a visitors center for it.  The Ellipse is located just south of The White House and is quite large.  I suppose they use it for ceremonies and the like.  Hey!  That's strange, there's a huge evergreen tree nearby, standing all alone and isolated. I wonder what it could be?
