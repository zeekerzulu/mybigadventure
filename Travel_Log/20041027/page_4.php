Erected in 1964, the <a href="javascript:myPopup4('http://www.nps.gov/whho/PPSth/boysctmem/')">Boy Scout Memorial</a> is the only memorial in Washington that commemorates an active and living institution.  All funds for its construction were raised solely by the Boy Scouts.  The bronze statue consists of a man (who looks kinda creepy in my opinion) representing physical, mental and moral strength, loyalty, courage, honor... you know, guy stuff I guess.  The woman is supposed to represent love in God, faith, justice, freedom, democracy... where do they get this stuff?  The Boy Scout represents the hopes and dreams of all past, present, and future scouts worldwide.  There's a small pool in front of the memorial, honoring all the boys who have joined the <a href="javascript:myPopup6('http://www.scouting.org/')">Boy Scouts of America</a>.
