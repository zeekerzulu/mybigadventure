My tour begins.  Walking westward on the northern side of the National Mall, I pass by the Smithsonian Institution's <a href="javascript:myPopup5('http://www.mnh.si.edu/')">National Museum of Natural History</a>.  According to their tagline, "The National Museum of Natural History is dedicated to understanding the natural world and our place in it."  The museum's publicly displayed collection, as well as its extensive behind-the-scene archives, contains over 140 million separate artifacts and specimens.  Yowza!  A world famous center for research, the museum is dedicated to the furtherance of public education and scholarship in the sciences, arts, as well as history.
