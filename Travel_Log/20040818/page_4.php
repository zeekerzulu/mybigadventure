This portion of South Dakota is rather boring.  Nothing noteworthy.
<p>
I finally arrive in Rapid City, SD and immediately set to task; look for a street-side Internet connection.  I tell ya, I really have to work hard finding a connection. The sections of the city I first drive through are rather run down.  It's hard to find where the "money" is in this town because some of the prime real-estate with views seem to be filled with subsidized housing.
<p>
After about 35 minutes of scouting around, I finally stumble upon an Internet connection in a pretty nice section of town.  I download my email then set out to grab some dinner.  It's too late to cook something myself (10pm) so I drive down the street a little way and grab a bite to eat at a Perkins Restaurant.
<p>
After dinner I settle in for the evening, work on the website for a bit then retire.  Since my last content upload to the website a few days ago I haven't typed a single word describing my trip.  My sporadic website work since then has solely consisted of configurating the site in preparation for a day of solid travel writing.  Tomorrow will be that full day of writing.
<p>
At least that's my goal now, to travel for 4 days then have a day of downtime.  I think if I can keep on top of the site's mechanics during the 4 days of travel, the 5th day can be strictly devoted to writing.  Well, at least that's the plan.  Yeah, and I had a plan to do push-ups every day but that only lasted 3 days!  I guess we'll see how this new plan goes.
