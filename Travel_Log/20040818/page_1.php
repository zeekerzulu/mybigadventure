<p>
11am rolls around and I see this tractor-trailer pull into view.  Upon the trailer are piled bundles of straw, all rolled up tight-like in cylinders.  Shortly thereafter a green tractor with a specialized jaw pulls up to the van and just sits there.  I'm sitting in the van in plain view, my privacy curtain is pulled open, and I'm just typing away on my laptop.
<p>
Well, I not getting out of the van to investigate because I'm busy.  So the tractor starts moving again and pulls up alongside the double-side doors.  I think again, I'm not getting out of the van, I'm busy.  After about a minute or so, the tractor pulls around the back and to the other side of the van.  I start thinking, "Is he was trying to figure out how to connect his tractor's jaws to the van so he could flip it?"...yeah, I'm just paranoid.  In any event, either the driver can't figure out how to flip the van or decides I'm harmless, so he goes on his way over to the semi and starts unloading the straw cylinders.
<p>
I take his actions as a "shot over the bow" on his part and leave shortly thereafter.  I'm glad I didn't have to record my flipped van as my 7th mishap of the trip.  But it would have been funny...eventually...years later...maybe.
