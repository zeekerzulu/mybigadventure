<p>
My day starts out in a cow pasture a few miles from Devils Tower National Monument. Perfect. The pasture turns out to be nothing special other than being nice and secluded.  As you can see, I've smeared off the van's URL dirt sign.  The previous day, when driving around Sheridan, WY in search of an Internet connection, I noticed people looking at the van and I didn't like the feeling.  Having that level of visibility is especially bad when "slinking" around neighborhoods, driving slowly from house to house, street to street, sniffing out wireless Internet signals. I've chosen stealth over self-promotion.
<p>
Before heading out to the Monument I decide to work on the website for a few hours.  Pickup truck traffic periodically passes by but they don't stop to bother me, seems no one cares that I'm ...uhh... trespassing?  But there were no signs posted so...
<p>
