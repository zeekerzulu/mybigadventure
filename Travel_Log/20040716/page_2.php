While walking down Nelson Street I spy Monica, a tarot card reader who has set up shop on the busy sidewalk.  As I walk by her small card table I start thinking about how useful having my cards read would be.  The road trip I'm on isn't only about searching for things outside of myself.  It's also (and maybe more importantly) about seeking recognition and understanding of my inner landscape, so perhaps a reading would give me some insight into my internal workings, as well as maybe how my trip will go.  So I retrace my steps back to her with much anticipation.
<p>
I have two options, either a palm reading or a tarot card reading.  I go with the card reading.
<p>
