<p>
After my tarot card reading I realize it has grown late in the evening so I head back to my bike for the return trip back to my home on wheels.  Since it's now dark I don my bike with a headlight and a flashing taillight to assist my safe passage through the city streets.  On the way back I encounter a section of the waterfront bike trail that closes after nightfall, so I end up having to ride up and over the inlet on the Granville Bridge.
<p>
Soon enough I arrive back to the van and settle in for the night.  Tomorrow will be a big day, I'll be touring Chinatown and the Chinese Gardens.
