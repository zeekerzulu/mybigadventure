According to this <a href="javascript:myPopup1('http://www.vfda.net/pressrelease_thackerexpansion6_9_05.html')">article</a> on the Internet:
<p>
"Thacker Caskets, Inc. has experienced unprecedented sales growth in recent years with unit volume up 76% since 1999. Vice President of Sales & Marketing, Michael Beardsley says that they like to refer to themselves as the Southwest Airlines of the casket business. He continues, quietly, Thacker Caskets Inc. has grown to become America's 4th largest casket manufacturer and 2nd largest family owned casket maker."
<p>
That's strange.  I thought more and more people are getting cremated these days, so, what's up with their hefty increase in sales?  I don't see anything in the article about them transporting the dearly departed in their company trucks, so, I guess the noise I heard came from somewhere else... or did it???  Hooo Hooo Haaa Haaa Haaa! (evil laughter)
