Established by Congress in 1820, the <a href="javascript:myPopup7('http://www.usbg.gov/')">United States Botanic Garden</a> is the oldest botanic garden in North America.  Approximately 4000 plants reside within the premises, together representing a variety of mini-ecosystems, including jungle, forest, and desert.  Unseen by visitors, a fully automated climate control system works behind the scenes to monitor the outside weather and to adjust the inside conditions for optimal plant health via misting, shade cloth, heating, fans, air-handling equipment, and window venting.
