<p>
After a little driving around I find a suitable place and park the van.  I immediately retire for the evening, taking care to not turn on the interior light or step outside the van, with the goal of keeping a low profile.  Well it isn't anymore than 10 minutes before two police cars show up.  I immediately hit the floor, hoping they will just shine their spot lights on my van and move on.  Well, after the little light show I hear two car doors slam and I know the gig is up.
