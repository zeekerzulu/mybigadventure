Surprisingly, I only see this single cotton field during my entire drive.  Initially, I'm not sure what it is, having never seen a live plant before.  To my surprise, I quickly learn it's cotton.  I pull the van over to investigate.  Amazed at how much raw cotton resembles the cotton balls you buy, I spend a little time playing with the fiber.  Simple pleasures for simple minds, eh?
<p>
<a href="javascript:myPopup2('http://en.wikipedia.org/wiki/Cotton')">Cotton</a> is a very important worldwide commodity.  As far back as 12,000 BC, our ancestors used the plant's white offering.  Cotton is an important cash crop in Tennessee.  It's historical significance is promoted by its prominent placement within the <a href="javascript:myPopup3('http://en.wikipedia.org/wiki/Seal_of_Tennessee')">Seal of Tennessee</a>.
