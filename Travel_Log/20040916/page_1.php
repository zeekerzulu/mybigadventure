After waking to a sunny morning in my Aunt and Uncle's driveway near Medina, NY, I make plans for my homecoming trip to Oakfield, NY.  From their house I will ride my bike to Oakfield and on the way I'll swing by Pine Hill Airport, the airport where my father taught me to fly when I was 15 years old.
