After completing my bike ride I decide to break camp and head to Seattle, WA.  On the way I'll pass through <a href="javascript:myPopup1('http://www.nps.gov/mora/')">Mount Rainier National Park</a>, and if you recall, Mount Rainier eluded me yesterday, foul weather foiled all my attempts to capture her likeness in digital.  Since a few hours of daylight are still at my disposal, I'll make an effort to photograph her once more, for the weather this evening is both sunny and clear, which will go a long way in facilitating that perfect mountain scene I've really been itching for.
