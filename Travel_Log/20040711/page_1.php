I jump in the van and start driving to Seattle, my route will take me out of the forest and into the city, half of the driving will be in wilderness and the remainder will be a mix of country and city.  Early in the drive I find myself at Naches Peak, an interesting pinnacle that sits right smack on the border of <a href="javascript:myPopup2('http://www.nps.gov/mora/')">Mount Rainier National Park</a> and <a href="javascript:myPopup3('http://www.fs.fed.us/r6/mbs/')">Mount Baker - Snoqualmie National Forest</a>.  With camera in hand, I jump out of the van and make my way to a foot trail that'll wisk me to a remote vantage point where I'll set up and shoot the mountain.
