After waking late in the morning, I fix my usual breakfast of scrambled eggs and oatmeal, then make preparations for my early afternoon bike ride.  I'm feeling pretty good today, I'm no longer sore from my <a href="index.php?action=Stats&stat=Biking&date=20040709&page=1">Lewis River</a> mountain bike ride, my trip's first bike ride that took place two days ago on Friday.
