Today I've task mysellf with tackling Fifes Ridge, a challenging mountain bike trail that shoots skyward 2,000 feet and stretches more than 14 miles across a variety of terrain.  I'm really looking forward to its tricky downhill runs, all of which are highlighted in bright yellow on my trail map; such warnings only further fan my interest.  In the end, the ride doesn't let me down, it proves to be both interesting and exhausting.
