There was a moment on the way out when I thought about what it is to be cold and lost and out of options, and I felt it, a little.  Then I did the math: I know where I am, it isn't snowing, nothing is numb all the way through, I'm still talking to myself in full sentences, and the gate is not far.  Keep walking.
