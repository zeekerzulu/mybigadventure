Face mask on, 5 o'clock, and a flagging tape marker on a stick, which was the most beautiful thing I saw all day.  I count to a hundred.  I do my ABCs.  That's what you do to check you're still making sense, and I passed, mostly.  Stumbling a little.  I think the hypothermia was closer than I'd like.
