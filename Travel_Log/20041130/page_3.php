The visitor center sign and map, and then the canyon.  Just like that.  You walk to the edge of a flat snowy mesa and the ground is gone, 1,800 feet of black rock straight down to a river you can hear and not see.
<p>
<a href="index.php?action=Pics&name=Daily/20041130/DSCN0131.jpg"><img src="Pics/Daily/20041130/Small/DSCN0131.jpg"></a>
