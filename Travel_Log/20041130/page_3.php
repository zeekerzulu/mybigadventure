<p>
The Black Canyon isn't black, it's dark gray gneiss and schist, two billion years old, with the sun reaching the bottom for about half an hour a day.  Hence the name.  The snow on the ledges only makes it darker.
<p>
<a href="index.php?action=Pics&name=Daily/20041130/DSCN0139.jpg"><img src="Pics/Daily/20041130/Small/DSCN0139.jpg"></a>
