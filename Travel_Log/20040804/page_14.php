Gardiner River, the main river, is fed by the Boiling River which originates straight out of the ground.
<p>
<a href="index.php?action=Pics&name=Daily/20040804/P1010230.JPG"><img src="Pics/Daily/20040804/Small/P1010230.JPG"></a>
<p>
Just downriver of where the Boiling River flows into the Gardiner River, some wise soul built a wall of rocks to help trap the hot water and form a sort of Jacuzzi.  It's really a wonderful thing.  I only stay in for about 15 minutes, realizing I can always come back again before I leave the park.
<p>
<a href="index.php?action=Pics&name=Daily/20040804/P1010232.JPG"><img src="Pics/Daily/20040804/Small/P1010232.JPG"></a>
<p>
9pm arrives so I climb out of the water and walk back to the van as the sun is setting.
<p>
When I get back to the campsite I work on the website for a while then go to bed.
