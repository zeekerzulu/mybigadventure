On the way to the campground I pass across the 45th parallel.  The sign is right next to two parking lots filled with cars so I stop to find out what all the hubbub is about.  I start thinking about that experiment where you drain a sink and the water doesn't spin left or right, it just drains without spinning.  But "that's an equator thing" I remember so all this activity is something else.
<p>
I manage to catch someone on the way to their car and they tell me there's a swimming hole about 1/2 mile down the way.  I think about investigating but remember I have a campsite to catch so back in the truck and up the hill I go.
