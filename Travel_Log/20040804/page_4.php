<p>
While driving on the dirt road I encounter many driveway entrance archways.  Well, they aren't exactly archways because they're not all curved, rather, in their simplest form they're just two vertical poles with a horizontal pole spanning across top of the two verticals.  When driving your car through them are you supposed to feel like you've entered Shangri-La?  They've always been a mystery to me.  But folks out in these parts really like them, some more than others.
