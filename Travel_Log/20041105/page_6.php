As the afternoon and evening winds down, I find myself travel writing and working on the website.  Today turns out to be rather uneventful.  As I work in the van, one thing outside really catches my attention.  Pickup trucks are king here in Kentucky.  Everyone is driving them to Walmart, it seems, and many of them drive with loud mufflers and such.  There's also a lot of overweight folks in these parts, more so than in many of the other places I've visited so far on my trip.  I guess the food must be really good here?
