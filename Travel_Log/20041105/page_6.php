Tomorrow promises to be a big day for me, I'm going to Mammoth Caves.  I visited Carlsbad Caverns in NM as a kid, and I now find myself wondering how Mammoth will measure up.  Well, I guess I'll find out soon enough tomorrow.  I hit the hay early in proparation for a long day of touring tomorrow.
