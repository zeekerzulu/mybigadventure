I complete my ride just in time. Soon it will be dark and I had forgotten to bring my bike light along on the ride.  I'm so glad the ride is over. I'm more tired than expected.  I shouldn't be surprised though, it has been quite a while since I last rode such a long distance.
<p>
After stowing the bike and changing out of my biking clothes, I head back through Lake Placid then due north again, to Wilmington North Public Campground.  It turns out to be a nice little campground run by NY State.  I shower and eat dinner.  Afterwhich I download all my pictures for the day onto my laptop then do a little travel writing before retiring for the evening.
