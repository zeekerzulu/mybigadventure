<p>
And then I see the problem, the road is gated, no vehicles are allowed.  Major bummer!  Being forced to first hike to Marcy Dam effectively adds an additional 2.5 miles each way.  Damn!  So here I am, it's close to noon, and I have to tack on an additional 5 miles to the hike.  So it all boils down to hiking a total of 15 miles with a total altitude gain of more than 3,700 feet.  Hmmmm.  Well this hike has really turned into a challenge.  It is long, it is high, it is late in the day, and probably worst of all, I'm not in peak form due to the toll yesterday's bike ride has taken on me.
<p>
But you know what they say, "no brain, no pain."  And when it comes to certain challenges, my brain shrinks to a peanut-sized nugget.  So the plan is still a go, hike to Mount Marcy or bust.  But I have to be quick about it.  There are loads of black bears lurking about in the forest and I don't want to get caught hiking out alone in the dark.
<p>
<a href="index.php?action=Pics&name=Daily/20040923.1/DSCN0060.JPG"><img src="Pics/Daily/20040923.1/Small/DSCN0060.jpg"></a>
<p>
Not wasting a single moment, I quickly park the van and get ready for my hike.
<p>
I pull out my old leather hiking boots and put them on.  Immediately I run into a problem.  They are really irritating one of my ankles.  Why?  Well the day before my foot slipped off one of my bike peddle shoe clips as I tried to snap into it.  As a result I jammed the clip hard against my ankle, bruising it pretty bad.  So it's on to Plan B, hike with my sneakers.  Now that kinda sucks because this hike is going to be very rocky and my leather boots provide a certain measure of ankle support.
<p>
<a href="index.php?action=Pics&name=Daily/20040923.1/DSCN0059.JPG"><img src="Pics/Daily/20040923.1/Small/DSCN0059.jpg"></a>
<p>
So I canceled my hike. Yeah, right. No, I just put on my sneakers, problem solved.
<p>
<a href="index.php?action=Pics&name=Daily/20040923.1/DSCN0056.JPG"><img src="Pics/Daily/20040923.1/Small/DSCN0056.jpg"></a>
<p>
Overflowing with both water and granola bars, I'm ready to start my hike. 
