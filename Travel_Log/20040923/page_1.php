I wake with the desire to mountain bike Whiteface Mountain (yesterday I tried but the ski lift was broken) but have to postpone my plans.  I discover after walking around a bit that I'm just too stiff and sore to entertain any hard-core mountain biking.  So my fall-back activity?  Well it's hiking of course.
<p>
I crack open the laptop and hunted around of a challenging but fun hike via my GPS software.  After a little soul searching (I'm sore, but hiking is easier than biking for me, so a hard hike is okay, right?) I decide to hike the tallest peak in NY State, Mount Marcy.  The GPS tells me I can start at Marcy Dam, which means the total round-trip hiking distance will be around 10 miles.
<p>
Well that doesn't seem so bad, right?
