All in all the day turns out to be a good one.  The weather was sunny, I enjoyed the sights, and I didn't get hit by a car.  Regarding cars and traffic, in Canada they do things differently in regards to traffic control.  First, their green lights flash, perhaps to get the attention of those folks who don't notice the light has turned from red to green.  Secondly, the crosswalks make a funny chirping noise.
<p>
<a href="index.php?action=Pics&name=Daily/20040717/78.JPG"><img src="Pics/Daily/20040717/78_sm.JPG"></a>
<p>
The chirping noise alerts the pedestrian that it's okay to walk across the street.  The chirping comes from a little box mounted next to the walk-don't-walk signal.  Like the drivers, perhaps the pedestrians also mentally wander off on tangents and forget the walk sign has turned to their favor.
