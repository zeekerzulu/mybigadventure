After spending more than two weeks in Western NY visiting my family and friends, I'm now ready to hit the road once again.  After spending the night at Aunt Chris and Uncle Bob's place, I wake early to get a good start on my day.
<p>
<a href="index.php?action=Pics&name=Daily/20040921/DSCN0003.JPG"><img src="Pics/Daily/20040921/Small/DSCN0003.jpg"></a>
<p>
Greeting me with a smile, Uncle Bob is already up with his morning coffee in hand.  We chat for a bit, then regretfully exchange our goodbyes as I step into the van, my humble home on wheels that has taken me into and out of so many lives on this trip of mine.  As I pull out of the driveway, Uncle Bob is sitting on the front porch steps, waving a fond farewell.
<p>
I feel rather sad now, not knowing when I'll see him and all my other NY-based family and friends again.  But the time I've spent with them all during my short stay was sufficient in quality and quantity to produce a trailer-full of wonderful memories.  So amidst the sadness of separation, I smile, knowing that my trailer of memories are firmly connected to my van's hitch as I turn out of the driveway and head down the road.
<p>
Up to this point I've traveled more than 5,000 miles to get to NY and am now ready to dive deeper into NY State.  My destination?  The Adirondacks.  I have visited the Adirondacks twice in the past when I lived in NY but always in the summer, never in the fall.  So my third visit will be a new experience for me, one filled-full of vibrant colors and pleasant smells of the fall season.
<p>
