Not too far into my drive my stomach starts grumbling for some morning grub.  Since I want to make good time on the road today, I opt for the path of most convenience and least health, I go to McDonalds.
<p>
<a href="index.php?action=Pics&name=Daily/20040921/DSCN0007.JPG"><img src="Pics/Daily/20040921/Small/DSCN0007.jpg"></a>
<p>
Whenever I go to McDonalds for breakfast I always order the Sausage McMuffin and Pancakes.  It doesn't taste too bad but I have to admit it's really packed full of salt.
<p>
<a href="index.php?action=Pics&name=Mishaps/20040921_1.JPG"><img src="Pics/Mishaps/20040921_1_sm.jpg"></a>
<p>
I quickly wolf down my breakfast then head out the door.  On the way to the parking lot I notice Ronald McDonald waiving goodbye to me.  He always seems like such a happy guy.  Maybe too much helium from the McDonald party balloons?  As I pass him by I notice Ronald has had an <a href="index.php?action=Stats&stat=Mishaps&date=20040921&page=10"> accident</a> of sorts.  But you know what?  Helium addict or not, Ronald is a real trooper in my book.  Despite his little embarrassing incident, he's all smiles and waves.
