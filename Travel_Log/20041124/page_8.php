The Cliff Dwellings are tucked under a sandstone overhang above the road, with a three-story pueblo building for the museum and a tipi out front, for good measure.
<p>
<a href="index.php?action=Pics&name=Daily/20041124/DSCN0332.jpg"><img src="Pics/Daily/20041124/Small/DSCN0332.jpg"></a>
