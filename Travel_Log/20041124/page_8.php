<p>
When I pull in there are tons of kids crawling all over the dwellings like ants on a hill.  By the time I start my tour they've scattered.  I get the ruins to myself and some clean pictures.
<p>
<a href="index.php?action=Pics&name=Daily/20041124/DSCN0341.jpg"><img src="Pics/Daily/20041124/Small/DSCN0341.jpg"></a>
