<p>
The tour is self-guided.  Numbered panels explain the grinding stones, the storage bins, the rooms where people cooked and slept.  Every doorway is small.
<p>
<a href="index.php?action=Pics&name=Daily/20041124/DSCN0353.jpg"><img src="Pics/Daily/20041124/Small/DSCN0353.jpg"></a>
