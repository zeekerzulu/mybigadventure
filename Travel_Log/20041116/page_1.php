Here's the Walmart in Pecos, TX, my campground and temporary home away from home.  "We Sell For Less" is their motto, "Satisfaction Guaranteed" is another.  Most folks either like Walmart or dislike Walmart.  And then there are individuals like myself who are torn.  I don't much like Walmart because they tend to run the local merchants out of town. So I try not to shop there if I can help it, but I do like to overnight in their parking lots.  So, what does that make me?  A bad person?  A conflicted person?  I'm not sure, should I feel bad about parking in their lot without buying something?
