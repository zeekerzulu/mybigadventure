<p>
After my official tour of Sandpoint comes to an end I decide to drive around and sniff out a wireless Internet signal.  I tell ya, Sandpoint, ID ain't no Seattle, WA when it comes to wireless access.  It takes me over 15 minutes of driving around to lock on just one lousy signal.  Fortunately I'm able to jump on so I park the van for the night where the signal is the strongest.
<p>
This is the first night of my trip that I have to deal with bugs.  Somehow a million baby mosquitoes find their way into the van and I cannot get them to leave.  So I guess I'll need to put on some Deet before I retire for the evening.
<p>
Tomorrow is going to be a fun bike riding day.  I'm slated to ride a really nasty mountain bike trail.  I'll probably be pushing my bike up a lot of hills tomorrow but as they say, no pain, no gain.
