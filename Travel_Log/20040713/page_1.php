The time has arrived to leave the hustle and bustle of Seattle, the road is once again calling my name to seek out new and interesting adventure.  So, in the spirit of continual discovery, I head northward to the <a href="javascript:myPopup1('http://www.sanjuanisland.org')">San Juan Islands</a>.  During my research of this popular tourist destination I learn the islands are actually eroded remnants of ancient mountain-tops, having lost their prominance long ago to the newer American mainland.   Not surprisingly, the islands are quite hilly, the tallest hill, or rather mountain, being Mount Constitution, sits .5 miles high.
<p>
My final destination for the day? <a href="javascript:myPopup2('http://www.friday-harbor.com')">Friday Harbor</a>, Washington.  Located on the largest and most westerly of the San Juans, Friday Harbor is a small community of approximately 2,000 permanent residents.  On the island you'll find many a harbor and even a small airport if you wish to come and go via air.  I've never been there before, but many a time I've heard people rave about its charm and natural beauty.
