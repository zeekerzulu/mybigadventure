Gore Creek from the bridge, then the Starbucks (I told you) and another $3 for parking.  I write and process photos until I can't.  Here's the truth: I'm bored out of my mind and alone, and tonight I'm a little tired of being alone.  Some nights the van is a very small place.  When I'm not touring I'm in a coffee shop, a bar or a restaurant, so I fear I'm destined to become a caffeine addict, a drunk, or really fat.  Patrick calls and says look into Google AdSense for the website, so that's something.  I drive to Avon looking for somewhere to hang out, circle for a Subway, ask three sets of really friendly people, find it, then call Wal-Mart for directions and end up back on I-70 toward Vail.  Park, bury myself under five layers, and crash.  Tomorrow I ski.  The next two weeks are going to be the longest of the trip.
