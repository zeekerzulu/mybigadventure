Finally!  I've reached the Louisiana state border.  Immediately thereafter I spy a Welcome Center where I pull in to grab me some tourist booty!  I score a couple of useful brochures, the most worthwhile being a detailed map of the city of New Orleans.
<p>
<a href="index.php?action=Pics&name=Daily/20041111/DSCN0164.jpg"><img src="Pics/Daily/20041111/Small/DSCN0164.jpg"></a>
<p>
With still about 80 miles to go, I plug along down the highway to New Orleans.  Ho Hum.
<p>
I arrive in New Orleans after nightfall.  Totally unfamiliar with all areas outside of the French Quarter (years ago I visited a week before Fat Tuesday), I wander around the city looking for an Internet connection.  I must admit, many of the areas I pass through on my search are really run-down.  Certain sections of New Orleans are really poor.  Some are so bad that I hate to venture what would happen if the van was to break down there.
<p>
I finally find an Internet connection, catch-up on my email, then call around for find a Walmart to overnight at.  My second call snags me one that's close to the French Quarter, perfect!  I drive there and settle in for the evening.  Tomorrow I have plans to tour the French Quarter.  The weather today was pretty crummy, I'm hoping tomorrow provides a better, brighter touring weather day for me.
