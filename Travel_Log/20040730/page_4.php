After cleaning up I high-tail it back to Bozeman.  On the way out I'm able to snap a good picture of the road's washboard problem, the problem I mentioned earlier.  It's caused by water draining across the road.  Over time the grooves will grow wider and deeper, making fast driving a teeth-chattering experience.
