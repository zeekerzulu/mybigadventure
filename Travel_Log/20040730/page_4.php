After returning from the ride I throw my bike back on the rack then step inside the van for a washcloth bath.  It's a pretty sweet setup.  The van's double doors face away from the empty parking lot so I can leave them open as I strip naked and cleaned up.  It's a bath with a grand view of Montana wilderness at its best!
