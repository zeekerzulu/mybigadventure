As I walk I can see one of the Grand Tetons peaking over the distant hills, it is calling to me.  Today is going to be a bike riding day.  It'll feel good to be back in the saddle again, having not biked for a long 2 weeks.  The day's bike ride will take me up Shadow Mountain, a 8.9 mile loop on gravel road, plus double and singletack trails.  I've picked it because to the west the view of the Grand Tetons promises to be spectacular.
<p>
