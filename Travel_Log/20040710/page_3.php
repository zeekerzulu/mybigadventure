A little more driving takes me to the day's destination, a campground just outside of Fife's Ridge.  Here's home sweet home, well, at least for tonight and the next day.  I'm sharing a small campground with 5 families, all motocross enthusiasts.  I thought they'd be a rowdy bunch come nightfall, but, they're as quiet as church mice.  I'm surprised the following morning to see they brought their dogs, a total of 6, and I only heard an occasional bark.  Great neighbors, indeed.
