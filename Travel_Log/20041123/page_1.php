<a href="index.php?action=Pics&name=Daily/20041123/DSCN0006.jpg"><img src="Pics/Daily/20041123/Small/DSCN0006.jpg"></a>
<p>
Let's get a closer look at this thing.  Fuel, food, firewood, film.  As you can see, it's a bit of a fire hazard.  I don't smoke, and today I'm glad.
<p>
<a href="index.php?action=Pics&name=Daily/20041123/DSCN0007.jpg"><img src="Pics/Daily/20041123/Small/DSCN0007.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041123/DSCN0009.jpg"><img src="Pics/Daily/20041123/Small/DSCN0009.jpg"></a>
<p>
The only way through is to dump it on the carpet and sort: gas here, food there, everything else over yonder.  Four and a half months of road trip in little paper rectangles on Paul's floor.  Humbling, and not just because of the fast food.
<p>
<a href="index.php?action=Pics&name=Daily/20041123/DSCN0008.jpg"><img src="Pics/Daily/20041123/Small/DSCN0008.jpg"></a>
<p>
Several hours later the cabbage is a zip-lock bag, flat, sorted and dated.  Financial accounting, trip-style.  The rest of the day is travel writing and hanging out with Paul.  I have to admit, it's nice sleeping inside.  A real bed, a real furnace, a bathroom that isn't a hike.  Best not to get used to it, because when I leave Paul's the van and I go back to the freezing cold.  Can't say I'm looking forward to that.  Hit the hay around 12:30, late for a day whose big event was paperwork.
