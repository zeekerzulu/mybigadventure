Up at 7:30, which for me counts as the crack of dawn.  The sky over Paul's place is doing its innocent act, blue and calm, but the mountain forecast says Pikes Peak is a no-go.  Rats.  No backup plan, so today the trip plans me, and it plans a day off.
<p>
<a href="index.php?action=Pics&name=Daily/20041123/DSCN0001.jpg"><img src="Pics/Daily/20041123/Small/DSCN0001.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041123/DSCN0003.jpg"><img src="Pics/Daily/20041123/Small/DSCN0003.jpg"></a>
<p>
So what does a guy do with a free day in a warm apartment?  He faces the thing he's been avoiding since Portland.  Receipts.  Every gas station, grocery store and greasy spoon since July 8th has handed me a slip of paper, and every slip went into the same wad.  Here it is, roughly the size and shape of a cabbage.
<p>
