Up at 7:30, which for me on this trip counts as early, and the sky over Paul's place is doing its innocent act again: blue, calm, not a cloud.  The mountains are another story.  Today was supposed to be Pikes Peak, but the forecast up high is nasty enough that I scuttle the whole idea.  No backup plan, no problem.  Some days the trip plans you, and today it plans a day off.
<p>
<a href="index.php?action=Pics&name=Daily/20041123/DSCN0001.jpg"><img src="Pics/Daily/20041123/Small/DSCN0001.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041123/DSCN0003.jpg"><img src="Pics/Daily/20041123/Small/DSCN0003.jpg"></a>
<p>
So what does a guy do with a free day in a warm apartment?  He faces the thing he's been avoiding since Portland: the receipts.  Every gas station, grocery store, campground and greasy spoon since July 8th has handed me a slip of paper, and every slip has gone into the same wad.  Here it is next to the laptop, roughly the size and shape of a cabbage.
<p>
