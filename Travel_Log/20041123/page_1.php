<p>
Let's get a closer look at this thing.  Fuel, food, firewood, film.  As you can see, it's a bit of a fire hazard.  I don't smoke, and today I'm glad.
<p>
<a href="index.php?action=Pics&name=Daily/20041123/DSCN0007.jpg"><img src="Pics/Daily/20041123/Small/DSCN0007.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041123/DSCN0009.jpg"><img src="Pics/Daily/20041123/Small/DSCN0009.jpg"></a>
<p>
The only way through is to dump it all on the carpet and start sorting: gas in one pile, food in another, everything else in a third.  Four and a half months of a road trip, laid out on Paul's floor in little paper rectangles.  It's humbling, and not only because of the fast food.
<p>
<a href="index.php?action=Pics&name=Daily/20041123/DSCN0008.jpg"><img src="Pics/Daily/20041123/Small/DSCN0008.jpg"></a>
<p>
Several hours later the cabbage has become a zip-lock bag, flat, sorted and dated.  Financial accounting, trip-style.  The rest of the day is travel writing on the laptop, hanging out with Paul in the evening, and not much else to report.
<p>
As an aside, I have to admit it's nice sleeping inside.  A real bed, a real furnace, a bathroom that isn't a hike.  But it's best not to get too used to this.  When I leave Paul's place the van and I go back to sleeping in the freezing cold, and I can't say I'm looking forward to that.  I hit the hay around 12:30, which is late for a day where the big event was paperwork.
