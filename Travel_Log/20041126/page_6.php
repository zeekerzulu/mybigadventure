Here's what I wrote from the coffee house that night: I'm finding myself in Idaho Springs, sitting in a coffee shop and hiding out from the cold.  Shortly the barista will be kicking me out, for the clock will soon roll around to 7:30.  So down the street I'll meander, to any ole bar, to extend my current addiction for anything and everything warm.  You see, the nights are cold up here in the mountains, and tonight's forecast calls for a low of something ridiculous like 11 degrees.  I've never slept in 11-degree weather.  While ill-prepared psychologically, I have at least prepared practically: two Indian blankets, five layers of covers, a sleeping bag with a hoodie, winter underwear and half a brain.
<p>
In all honesty, my primary concern isn't for my own well-being.  No.  It's for the laptop.  Running a laptop in very cold temperatures is never a good idea, the hard drive just doesn't like it.  So how do I keep it warm?  Since the only source of heat at night is me, I will have to sleep with my laptop.  Yeah, sounds a little strange, maybe even kinky.  But if I roach my laptop, my travel writing is pretty much screwed.  Suppose I froze to death in my sleep.  What would the eulogy be like?  "He loved life, he loved his friends, he loved his family, and he loved his laptop, right up until the very end.  Loved the laptop, that is..."
