Near the tail-end of my dinner I begin to hear a chorus of curious popping noises.  Soon thereafter, I go outside to investigate and am greeted by a lightshow of major proportions.  What could be possibly be going on?  It's October 20th, what is so special about today?
<p>
After taking in the fireworks for about 5 minutes, I start asking strangers if they know what the celebration is all about.  The third person I ask knows full-well what's going on.  Today is the last game in a 7-game baseball series.  The Boston Red Sox and the NY Yankees go head-to-head tonight in NY, both will fight tooth and nail to win the American League Pennant.
