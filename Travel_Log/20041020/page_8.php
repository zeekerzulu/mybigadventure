Instead of opting for formal dining at such places as Houston's, I go for <a href="javascript:myPopup4('http://www.boston-online.com/cityviews/quincy_market.html')">Quincy Market</a>.  Built in 1742 as a wholesale market, the building also hosts a large meeting hall on the second level.  Believe it or not, it's the most visited tourist destination in Boston, probably because people go there to eat more than anything else.  I suppose if there was a very large, historic bathroom facility next door, I suspect it would give Quincy Market a run for its money in the popularity department.
