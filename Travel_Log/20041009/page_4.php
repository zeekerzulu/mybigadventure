At Bill's place we meet up with his girlfriend, Louise, who swung by to say hi.  I had heard all about her from Bill and was looking forward to meeting her.  Turns out, Louise is a real sweetie, she's chocked-full of energy and exuberance.  I really enjoyed chatting with her, and listening to her thick French accent.  Oui, oui, very nice indeed.
<p>
