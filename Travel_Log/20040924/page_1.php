I wake to a sore knee, it's still bothering me from yesterday's hike up Mount Marcy.  After some consideration I decide the day was going to be a "down" day for me but I don't want to spend the entire day holed-up at the campsite.  It's just too nice a day to throw it away like that.  So I decide to tour Lake Placid, an activity requiring only a little walking on relatively level surfaces.  Lake Placid is a quaint little village bordering Mirror Lake.  Having hosted the 1932 and 1980 Winter Olympics, it's a bit of a tourist trap but not "over-the-top" touristy.
