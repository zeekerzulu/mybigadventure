Happy Halloween! Up and at'em at 9am, I'm out of the van and knocking on my Uncle's door.  He quickly answers and into the house I go, where we catch-up a bit on things before setting down for some breakfast.  It's so good to see my <a href="index.php?action=Stats&stat=Family&date=20041031&page=8">Uncle Donald</a> again, I haven't seen him for almost 10 years.
<p>
After breakfast we both set to task, harvesting a boatload of sage that have been hanging and drying for a quite while in his kitchen.  You see, my Uncle is an excellent cook, he does this kind of thing all the time.  All the while, we continue to reminisce about the old times on the farm.  My paternal grandparents, Uncle Don's parents, were farmers.  As I kid I spent a lot of time with grandpa, tending to the cows, making straw forts in the hay barn, you know, fun kid stuff.
<p>
After lunch we go to his office (he's a commercial photographer) to play around with Photoshop.  I have a digital photo, my favorite so far from my trip, that he wants to tweak in an effort to clean things up.
