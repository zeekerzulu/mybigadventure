<p>
In front of Union Station you'll find the Columbus Memorial Fountain.  Unveiled in 1912, the fountain was made possible by lobbying efforts of the royal fraternity of brothers, the Knights of Columbus.  During the ceremony, 20,000 Knights marched in the parade.
<p>
<a href="index.php?action=Pics&name=Daily/20041025/DSCN0330.jpg"><img src="Pics/Daily/20041025/Small/DSCN0330.jpg"></a>
<p>
The memorial's inscription reads "To the memory of Christopher Columbus, whose high faith
and indomitable courage gave to mankind the new world".
<p>
While researching the memorial, I stumble across an interesting <a href="javascript:myPopup8('http://www.dc-movies.com/search.asp?subject=41')">website</a> that lists the popular, and not so popular, movies that have been shot in and around the various sights and venues that Washington, D.C. has to offer.  According to the site, the following movies have scenes capturing the Memorial Fountain - <i>Along Came a Spider, Collateral Damage, Earth vs. the Flying Saucers, Eye of the Beholder, and Hannibal.</i>
<p>
<a href="index.php?action=Pics&name=Daily/20041025/DSCN0329.jpg"><img src="Pics/Daily/20041025/Small/DSCN0329.jpg"></a>
<p>
Apparently, I'm not the only one finding the memorial useful. Me for learning, this individual for sleeping.  I've seen quite a few homeless people today, this is just one of many.
<p>
