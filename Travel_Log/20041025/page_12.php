<p>
In between Union Station and the fountain I spy <a href="javascript:myPopup9('http://www.libertybellmuseum.com/morereplicas/dcfreedombell.htm')">The Freedom Bell</a>.  Having traveled to all 48 contiguous states aboard <a href="javascript:myPopup10('http://www.freedomtrain.org/aft_home.htm')">The Freedom Train</a> between 1975 and 1976, the bell now permanently rests here in D.C.  Cast in the same foundry as the <a href="javascript:myPopup1('http://www.ushistory.org/libertybell/')">Liberty Bell</a>, this bell is nearly twice as large.
<p>
It looks like the bell has its ringer, I wonder what it sounds like?  I don't plan to actually ring it, too many police are milling around, but I do take a peek underneath and discover that many others have been here before me.  Unfortunately, some of them have felt inclined to leave a message behind.  Well, at least they are hidden from view.
