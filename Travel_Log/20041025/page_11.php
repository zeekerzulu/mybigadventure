Nearby I encounter a prominent landmark, <a href="javascript:myPopup5('http://www.aoc.gov/cc/grounds/art_arch/peace.cfm')">The Peace Monument</a>.  Erected in 1877-78 to commemorate Civil War era deaths at sea, this 44-foot high white marble monument captures my imagination with its figures representing Grief, History, Victory, and Peace.  Additionally, near the base of the memorial, Mars, the God of War, and Neptune, the God of the Sea, are embodied in the form of pudgy cherubs.
<p>
