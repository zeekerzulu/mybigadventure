<p>
After entering the Smithsonian Castle, I notice a small corridor to the left of the entrance hall.  In this little nook I discover the tomb of <a href="javascript:myPopup2('http://www.sil.si.edu/Exhibitions/Smithson-to-Smithsonian/who_01.html')">James Smithson</a>, who was the sole catalyst behind the formation of the Smithsonian Institution.  A rather historically obscure individual, the instructions in his Will were to give to the United States the lofty sum of more than $500,000, to be used to underwrite a place of science and learning called the Smithsonian Institution.  There was a catch, however.  This donation would only be made if his nephew and sole heir failed to have children, legitimate, or otherwise.  In the end, no kids were fathered, so when the nephew died, the money was given to the U.S., but not until a bit of <a href="javascript:myPopup3('http://www.sil.si.edu/Exhibitions/Smithson-to-Smithsonian/accepting_01.html')">controversy and debate</a> first played-out across the country.
<p>
Once the hubbub subsided and the money was accepted, the initial general consensus was to create a national university.  However, the devil is in the details, and a slew of important people from around the country piped in with <a href="javascript:myPopup4('http://www.sil.si.edu/Exhibitions/Smithson-to-Smithsonian/compromise_01.html')">ideas</a> about what kind of national university it should be.  The debate then took a left turn and talk of forming a national museum gained some traction, which was followed by propositions of a national scientific institute, then talk of a national observatory, then a national library, then back around again to a national university.  Are you dizzy yet?
<p>
Finally, on August 10, 1846, the Smithsonian Institute was created!  Since then, loads of great things have happened.  You can get the skinny on the rest of the story <a href="javascript:myPopup5('http://www.sil.si.edu/Exhibitions/Smithson-to-Smithsonian/compromise_06.html')">here</a>, as well as just what kind of place the institute panned out to be.
