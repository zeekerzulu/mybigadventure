My next stop, <a href="javascript:myPopup9('http://www.si.edu/')">The Smithsonian Institution's</a> first building, the <a href="javascript:myPopup10('http://www.si.edu/visit/infocenter/sicastle.htm')">Smithsonian Castle</a>.  Completed in 1855, this eloquent landmark embraces the 12th century architectural motifs of late Romanesque and early Gothic.  Here you'll find both the Institution's administration offices and the <a href="javascript:myPopup1('http://www.si.edu/visit/')">Smithsonian Information Center</a>.
