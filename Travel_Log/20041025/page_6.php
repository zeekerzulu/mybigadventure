<p>
Here's the <a href="javascript:myPopup7('http://www.si.edu/ai/')">Smithsonian Arts and Industries Building</a>.  Completed in 1881, the building embraces a High Victorian style of architecture.  Upon completion, the National Museum was promptly moved from the Smithsonian Institution Building to this building, providing a fully dedicated space needed for the ever-expanding museum.
<p>
<a href="index.php?action=Pics&name=Daily/20041025/DSCN0168.jpg"><img src="Pics/Daily/20041025/Small/DSCN0168.jpg"></a>
