Now this is fun.  They've erected a simulation of the solar system, stretching across a portion of the National Mall.  I'm currently at Neptune and am working my way towards the Sun.  Did you know Neptune is the windiest planet in the solar system?  How do they calculate that?  Science is just amazing, eh?
