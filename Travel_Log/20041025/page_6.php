<p>
In front of the Smithsonian Castle there's this impressive statue.  My first thought is it's a memorial to James Smithson, but, upon closer inspection, the statue is actually that of <a href="javascript:myPopup6('http://www.si.edu/archives/ihd/jhp/joseph01.htm')">Joseph Henry</a>.  Certainly not a household name of our times, he was quite an important and influential individual back in the day when the Smithsonian Institution was in its infancy.
<p>
The Institute's first Secretary, Henry was pivotal in ensuring the Institution's charter of embracing basic research was not sidetracked by outside influences intent on using the Institution for their own financial and/or political gain.  If not for Joseph Henry, the Smithsonian Institution may very well have evolved into something completely different, which certainly would have been a shame.
<p>
<a href="index.php?action=Pics&name=Daily/20041025/DSCN0160.jpg"><img src="Pics/Daily/20041025/Small/DSCN0160.jpg"></a>
<p>
I hear music.  What's this?  Am I in an amusement park?  I wish I had more time, I'd like to ride the carousel.  I wonder if the politicians ride on it?  I can see it now, the Republicans only ride the elephants and the Democrats only ride the donkeys.
<p>
