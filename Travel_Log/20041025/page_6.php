<p>
After my little artifact tour, I make my way outside again and continue my counterclockwise jaunt around the National Mall.  In the distance, to the west, I see the Washington Monument and to the east I see the U.S. Capitol.  What on earth is going on over at the U.S. Capitol?  What is the crane being used for?
<p>
