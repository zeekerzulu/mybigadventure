Making my way westward now on the northern side of the National Mall, I quickly run into the East Building of the <a href="javascript:myPopup7('http://www.nga.gov/home.htm')">National Gallery of Art</a>.  Displaying mostly 20th century art, the futuristic East Building offers mammoth display spaces that are perfect for supporting large touring exhibitions.  Opened in 1978, the gallery is triangular in shape and supposedly possesses the sharpest corner of any building ever constructed.
