I pass by the <a href="javascript:myPopup5('http://www.aoc.gov/cc/grounds/art_arch/garfield.cfm')">James A. Garfield Monument</a>.  Around the monument's base you'll find three allegorical figures who represent Garfield in three separate phases of his life; the student, the warrior, and the statesman.  <a href="javascript:myPopup6('http://www.whitehouse.gov/history/presidents/jg20.html')">James A. Garfield</a> only served 4 months as President, having been assassinated in 1881 by a disgruntled office-seeker.
