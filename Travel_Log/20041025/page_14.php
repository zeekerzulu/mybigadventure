Located on <a href="javascript:myPopup3('http://www.capitolhill.org/main%20page.html')">Capitol Hill</a>, across from the U.S. Capitol Building, the <a href="javascript:myPopup2('http://www.supremecourtus.gov/')">U.S. Supreme Court</a> is my next sightseeing destination.  Consisting of a single Chief Justice and eight Associate Justices, the court was created in 1790 in response to a provision within the U.S. Constitution, "...the judicial Power of the United States, shall be vested in one supreme Court, as in such inferior Courts as the Congress may from time to time ordain and establish."
