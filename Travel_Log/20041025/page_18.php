<p>
Next I pass by the <a href="javascript:myPopup2('http://www.archives.gov/')">U.S. National Archives and Records Administration</a>, home of America's most famous, historical documents, including the <i>Declaration of Independence</i>, the <i>U.S. Constitution</i>, and the <i>Bill of Rights</i>.  Not only is the government interested in making these and many other documents available for public display, they are equally interested in preserving the documents through advanced science and technology.
