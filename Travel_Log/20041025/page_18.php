Justice I say!  I want justice!  And what better place to get it than at the <a href="javascript:myPopup2('http://www.usdoj.gov/')">Department of Justice</a>.  I walk up to the door and give the knocker like handle a couple of really hard whacks!  And then I run like hell!  Ah, just kidding, I didn't knock on the door, but, I really wanted to, that's got to count for something, right?
