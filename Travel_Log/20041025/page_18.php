My next stop is the <a href="javascript:myPopup9('http://www.nga.gov/feature/sculpturegarden/general/index.shtm')">National Sculpture Garden</a>.  Unfortunately, it's closed for some reason, so I resort to taking my pictures through the fencing.  The garden contains <a href="javascript:myPopup10('http://www.nga.gov/feature/sculpturegarden/sculpture/index.shtm')">17 modern sculptures</a>, ranging from a <a href="index.php?action=Stats&stat=Oddities&date=20041025.5&page=38">huge typewriter eraser</a> to a large metal spider.
<p>
Scanning my tour map for interesting sights off the National Mall, I decide to trek out to Ford's Theater, the place where President Abraham Lincoln was assassinated in 1865 by the well-known actor, John Wilkes Booth.
<p>
<a href="index.php?action=Pics&name=Daily/20041025/DSCN0449.jpg"><img src="Pics/Daily/20041025/Small/DSCN0449.jpg"></a>
<p>
On the way I pass by the <a href="javascript:myPopup1('http://www.ftc.gov/')">Federal Trade Commission</a>.  Created in 1914, the charter of the FTC is to enforce a variety of federal antitrust and consumer protection laws.  The commission has the teeth to investigate and regulate business practices relating to advertising, promotion, sales, or any other business practice that has the potential to cause unfair treatment and undue harm to the consumer.
<p>
