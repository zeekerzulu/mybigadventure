Soon enough I'm standing in front of the <a href="javascript:myPopup8('http://www.nasm.si.edu/')">Smithsonian National Air and Space Museum</a>, home of the world's largest collection of historic air and spacecraft.  Folks interested in researching the history, technology, and science behind the items in this fascinating exhibit will certainly walk away from the experience both educated and inspired.
<p>
There are actually two parts to the museum.  The one located here in the National Mall contains hundreds of artifacts including the original 1903 Wright Flyer, Lindbergh's Spirit of St. Louis, and the Apollo 11 command module.  The companion facility, the <a href="javascript:myPopup9('http://www.nasm.si.edu/udvarhazy/')">Steven F. Udvar-Hazy Center</a>, is located near the Dulles International Airport.  It contains the aviation and space artifacts that are too big to be exhibited here at the National Mall facility.  The collection includes a Lockheed SR-71 Blackbird, a Boeing Dash 80, the famous Boeing B-29 Superfortress, <i>Enola Gay</i>, and Space Shuttle <i>Enterprise</i>.  The bus now parked in front of the museum must shuttle visitors between here and the companion facility.
