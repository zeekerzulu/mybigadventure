Do you appreciate modern and contemporary art with an international bent?  If so, you should visit the <a href="javascript:myPopup7('http://hirshhorn.si.edu/')">Smithsonian Hirshhorn and Sculpture Garden</a>.  The museum is America's first modern and contemporary art museum, with much of its focus trained on acquiring and displaying art created within the last 30 years.  Famous pieces include works created by Picasso, Giacometti, de Kooning, and Warhol.
