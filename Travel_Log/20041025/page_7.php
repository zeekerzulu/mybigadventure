A stone's throw away is the Sculpture Garden.  I must admit, I do appreciate modern art, but only if it's art that I think I could never create on my own.  I'm no artist, I have no talent in that realm, but I can take paint and splat it on a canvas, or take a bunch if steel I-beams and throw them together.  Some folks consider such things art, I don't.  To me, everything I see here is art, with the exception to the red I-beam monstrosity.  Yikes!
