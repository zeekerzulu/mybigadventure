<p>
Looking at Washington, D.C. from 30,000 feet, the predominate area of interest to me, the <a href="javascript:myPopup10('http://www.nps.gov/nama/home.htm')">National Mall</a>, is about 2.5 miles long and .25 miles wide.  I'll attempt a counterclockwise spin around it, starting at the Department of Agriculture (see arrow). The ship is leaving, all aboard!  Get it?!?
<p>
<a href="index.php?action=Pics&name=Daily/20041025/DSCN0080.jpg"><img src="Pics/Daily/20041025/Small/DSCN0080.jpg"></a>
<p>	
I first pass by the <a href="javascript:myPopup3('http://www.usda.gov/wps/portal/usdahome')">U.S. Department of Agriculture</a> (USDA).  Founded in 1862 by President Abraham Lincoln, the department's initial mission was to provide seeds and crop growing information to the nation's farmers, who comprised 58% of the population.
<p>
Since then, the department has extended its reach into such areas as social welfare (Food Stamp, School Lunch, School Breakfast, and the WIC Programs), land management (oversees 192 million acres of national forests and other government land), natural resource conservation, food safety, and international food aid.
<p>
So, if you have questions about planting corn or raising cows, I guess this is the place to go.  I wonder, if I polled all the folks who work here, would most be willing to eat <a href="javascript:myPopup4('http://ma.essortment.com/geneticallyengi_rhjq.htm')">genetically altered food</a>?  My guess is they would be.
<p>
As for the ketchup fiasco back in 1981, when the USDA considered changing the <a href="javascript:myPopup5('http://childnutrition.doe.state.de.us/childnutrition/lunchprog.htm')">National School Lunch Program</a> Standards to allow ketchup to be counted as one of the required two fruits or vegetables (the complete list is meat, milk, bread, and two servings of fruit or vegetables), the decision made the Republicans look rather foolish.  Like most things, there is probably more to the story.
<p>
<a href="index.php?action=Pics&name=Daily/20041025/DSCN0083.jpg"><img src="Pics/Daily/20041025/Small/DSCN0083.jpg"></a>
<p>
Near the Metro-Smithsonian Station I spy a mounted officer from the <a href="javascript:myPopup7('http://www.nps.gov/uspp/')">U.S. Park Police</a>.  He's sitting high atop his horse and at the ready, to assist the public with directions and to crack heads if things get out of hand.
