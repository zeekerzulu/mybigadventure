Heading eastward toward the U.S. Capitol Building, I encounter the first exhibit of my tour.  Do you have any interest in Asian art?  If so, the <a href="javascript:myPopup8('http://www.asia.si.edu/')">Freer Gallery of Art</a> is the place for you.  True to its name, admission is free!  I'm not sure what the piece of artwork is on the front lawn?  A stone tongue?
