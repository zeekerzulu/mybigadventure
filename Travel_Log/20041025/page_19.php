I make my way past the <a href="javascript:myPopup3('http://www.fbi.gov/')">Federal Bureau of Investigations</a>.  Established in 1908 and initially comprised of 9 detectives, 13 civil rights investigators, and 12 accountants, the organization has since grown to 28,000 employees.  Yowza!
<p>
Here's a list of their priorities, sorted by most important first:
<ul>
<li>Protect the United States from terrorist attack.
<li>Protect the United States against foreign intelligence operations and espionage.
<li>Protect the United States against cyber-based attacks and high-technology crimes.
<li>Combat public corruption at all levels.
<li>Protect civil rights.
<li>Ensure the FBI Director doesn't get into the <a href="javascript:myPopup4('http://www.straightdope.com/columns/021206.html')">habit of wearing dresses</a>, unless of course, the position is occupied by a woman.
<li>Combat transnational and national criminal organizations and enterprises.
<li>Combat major white-collar crime.
<li>Combat significant violent crime.
<li>Support federal, state, county, municipal, and international partners.
<li>Upgrade technology to successfully perform the FBI's mission.
</ul>
<p>
You know what?  I'm feeling a bit paranoid right now, can I get into trouble for taking pictures of the building?  I've heard that the government is somewhat worried about the possibility of terrorists casing out possible bomb targets, and that includes terrorists taking pictures of their intended targets.  I'm positive I'm being video taped right now.
<p>
So, what do I do?  Well, I take quick pictures and hide my camera in between shots.  In retrospect, that probably made me look even more suspicious.  Regardless, I manage to snap these few shots then make my getaway unimpeded.
