Finally, I've made it to <a href="javascript:myPopup5('http://www.fordstheatre.org/')">Ford's Theater</a>!  Made forever popular by the unfortunate demise of one of American's greatest Presidents, Abraham Lincoln, the theater today is a live and working theater.  Serving as a tribute to Lincoln because of his love of the performing arts, after being closed for 103 years, in 1968 its doors reopened, effectively reclaiming and sharing this national treasure with the public at large.  Hmmm... I wonder if you can sit in the same balcony seat that Lincoln had?
