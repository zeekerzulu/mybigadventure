The sun has just set and the moon has now taken its place as the premier sight in the heavens above.  It's a good thing my touring day is over, my feet are really killing me.  I didn't make it all the way around the National Mall like I had hoped to, I just made it a little more than half way.  Well, the time has arrived to head back to the van.  I take the train back then decide to do my laundry at the laundromat across from where I parked the van.  How convenient!
<p>
After completing my laundry, I drive back to the Walmart in Laurel, MD and settle in for the night, dining on a meal from McDonalds while working on the website.  For as skinny as I am, God, I'm getting fat from eating too much fast food.  My evening eventually winds down and I hit the hay.  I'm not sure if I'll tour tomorrow, I've feeling pretty drained right now, maybe tomorrow will be a day of rest for me.  My feet will certainly thank me for it.
