On my way back to the National Mall, I pass by the <a href="javascript:myPopup7('http://www.irs.gov/')">Internal Revenue Service</a>.  One of the world's most efficient tax administrators, annually they process more than 224 million tax returns and shovel in more than $2,000,000,000,000.00 a year.  Yes, that's right folks, there are 12, count'em, 12 zeros to the left of the decimal point!  The IRS mission statement states: "Provide America's taxpayers top quality service by helping them understand and meet their tax responsibilities and by applying the tax law with integrity and fairness to all."
<p>
Translation: Pay up or go to jail.
<p>
Heck, the IRS says they want to help me meet my tax responsibility?  Well, how about giving me a loan to help me pay my taxes, or better yet, forgive my tax debt.  Yeah, that would be good, I'd be on board with that!
