As I approach the machine I'm stopped in my tracks by the thought of what goes better with worms, cola or water?  My guess is cola, the sweetness compliments the worm taste I think.  Waaaait a minute!  It's a ploy for sure, to get me to accept this barbaric live bait machine.  Well they've failed to lured me into their thinking.
