My day is pretty much spent travel writing in the van at Walmart.  However, I did find the time to perform a rescue of sorts.
<p>
<a href="index.php?action=Pics&name=Favorites/Pictures/5080_1.JPG&nogallery=1"><img src="Pics/Favorites/Pictures/Small/5080_1.jpg"></a>
<p>
To my great surprise, I discover this live bait vending machine just outside Walmart.  I have never seen such a thing. When I first saw it I immediately thought about the live critters inside, like little prisoners on death-row.  All of them waiting in their chilled Styrofoam coffins for their fisherman executioner, who will buy them then implement a cruel injustice with hook, line, and sinker.  I had first noticed the vending machine two day's prior and since then the scene had been replaying over and over again in the back of my mind.
<p>
Just what could I do to make me feel better about it?  And then it hit me, I could perform a worm rescue!
<p>
