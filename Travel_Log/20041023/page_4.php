After the ship tour, I begin to wander along the waterfront and quickly notice the weather has turned significantly colder.  I may be smiling on the surface, but, on the inside I'm not a happy camper.  I'm cold, I'm grumpy, I'm hungry, I'm so done with my sightseeing today.  You know what?  I'm so done with all this cold weather.  I have plans to visit <a href="index.php?action=Stats&stat=Friends&date=20041015&page=14">Monica</a> in NYC on my way south but the cold weather, coupled with not looking forward to visiting that big, hectic city, is really depressing to me right now.
<p>
I make an executive decision, I will completely bypass NYC and head directly to Washington, DC.  I call Monica, but only get her answering machine.  I leave a message for her, explaining my situation.  I hope she understands.  I feel bad for bailing on her, but, I'm feeling really down right now.  I'm almost as down as I was on Wednesday when I was seriously thinking about bagging the rest of my trip and going back home to Portland, OR.  It's times like this when I think I'm at my most selfish.  When I cut bait in order to stay in the boat, rather than hold on, and risk getting pulled into the water.  Right now I've lost confidence in my swimming skills.  Part survival, part peace of mind, that is what I now seek.
<p>
With new plans in hand and some relief in sight, I grab some grub then hit the road.  I drive into the early morning on one of the longest legs of my trip so far.  Exiting Massachusetts, I pass through Rhode Island, Connecticut, New York and eventually conclude my long drive north of Trenton, NJ, at a NJ Turnpike rest stop.  Tired but thankful for all my southerly progress, I hit the hay and quickly fall asleep.
