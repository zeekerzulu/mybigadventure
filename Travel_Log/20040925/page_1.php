After rising I immediately notice my knee is feeling much, much better.  I not 100% sure if I'm ready to bike today but I'll give it a shot.  Worse case I'll just abort my biking if it starts hurting again.  Today should be an interesting one.  I plan to mountain bike down Whiteface Mountain.  Never have I biked a ski resort where you take the lift to the top and bike down.  I'm excited about the prospect because for me, mountain biking is all about the downhill.  My uphill traverse will be handled by a gondola ride.
