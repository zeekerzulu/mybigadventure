After dinner I hit the road for my long drive.  It's now after dark so no pictures to share, sorry.  I wish I had departed sooner since I'll be driving the northeastern portions of Yellowstone.  I neglected to tour that region of the park because of time constraints.  Oh well, if I visit Yellowstone again, I'll have to make a point to see it.
<p>
Stepping back and looking at the day's drive, it's a long one, and involves tacking on additional mileage due to road closures forced by ongoing road construction.  The Yellowstone's Eastern Pass closes at 8pm for night construction activities so I can't take Highway 14 directly to Cody, WY, my destination.  Instead, I have to drive back to Mammoth Hot Springs and head east from there which tacks on an additional 2 hours to my travel time.
<p>
Fortunately, the drive is uneventful.  During the drive there was a bit of up-and-down which makes me curious about all the missed vista opportunities.  That's one of the bad things about driving at night, wonderful, hidden things can pass you by.  As I drove I found myself looking forward to going to the rodeo in Cody, WY.  I've heard it's one of the best rodeos in the country.  When I was a kid my family would go to the local rodeo every year.  I just loved the rodeo.  I still do.
<p>
After arriving in Cody, WY around 1:30am in the morning, I take a washcloth bath then jump into bed.  The day proves to be a very long one but it was a good day, filled with a great bike ride, a nice dinner, and safe passage to Cody, WY.
