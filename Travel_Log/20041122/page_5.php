The hospitality lounge, where the tour ends and the real sampling begins, and a room full of strangers who've never met suddenly all get along.  Funny how that works.  I have a confession to make: I don't buy a single beer.  I'm a microbrew guy, and after a day inside the biggest brewery on the planet I find I'm still a microbrew guy.  Don't tell Adolph.  On the way out a wall of brass plaques honors the Coors employees who served in the military, hundreds of names, and I stop and read a few.  Then it's Visitors Exit, elevator, stairs.  The party's over.
