First, a little housekeeping.  I owe my buddy Sean a call tonight about meeting up in Vegas, so I spend a few minutes with the calendar figuring out where I'll be and when.  Then it's time for the real business of the day.  Let me put it this way: if you like beer, you are a man, you are in Denver, and you have a little time on your hands, you are obligated to take the Coors Brewery Tour in Golden, Colorado.  It's not a choice, it's a duty.  Paul's off doing whatever Paul does on a Monday, so this one's a solo mission.  North on I-25, and there's Denver doing its best impression of a big city.
