Good morning.  You know what?  I slept pretty well last night, and I think I know why.  Dancing beer cans.  All night long, a chorus line of silver cans high-kicking through my dreams like the Rockettes.  Why beer cans?  Because today I have plans to go on a tour that involves alcohol, and if luck prevails, free alcohol.  The van is ready and the sky is scrubbed Colorado blue.  I take this as a good sign.
