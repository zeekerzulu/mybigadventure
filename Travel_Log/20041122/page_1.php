Good morning.  You know what?  I slept pretty well last night, and I think I know why.  Dancing beer cans.  All night long, a chorus line of silver cans high-kicking their way through my dreams like the Rockettes.  Why beer cans?  Because today I have plans to go on a tour that involves alcohol, and if luck prevails, free alcohol.  Here's the van out front of Paul's place at 8:30, still wearing Saturday's snow like a bad toupee, and here's the sky, scrubbed that deep Colorado blue a storm leaves behind.  I take this as a sign.  The beer gods are smiling.
