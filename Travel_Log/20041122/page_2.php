Then the history lesson begins.  Adolph Coors and a partner named Schueler started this place in 1873 in a converted tannery, back when Golden was the capital of the Colorado Territory and Denver was the upstart down the road.  Look how that turned out.  Denver got the capitol, Golden got the beer.  I know which one I'd pick.
<p>
