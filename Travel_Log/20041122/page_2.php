The bus rolls up, we pile in, and a few minutes later we're deposited at the front door, where a copper kettle the size of my van stands guard.  I have a feeling I'm going to see a few more of these.  First order of business is a little card that says Keystone Light.  [What was the card for?  Group number, sample ticket, or did they hand everyone a brand to carry around?]  Keystone Light.  Of all the brands in the building, they hand me Keystone Light.  I try not to take it personally.
