Here's a good one.  Prohibition hit Colorado in 1916, four years before the rest of the country got the bad news, and Coors kept the lights on for thirteen dry years by making malted milk and porcelain.  Porcelain!  Somewhere out there is a toilet with the Coors name on it, and I want to see it.  Today the place employs 4,000-plus people here in Golden, with more plants in Tennessee and Virginia and one over in the UK.  The exhibits glow red like the inside of a beer can, which, now that I think about it, is probably the idea.
