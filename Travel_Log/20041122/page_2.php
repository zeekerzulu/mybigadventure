First order of business: a little card that says Keystone Light.  [What was the card for?  Group number, sample ticket, or did they hand everyone a brand to carry around?]  Then the history lesson begins.  Adolph Coors and a partner named Schueler started this place in 1873 in a converted tannery, back when Golden was the territorial capital and Denver was the upstart down the road.
