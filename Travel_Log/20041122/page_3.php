Wristband on, we're herded past a wall of barrels wearing every brand in the family: Coors, Coors Light, Killian's, Blue Moon, Keystone, Zima.  Zima!  Remember Zima?  Clear beer for people who didn't like beer.  Whatever happened to those folks?  I suspect they moved on to wine coolers and are doing just fine.
