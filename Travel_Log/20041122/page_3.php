<p>
Adolph Coors himself keeps watch from the wall, signature and all.  He was 26 years old when he opened this place.  At 26 I was, well, not opening a brewery.  I was drinking in one.  Different career path.  And yes, I'll make light of the name Adolf, or dark, depending on what's on tap.
<p>
