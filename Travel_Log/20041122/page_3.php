<p>
And then the brewhouse.  Copper kettles the size of small houses, lined up in a white tiled room like they're waiting for inspection.  This is the largest single brewery site in the world, they tell us, something like 81,000 gallons of beer a day if I heard the guide right, and standing here I believe it.  I should mention the guide is moving us along at a pretty good clip.  Good thing I'm taking pictures, otherwise I'd have no idea what I just saw.
