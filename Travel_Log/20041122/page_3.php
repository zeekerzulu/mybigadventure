And then the brewhouse.  Copper kettles the size of small houses, lined up in a white-tiled room like they're waiting for inspection.  The guide says this is the largest single brewery site in the world, something like 81,000 gallons of beer a day, if I heard her right.  Did I hear her right?  Hard to say, because the guide is moving us along at a pretty good clip.  I'd call it a brisk walk with occasional facts.  Good thing I'm taking pictures, otherwise I'd have no idea what I just saw.  Call it the Coors Brewery Jog.
<p>
