The grave sits at the top of the hill.  The short version of a long life: William F. Cody, born in Iowa in 1846, Pony Express rider (so he said), Army scout with a Medal of Honor, and the man who shot 4,282 buffalo in eighteen months to feed the railroad crews, which is how you end up with a name like that.  Then he figured out there was more money in pretending to be a cowboy than in being one, and took his Wild West show around the world for thirty years.  Queen Victoria saw it twice.  He died in Denver in 1917 and was buried up here, and Cody, Wyoming has never forgiven Colorado for it.  In 1948 the Cody American Legion offered $10,000 to anyone who'd steal the body, so Denver poured concrete over him.  Just in case.  He put on a show for half the world and ended up on a hill with a closed gift shop.
