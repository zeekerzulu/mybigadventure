The grave sits at the top of the hill behind an iron fence, a stone cairn with bronze plaques, snow in the cracks.  Buffalo Bill died in Denver in 1917 and was buried up here on Lookout Mountain, though Cody, Wyoming has never quite forgiven Colorado for it.  I put a hand on the stones.  Cold.
