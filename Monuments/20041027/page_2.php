Work recommenced on the obelisk in 1880.  The Maryland marble that was secured for the remainder of the construction was acquired from the same quarry, as well as from the same vein.  Unfortunately, the new marble was taken from a much lower stratum because of ongoing quarrying during the 25 years of construction inactivity.  As a result, a difference in rock color was realized, as evidenced by the really wide ring that runs from the 150 feet mark on up a good third of the monument.  Oops!  The first photo does a good job of pointing that out.
<p>
The top can be reached by a 70 second elevator ride, or, for the strong at heart, via an iron stairway.  Take the stairway option and you'll be spanked by 897 steps and 50 landings.  The interior walls are graced with 188 stone carvings, commemorating those individuals, groups, societies, cities, states, and nations who pitched in for its construction.
