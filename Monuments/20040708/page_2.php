<p>
I remember my hike up the mountainside to the crater was a tough one.  I was hell-bent on keeping a fast pace but wasn't accustomed to the steep incline.  Ascending more than 4,500 feet in less than 5 miles calls for a certain measure of restraint, but of course I ignored that.
<p>
About a half-mile from the top I reached the mountain's ash dome.  Ever try hiking up a steep ash slope?  It's sorta slippery, every two steps forward is met with one sliding step back.  Add to this leg cramping and you get a picture of my experience.  But I made it to the top, no bones about it.
<p>
<a href="index.php?action=Pics&name=Daily/20040708/30.JPG"><img src="Pics/Daily/20040708/30_sm.jpg"></a>
<p>
At the top I was rewarded with a spectacular view of Mount Rainier, located 50 miles to the northeast.  In the mid-ground is Spirit Lake.  Hammered by the eruption, the lake is still recovering from the devastation.  In the foreground you can see the eastern crater wall.  I'd estimate its height to be around 1,500 feet.
<p>
<a href="index.php?action=Pics&name=Daily/20040708/32.jpg"><img src="Pics/Daily/20040708/32_sm.jpg"></a>
<p>
Here's me standing near the crater edge with Mount Rainier in the background.  Those funny blue things on my lower legs are called gaters.  They worked well to kept all the ash out of my hiking boots.
<p>
<a href="index.php?action=Pics&name=Daily/20040708/29.JPG"><img src="Pics/Daily/20040708/29_sm.jpg"></a>
<p>
At the center of it all is the lava dome, standing about two hundred feet high.  This picture is a bit dated, however. Recently the mountain has been showing signs of waking up.  At present, another lava dome has appeared and is growing at a much faster rate when compared to the time it took to build the original lava dome pictured here.
<p>
<a href="index.php?action=Pics&name=Daily/20040708/Topo1.jpg"><img src="Pics/Daily/20040708/Topo1_sm.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20040708/Topo2.jpg"><img src="Pics/Daily/20040708/Topo2_sm.jpg"></a>
<p>
I've included two topography maps from my DeLorme GPS software.  The first is a 2-D map of the crater.  Filled with squiggly lines, the distance between any two lines on either map represents 100 feet in elevation.  Look at all the glaciers on the mountain.  The second map is a 3-D map which shows the depth of the crater looking due north.  Notice how the eruption blew out the northern side of the mountain.
<p>
That concludes my tour of Mount St. Helens National Volcanic Monument.  The tour was a terse one but you just can't beat a volcano when it comes to piquing one's interest.  I rate my tour a 5 thumbs-up, a perfect rating!
