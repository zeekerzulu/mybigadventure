The first of the 4 ancillary figures is Morality.  The figure depicts a woman holding in her left hand a book inscribed with "GOD" and in her right she holds the scroll of Revelation.  At the base of the figure I see two inset carvings, the first is of Moses the Prophet, holding the Ten Commandments, and the other is of an Evangelist writing in a book.  From all this I gather that the road to morality is to follow the Ten Commandments and to listen to your preacher?
