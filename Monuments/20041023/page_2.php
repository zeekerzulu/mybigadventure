Looking upward, it's hard to ignore the impressive size of the monument's central figure, Faith.  The figure attests to the strong belief that having faith in God is of primary importance.  These days, it seems like that concept is far less important, especially when looking at the popular American lifestyle of pursuing pleasure over all else.  Geeze, that last statement was kinda negative, but, is it true?
