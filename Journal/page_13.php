<a href="index.php?action=Pics&name=Daily/20040927/DSCN0722.JPG&nocomments=1"><img src="Pics/Daily/20040927/Small/DSCN0722.jpg"></a>
<p>
Today is my last day in Adirondack State Park.  I must say, I've spent a good many days here and have enjoyed each and every minute of them.  To cap off my Adirindack experience, I break camp then drive to Whiteface Mountain to say my goodbyes to this wonderful place.
<p>
I drive a very steep road that zig-zags up the mountain's northern face.  Near the top I park the van to check out Whiteface Castle, an interesting structure that sits about two hundred feet or so below the mountaintop.  After taking in the castle, I climb a long, rocky stairway to the top where I find an observation building as well as a weather station.  The view from atop the mountain is quite impressive, although it's a little hazy so the visibility is somewhat limited.
<p>
After finishing my mountaintop tour, I drive eastward out of the Adirondacks towards Burlington, VT, today's destination.  I soon discover I'll be taking a boat ride, for Lake Champlain is blocking my passage by land.  Reaching too far north and south to be circumnavigated, I buy a ticket then board a ferry for a 30 minute ride to Burlington, VT.
<p>
Upon reaching Burlington, I drive to a Walmart parking lot and settle in for the evening.  My plan is to campout here for a few days and catch-up on my travel writing.
