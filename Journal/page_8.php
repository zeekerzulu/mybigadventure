<h1><hr class="Journal2">THE BADLANDS - DAY #2 - Monday, August 23, 2004<hr class="Journal2"></h1>
<p>
<a href="index.php?action=Pics&name=Favorites/Pictures/5044.JPG&nogallery=1&nocomments=1"><img src="Pics/Favorites/Pictures/Small/5044.jpg"></a>
