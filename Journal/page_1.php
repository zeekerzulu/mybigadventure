<h1><hr class="Journal2">FIFES RIDGE - Sunday, July 11, 2004<hr class="Journal2"></h1>
<p>
<a href="index.php?action=Pics&name=Daily/20040711/36.JPG&nocomments=1"><img src="Pics/Daily/20040711/36_sm.JPG"></a>
<a href="index.php?action=Pics&name=Daily/20040711/15.JPG&nocomments=1"><img src="Pics/Daily/20040711/15_sm.JPG"></a>
<a href="index.php?action=Pics&name=Daily/20040711/77.JPG&nocomments=1"><img src="Pics/Daily/20040711/77_sm.JPG"></a>
<a href="index.php?action=Pics&name=Daily/20040711/96.JPG&nocomments=1"><img src="Pics/Daily/20040711/96_sm.JPG"></a>
<p>
Not a morning person, I wake late, then make preparations for my up-and-coming moutain bike foray that will take me up, across, and down Fifes Ridge.  The trail promises both great views and challenging ascends/descents.  The day proves to be a scorcher. The heat sears its way into my brain, making me feel a little delusional as I make my way up the 2,000 foot ascent.  My upward peddling grind is eventually paid back in triplicate as I make my way down the ridge, sometimes defying certain injury, maybe even death?
<p>
After an exhilarating bike ride I make my way to Seattle, WA.  On the way I stop for a quick photoshoot of Mount Rainier.  In the process, I get a whole lot more than what I bargained for, discovering ancient motifs that provide pictorial hints into a long lost civilization.
<p>
After my photoshoot I complete the drive up to Seattle.  Upon arrival, I drive around a bit, scouting for an "on-street Internet connection" and a suitable place to van-camp.  In short order, Seattle proves to be rich in both Internet connections and suitable van-camping street parking spots.
<p>
Tommorrow I'll tour downtown Seattle by bike.
