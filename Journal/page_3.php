<h1><hr class="Journal2">ROAD TRIP TO SANDPOINT, ID - Sunday, July 25, 2004<hr class="Journal2"></h1>
<p>
<a href="index.php?action=Pics&name=Daily/20040725/36.JPG&nocomments=1"><img src="Pics/Daily/20040725/36_sm.JPG"></a>
<a href="index.php?action=Pics&name=Daily/20040725/82.JPG&nocomments=1"><img src="Pics/Daily/20040725/82_sm.JPG"></a>
<a href="index.php?action=Pics&name=Daily/20040725/94.JPG&nocomments=1"><img src="Pics/Daily/20040725/94_sm.JPG"></a>
<a href="index.php?action=Pics&name=Favorites/Pictures/5007.JPG&nocomments=1"><img src="Pics/Favorites/Pictures/Small/5007.jpg"></a>
<p>
As they say, all good things must come to an end.  The time has arrived for me to hit the road once again.  After thoroughly enjoying my many day visit in Spokane, WA with my good friend Gil, I make my final preparations for departure.
<p>
The day ushers in a short drive to Sandpoint, located near the top of Idaho's panhandle and bordering Lake Pend Oreille, a huge lake that seems to go on forever.  Not terribly far from the Canadian border, the area surrounding Sandpoint brims with outdoor fun-filled adventure.  Upon arrival I tour Sandpoint, focusing primarily on the community's wonderful and expansive park, City Beach.
<p>
I settle into the park for a while, taking in dinner then jumping in the lake to cool off (today was a 100+ day).  Afterwards I putter around looking for an "on-street Internet connection" (not easy in such a small, out of the way town) then settle in for the night street-camping style.
<p>
The evening brings on my first encounter with bugs, the biting kind.  Without screening to keep out the little critters, my unwelcome, bloodsucking guests congregate and conspire without my knowledge, gathering above my head underneath the van's headliner.  Fortunately, vigorous swatting with a newspaper quickly takes them all out in short order.  After my murderous rampage, I plan tomorrow's mountain bike ride then turn in for the night.
