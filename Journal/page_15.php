<h1><hr class="Journal2">NEW ENGLAND CHARM - Wednesday, October 13, 2004<hr class="Journal2"></h1>
<p>
<a href="index.php?action=Pics&name=Daily/20041013/DSCN0083_3.JPG&nocomments=1"><img src="Pics/Daily/20041013/Small/DSCN0083_3.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041013/DSCN0213.JPG&nocomments=1"><img src="Pics/Daily/20041013/Small/DSCN0213.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041013/DSCN0223.JPG&nocomments=1"><img src="Pics/Daily/20041013/Small/DSCN0223.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041013/DSCN0245.JPG&nocomments=1"><img src="Pics/Daily/20041013/Small/DSCN0245.jpg"></a>
<p>
Bill is out of town in Boston for work, so today I've been left alone to explore.  I drive around a bit looking for any and all photogenic subjects that do well to characterize my imaginings of New England.  It doesn't take long before I hit paydirt and encounter a unique river setting.  The Ossipee River does its best to reflect the colors of the season, so much so, I shoot two amazing photos that look like French Impressionist paintings.
<p>
Crossing the Ossipee River I see a historical covered bridge.  Build in 1879, the Porter-Parsonsfield Historic Bridge effectively serves up 152 feet of river-crossing nostalgia.  Fully restored in 1999, the bridge is now only open to foot traffic.  I manage to capture the bridge's architecture in detail as well as its general stature in three nice panoramic shots, taken from afar.
<p>
After my covered bridge tour I make my way back to Bill's place.  On the way I encounter the world's longest road tattoo, followed by a large, interesting tree that causes me to form an odd theory as to how it gained its red coloration.
