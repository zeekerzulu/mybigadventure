<h1><hr class="Journal2">GRAND TETON SUNSET - Thursday, August 12, 2004<hr class="Journal2"></h1>
<p>
<a href="index.php?action=Pics&name=Daily/20040812/P1010071.JPG&nocomments=1"><img src="Pics/Daily/20040812/Small/P1010071.JPG"></a>
<a href="index.php?action=Pics&name=Daily/20040812/P1010072.JPG&nocomments=1"><img src="Pics/Daily/20040812/Small/P1010072.JPG"></a>
