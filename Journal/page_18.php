<h1><hr class="Journal2">ADVENTURE IN THE SMOKIES - Sunday, November 7, 2004<hr class="Journal2"></h1>
<p>
<a href="index.php?action=Pics&name=Daily/20041107.1/DSCN0080.jpg&nocomments=1"><img src="Pics/Daily/20041107.1/Small/DSCN0080.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041107.1/DSCN0272.jpg&nocomments=1"><img src="Pics/Daily/20041107.1/Small/DSCN0272.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041107.1/DSCN0208.jpg&nocomments=1"><img src="Pics/Daily/20041107.1/Small/DSCN0208.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041107.2/DSCN0018.jpg&nocomments=1"><img src="Pics/Daily/20041107.2/Small/DSCN0018.jpg"></a>
<p>
Today I'll be spending a whirlwind day in the Smoky Mountains.  On the way to Great Smoky Mountains National Park, I encounter the General Lee in Gatlinburg, TN.  As a kid, I was a huge fan of <i>The Dukes of Hazzard</I>, a silly TV series that ran from 1979-1985.  The General Lee, a 1969 Dodge Charger, was the star of the show.  Ha!  This must be one of the few cars they didn't wreck in the show's many car stunts.
<p>
Entering into the park, I ascend up the mountainside almost 5,000 feet in a little under 15 miles.  Once at the ridgeline, I soak in the sights and snap off quite a few shots of the haze filled mountains that stretch out before me in the distance.  Truly a great sight to see, I now understand why more than 9 million folks visit this park per year.
<p>
I then drive to Clingmans Dome, the park's highest point at 6,643 feet, to partake in two relatively short hikes.  The first, Andrews Bald, takes me to a grassy meadow where the panoramic views entice my sense of wonder about the Smokies.  My next hike takes me to Clingmans Dome, where I climb up a 5-story observation tower whose viewing platform looks a little like a UFO.  From the tower I receive an unobstructed, 360-degree view of the surrounding mountains.
<p>
Evening finally sets in and I stick around to capture the sunset.  The wait proves to be worthwhile, I manage to capture an amazing sunset.  All the colors of the spectrum are present with the exception of green.  But, in the end, I manage to give green its overdue recognition, if only through photo-editing.
<p>
After the sun goes down I drive back to Pigeon Forge, TN and van camp for a second night.
