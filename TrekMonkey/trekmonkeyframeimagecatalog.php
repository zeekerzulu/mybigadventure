					copiedimages[copiedcounter] = dd.obj.name;
					copiedcounter++;
				}
				images[counter][0] = dd.obj.name;
				if (dd.elements[dd.obj.name].w == 60) images[counter][1] = "tall"; else images[counter][1] = "wide";
				switch (counter) {
					case 0:
        		if (images[counter][1] == "tall")
							parent.contentedit.dd.elements[dd.obj.name].moveTo (67,29);
						else
							parent.contentedit.dd.elements[dd.obj.name].moveTo (57,49);
