<p>
Crossing the Ossipee River I see a historical covered bridge.  Build in 1879, the Porter-Parsonsfield Historic Bridge effectively serves up 152 feet of river-crossing nostalgia.  Fully restored in 1999, the bridge is now only open to foot traffic.  I manage to capture the bridge's architecture in detail as well as it's general stature in three nice panoramic shots, taken from afar.
<p>
After my covered bridge tour I make my way back to Bill's place.  On the way I encounter the world's longest road tattoo, followed by a large, interesting tree that causes me to form an odd theory as to how it gained it's red coloration.
