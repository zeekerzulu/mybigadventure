OH MY GOD!  It's a KILLER WHALE!  And he is almost close enough to grab the slice of bread I've hung over the railing!  He's a skittish fellow though, he comes and he goes.  I can't get a closer look at him.
<p>
While waiting for the whales to arrive (which in truth they never did), I met sisters <a href="index.php?action=Stats&stat=People&date=20040714&page=4">Paula & Rosemary</a>, both are on a little mini-vacation.  Visiting from Connecticut, Rosemary is being tour-guided by her sister Paula who's a park ranger for the North Cascades National Forest.  I chat with Paula for a little while, afterwhich I grow tired of waiting for the whales so I push onward down the road.
