Comparing harbors to dog breeds, Roche Harbor is like a high-strung toy poodle while Snug Harbor is like a old lazy basset hound.  Since I like basset hounds far better than poodles, I immediately feel at home at Snug.  It's like the mellow, laid-back places Jimmy Buffet describes in his songs.  Heck, maybe it's here where he composed a song or two while lounging uncounted days away in this peaceful harbor nook.
