When I hit the Idaho border the Centennial Trail goes from great to rather crummy.  Between the border and Coeur D'Alene the trail leaves the Spokane River for long sections, zig-zagging through neighborhoods, then bordering busy Interstate 90. While passing through neighborhoods it manages to intersect many cross streets which requires stopping and looking for traffic block after block.  Is this really a bike trail any longer? This is insane.
