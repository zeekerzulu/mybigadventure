When I finally hit the trail again I eventually catch up to the trailing rider.  I pull alongside and inquire if he is on a long distance bike ride.  It turns out <a href="index.php?action=Stats&stat=People&date=20040721&page=6">Adam</a> and the three other riders (John, John and Patrick) are indeed together and are on a long distance bike trip.  They all left Port Townsend, WA a while back and had traveled on SR-20 just as I had to get to Spokane, WA.  I must have passed them on the way but didn't take notice of them.  A little later I catch up with <a href="index.php?action=Stats&stat=People&date=20040721&page=6">John</a>, the ride leader.  We chat for a bit and over the course of the next few miles I kept running back into the group as I constantly needed to backtrack because Idaho does such a lousy job of marking the trail.
