Another great place to visit is <a name='valid_link' href="javascript:myPopup1('http://www.pikeplacemarket.org/')">Pike Place Market</a>.  It's located at the city's waterfront and is home to fresh fish, produce, and more.  The market spans many blocks along Seattle's Waterfront and offers everything you can imagine that is edible.  They even sell a large variety of flower arrangements on the cheap.
