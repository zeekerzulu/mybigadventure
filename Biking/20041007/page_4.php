As I ride around the northern section of Eagle Lake, I see colorful trees sharing space with large rocks, the latter having been carefully set in place along the roadside to keep carriages from wandering off into the woods.  The scenery here is quite serene, I believe I've found a good measure of peace in my day.  The weather is warming now and I catch myself wishing this day of riding would continue on forever and a day.  At least I'll have my memories when I depart from this place (as well as this website, of course).
