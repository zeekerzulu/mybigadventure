The day has finally arrived, I'm going to bike South Dakota's Badlands.  My route for today is an out-and-back via a gravel road.  I will first descend downhill to the mid-way point then return downhill back to my starting point.
<p>
Waaaaait a minute. Return downhill? Wishful thinking. I'll need to return uphill, I have no choice. I believe the current 100 degree temperature coupled with my preference for downhill is getting the best of me.
