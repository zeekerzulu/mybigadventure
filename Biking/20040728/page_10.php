<p>
I walk over to the Visitor Center to check out the temperature, it's a cool 60 degrees at 6,680 feet.  I'm feeling a little chilled now and start thinking about what the temperature is going to be on my way down the mountain with the added windchill.  I hadn't planned for cool temperatures, I didn't think to bring a windbreaker when I planned my trip.
<p>
Well, the time has arrived to go back down the mountain, all 10 miles and 3,000 feet of it.  It is growing late and I want to get back to my campsite well before nightfall.  I'm really looking forward to the ride down, cashing in all the hard labor it took to get up the pass.  Since the downhill ride is a retrace of my uphill trek, the camera is put away and all I care about is maximum speed and not falling off the bike.
<p>
The ride down is a lot of fun.  I manage to get in front of an older couple driving a Cadillac which boils down to my having the road all to myself, I am able to ride faster than they are driving.  An effective "car block" to all the other cars that are unlucky enough to be stuck behind the slow Cadillac.  I initially encounter a little rain on the way down which worries me, enough rain on the road will reduce the effectiveness of my braking.  But it quickly passes keeping the road under me dry and safe to ride on.
<p>
For me, 10 miles of downhill is a lot, probably the most I have ever experienced.  As the downhill ride progresses, my appreciation for the skills and courage to go fast and not crash grow by the mile.  Doing it well takes a whole lot of concentration and skill, of which I don't have an abundant supply, so the best I can muster is 35 mph with all the twists and turns the road continually throws at me.
<p>
Eventually I make it back to my campsite in one piece.  The ride turned out to be an absolutely perfect one.  It was filled to the brim with great challenges, wonderful views, and interesting wildlife just a stone's throw from the pavement.  This is the first ride of my trip that I'm giving a perfect rating, a 5 thumbs-up.  It wildly exceeded my expectations.
