We decide to hangout at the tower for a couple hours and enjoy the good weather, the good sights, and some good conversation.  At one point I notice the clouds are flashing a multitude of colors, thanks to the angle of the sun and my Polaroid sunglasses.  It's really amazing, I've never seen such a thing.  It reminds me of those colorful fractals you see in chaos theory picture books.  Lindsay can see the same effect with her sunglasses but to a lesser degree.  I'm not sure if that is a function of her sunglasses or maybe just her eyes?  Hard to say.
