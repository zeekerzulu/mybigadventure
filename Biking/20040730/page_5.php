The way down turns out to be a regular "bumpfest."  Unfortunately, I'm unable to gain much speed, primarily for safety reasons.  However, if I was sporting body armor and riding in the company of others, only then would I have pushed the envelope of my abilities.  But it makes no sense to push things when riding alone with no protection.  I don't wish to cut my trip short due to a broken arm or leg.  Or worse yet, cut my life short because I died on the trail, all broken and alone.
