Oh wait.  The sign is actually talking about an attraction called <xa href="javascript:myPopup1('http://www.acadiamagic.com/ThunderHole.html')">Thunder Hole</a>.  Unfortunately, the ocean is calm now, so Thunder Hole lies quiet and peaceful.  However, when the ocean is rough, high waves come crashing into this small inlet.  Within the inlet you'll find a small cavern which expels trapped air and water as a result of the wave action.  The resulting noise from the compressed air and water is a thunderous clap.
