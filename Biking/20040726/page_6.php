<p>
One mile from the end of the trail I meet <a href="index.php?action=Stats&stat=People&date=20040726&page=7">Katie and Ron</a>, two ambitious souls who are on their way up.  It is their first break from their uphill ride and they look pretty sweat-free, one sign of an in-shape biker.  They immediately size me up exclaiming I have a "hard tail" mountain bike.  They of course have full suspension rigs which puts my bike to shame but I don't mind.  Maybe someday I'll have one too.  We chat for a bit then go our separate ways, me going downhill of course, much to my pleasure.
<p>
After another mile of downhill fun, I reach the trailhead and feel rather good about my biking accomplishment.  It was a difficult ride in the beginning but the fruits of my labor, the views, and of course the downhill, make it well worth the effort.  I'd do this trail again, it was a grand, scenic adventure.
<p>
Given all the wonderful things this trail has to offer, I rate this ride a solid 4.5 thumbs out of a possible 5 thumbs-up.  If you're ever in Sandpoint, ID and in need of a mountain bike ride fix, check this one out, you won't be disappointed.
