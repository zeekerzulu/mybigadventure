I proceed to ride downhill for 4 miles, at times hitting better than 15 mpg which is pretty fast when you consider one's absolute destruction begins on either side of the singletrack which is only inches away from one's rapidly spinning tires.
<p>
As my downhill adventure progresses I enter into the "zone", I slowly become at one with my bike.  My only reality is the singletrack below me and the blur of the forest at my sides, rushing past my periphery at an ever increasing speed.  I find myself in Heaven on the way down, hopelessly wishing it will never end.  An unending downhill singletrack on legs of enduring steel fueled by limitless energy and enthusiasm, the ultimate nirvana for any mountain bike junkie as I have quickly become.
<p>
