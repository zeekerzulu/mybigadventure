<p>
Standing a tall 4,867 feet, Whiteface Mountain is the 5th highest peak in Adirondack State Park.  Years ago they created the Whiteface Mountain Ski Area which boasts a multitude of great ski runs that start as high as 4,416 feet,  providing a maximum vertical drop of 3,216 feet which is pretty awesome.  I grew up skiing in Western NY and the vertical there is something ridiculously short like 700 feet.
<p>
Little Whiteface Peak is the only run served by gondola, all other lifts are open-air chairs and operate only in the winter.  As a result, during the off-season you can only go as high as 3,676 feet.  The gondola serves both the tourists who want to ride up to see the view and bikers like myself who want a helping hand to the top of the downhill trails.
<p>
<a href="index.php?action=Pics&name=Biking/20040925_map.gif"><img src="Pics/Biking/20040925_map_sm.gif"></a>
<p>
The trails available to mountain bikers are a mix of wide ski trails, both singletrack and dirt roads.  Some of the descents are pretty insane.  The instructor at the bike shop gave me some advice about which trails to avoid because I'm not an expert in the sport.
<p>
Fast forwarding to ride's end, I decided to stick with the single course as outlined on the above map.   I traversed this trail 4 times which doesn't seem like a lot but it really is.  Difficult downhill takes time to navigate and requires a lot of energy just to hold on to your ride.  The flags represent all the places I fell over my handlebars, the purple flag being my worst crash that resulted in some nasty trail rash.
