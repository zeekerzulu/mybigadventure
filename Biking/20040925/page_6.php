My plan is to bike down the mountain without taking any pictures on my first run.  I need to get a good feel for the mountainside and don't want to be monkeying around with taking pictures.  I run the course and found it to be very challenging.  Frequently I find myself having to stop to assess the trail, to determine how I'm to get down without destroying myself.  It's really easy to pick up too much speed so I'm constantly on the brakes to keep the bike under control.  It takes me a while to ride the approximately 3 miles to the bottom and back to the gondola.
