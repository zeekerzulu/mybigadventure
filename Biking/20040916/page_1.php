This bike ride will be a special ride for me.  While the scenery isn't at all spectacular, the history behind it is close to my heart.  Why?  Because it is -my- history and it has been a long, long time since I have tread upon this once familiar part of the world.  The ride will take me from the once home of my grandparents (now owned by my aunt and uncle) near Medina, NY to Pine Hill Airport where my father taught me to fly a plane when I was 15 years old.  From there I'll bike to my old hometown, Oakfield, NY.
