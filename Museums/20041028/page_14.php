<p>
Operating under the banner of the <i>Great War in the Air</I>, the <a href="javascript:myPopup2('http://www.nasm.si.edu/exhibitions/gal206/gal206.html')">World War I Aviation Gallery</a> examines the myths and realities of air war during World War I.
<p>
<a href="index.php?action=Pics&name=Daily/20041028/DSCN1226.jpg"><img src="Pics/Daily/20041028/Small/DSCN1226.jpg"></a>
<a href="index.php?action=Pics&name=Daily/20041028/DSCN1227.jpg"><img src="Pics/Daily/20041028/Small/DSCN1227.jpg"></a>
