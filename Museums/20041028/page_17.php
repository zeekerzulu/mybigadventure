<b>THE SPACE RACE</b>
</center>
<hr>
<p>
The <a href="javascript:myPopup4('http://www.nasm.si.edu/exhibitions/gal114/gal114.htm')">Space Race Gallery</a> is a magical place, filled to the brim with spacecraft, missles, and telescopes. It reminds me of my toy chest as a kid, except this is on a much larger scale, of course.  This exhibit chronicles a time when the USA and USSR were elbowing their way into space, both attempting to claim the prize of space supremacy.  In the end, both countries agreed on a partnership, whereby they pooled their resources and together they built a space station.  What a nice ending to a rocky start.
