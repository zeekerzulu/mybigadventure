Ahhh, the <a href="javascript:myPopup1('http://en.wikipedia.org/wiki/Hubble_Space_Telescope')">Hubble Space Telescope</a>, the largest telescope in Earth orbit.  Space telescopes are in an excellent position to take extremely clear and sharp pictures because they reside outside the Earth's atmosphere.  Well, that assumes the telescope's mirror isn't flawed.  Oops, NASA launched the Hubble in 1990 with a bad mirror.   They eventually fix the problem four years later in 1994.  Since then, the Hubble has been blowing our collective minds with spectacular images.  As of today, despite the scientific importance of the telescope and all that it has contributed to our understanding of the universe, NASA has decided to let it slowly decay and die.  Nooooo! Say it ain't so NASA!
