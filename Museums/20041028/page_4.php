Between July 16 and July 24, 1969, the first lunar landing mission was performed, in part, by the <a href="javascript:myPopup9('http://www.nasm.si.edu/exhibitions/gal100/apollo11.html')">Apollo 11 Command Module "Columbia."</a>  The Command Module carried <a href="javascript:myPopup10('http://en.wikipedia.org/wiki/Neil_Armstrong')">Neil Armstrong</a>, <a href="javascript:myPopup1('http://en.wikipedia.org/wiki/Buzz_Aldrin')">Edwin "Buzz" Aldrin</a>, and <a href="javascript:myPopup2('http://en.wikipedia.org/wiki/Michael_Collins_(astronaut)')">Michael Collins</a> to the Moon and back.  The Command Module just orbited the Moon, the Lunar Module was used to actually land on the Moon's surface.  Maybe someday the Museum will also display the Lunar Module, how cool would that be?
<p>
Here's an <a href="javascript:myPopup3('http://www.hq.nasa.gov/office/pao/History/alsj/a11/a11.step.html')">interesting radio transcript</a> of the first Moon walk.  In addition to what was actually said, there's supporting analysis that tries to paint a larger picture of the events of that day.  Neil Armstrong's famous quote, as he stepped off the ladder and onto the Moon's surface was "That's one small step for man; one giant leap for mankind."
<p>
Funny, immediately after the quote was said, people have since been poking fun at ole Neil because it's symantically incorrect.  He should have said "one small step for (a) man."  With out the "a", he basically said "That's one small step for mankind; one giant leap for mankind."  Ha, that's sorta redundant.  Oh well, Neil wasn't picked for the mission for his mastership of the English language, he was selected because he was a damn good pilot.  Let all the English critics eat cake.
