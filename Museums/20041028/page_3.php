The <a href="javascript:myPopup3('http://www.nasm.si.edu/exhibitions/gal100/bellX1.html')">Bell X-1</a> was the first aircraft to break the sound barrier.  It was affectionately named "Glamorous Glennis" by its world famous pilot <a href="javascript:myPopup4('http://en.wikipedia.org/wiki/Chuck_Yeager')">Chuck Yeager</a> as a tribute to his wife.
