<a href="javascript:myPopup4('http://www.nasm.si.edu/exhibitions/gal100/mariner2.html')">Mariner 2</a> was the first spacecraft to study another planet.  On December 14, 1962, passing within 21,600 miles of Venus, scientific information was transmitted back to Earth.  We learned that Venus is very hot, has no measureable magnetic fields or radiation belts, and there are no Walmarts anywhere on the face of the planet.  Oh wait, that was in 1962, that was way before Walmart's meteoric rise.  Fast-forwarding to today, perhaps Walmart has made some inroads into the Venus economy.  Maybe we need to send another probe?
