The last plane in the Jet Aviation Gallery is this <a href="javascript:myPopup6('http://www.nasm.si.edu/exhibitions/gal106/gal106.html#ME262')">Messerschmitt Me 262</a>.  Nicknamed <i>Schwalbe</I>, or Swallow, this jet outperformed all other fighters during World War II.  Faster than the Allies P-51 Mustang by 120 mph, the jet gave the Germans an upper hand that was fortunately short lived.  Germany introduced the jet near the end of the war, and by then, Germany had already overreached its ability to maintain its military machine across multiple continents.  Total collapse was soon to follow.
