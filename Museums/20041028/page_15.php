Here's the blow-by-blow on the trip.  In a nutshell, the trip took four U.S. Army Air Service aircraft 175 days to circumnavigate the world, starting and ending in Seattle, Washington.  The airplanes were named after the cities who supplied their crews, namely, <i>Seattle, Boston, Chicago</I>, and <i>New Orleans</I>.  After 74 stops, lots of drama, and 27,550 miles, only the <i>Chicago</I> and the <i>New Orleans</I> made it back home.
<p>
The <i>Chicago</I>, a Douglas World Cruiser, is the airplane that's on display in this exhibit.
