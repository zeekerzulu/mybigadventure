I arrive at the front doorsteps of the Smithsonian Institution's <a href="javascript:myPopup5('http://www.mnh.si.edu/')">National Museum of Natural History</a>.  The Museum's publicly displayed collection, as well as its extensive behind-the-scene archives, contains over 125 million separate artifacts and specimens. A world famous center for research, the Museum is dedicated to the furtherance of public education and scholarship in the sciences, arts, as well as history.
