The last exhibit I squeeze in before the Museum closes is this Rube Goldberg Machine.  It explains how the various life cycles work on Earth.  It's geared for kids and is interesting to watch as the ball travels from top to bottom.
<p>
The Museum proves to be interesting and fun, I especially enjoyed the dinosaur exhibit.  Too bad I don't have more time to investigate what it has to offer.  In my book, the museum rates a solid 4.5 thumbs-up out of a possible 5 thumbs.
