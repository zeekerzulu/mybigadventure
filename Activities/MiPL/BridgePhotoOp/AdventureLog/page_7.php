On up ahead the Burnside Bridge stands tall and wide.  The white, puffy clouds are cooperating, providing an angelic backdrop to this water crossing scene.
<p>
Here are some interesting factoids about the Burnside Bridge, as per <a href="javascript:myPopup5('http://www.travelportland.com')">www.travelportland.com</a>:
<p>
<hr>
<center><b>B U R N S I D E&nbsp;&nbsp;&nbsp;B R I D G E</b></center>
<hr>
<br>
Opened: May 28, 1926
<br> 
Cost: $3 million 
<br>
Type: Steel double-leaf Strauss bascule drawbridge 
<br>
Main span: 252 feet long 
<br>
Owner: Multnomah County 
<p>
Highlights:
<p>
<ul>
<li>The bridge is closed each June for a few hours during the Portland Rose Festival to accommodate the Grand Floral Parade. 
<p>
<li>The street with which the Burnside Bridge connects was named after Vermont native Dan Wyman Burnside. A prominent Portland businessman and a member of Portland ’s social elite, Burnside helped raise funds to launch the Corps of Engineers on a 17-foot Willamette River channel dredging project in 1866. 
</ul>
