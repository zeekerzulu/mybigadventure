More pictures of the Steel Bridge.  It certainly doesn't have a very creative or imaginative name.  Looking at the closeup of the left tower, I think the bridge needs to be renamed the Rusty Bridge.  The bridge handles both train and automobile traffic.  The lower level carries freight and passenger train traffic, while the upper level carries <a href="javascript:myPopup3('http://www.trimet.org/max/index.htm')">MAX Light Rail</a> and automobile traffic.  There is a pedestrian walkway along the lower level where foot and bike traffic is permitted.
