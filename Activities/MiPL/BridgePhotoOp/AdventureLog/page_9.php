Then, an idea pops into my head.  Why not place the bottom of my camera flush with the sculpture side, with lense pointed skyward?  What kind of picture will this produce?
<p>
In my opinion, it produces a sculptured metal landscape of sorts.  An isolated mountain topography, with foreground plains filled full of jagged roads and pathways.  In some shots, light and dark floating objects are present.  Certainly I've gotten more than I had anticipated.  That's part of the fun of experimentation!
