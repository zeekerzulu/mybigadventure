Turning my attention northward, I set my sights on the Morrison Bridge to test my camera's zoom function.  Hmmm...  I wonder if I can see the damaged guard rail?
<p>
Nope... A few days ago, a woman drove off the bridge and plunged 60 feet through the air and into the Willamette River.  Fortunately, she was able to safely vacate her vehicle and reach the water surface relatively unharmed.  However, her Houdini-like escape didn't happen until she was at the bottom of the river.  Yikes!  Not on pleasant thought.  Not only is the river filthy, but God only knows what's on the riverbed.  Well, I guess we can all now name at least one thing down there...
