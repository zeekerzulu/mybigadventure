Welcome to the first MiPL Photo Op, sponsored by <a href="javascript:myPopup3('http://www.MEETin.org')">www.MEETin.org</a>.
<p>
Please join us as we photo tour a number of <a href="javascript:myPopup1('http://www.travelportland.com/media/genmedkit/gm_bridges_fountains.html')">bridges</a> in downtown Portland, Oregon.  The brain child of MiPL member Raj Khanna, today's event is rooted in a growing desire and interest within MiPL to pursue serious photography, as well as a general desire to goof around with other MiPL members, sharing both pictures and picture taking experiences.
<p>
Most folks will be bringing digital cameras today, although I suspect some folks will also bring along film cameras as well.  Today I'm bringing along my digital camera, a Nikon Coolpix 3200.  Nikon doesn't sell this model anymore, the closest thing to it is the <a href="javascript:myPopup2('http://www.nikonusa.com/template.php?cat=1&grp=2&productNr=25517')">Coolpix 4200 Model</a>.  Easy to use, the camera takes great pictures with little to no prompting on my part.  Overall I'm very happy with the camera.
<p>
Weather is an important factor when it comes to photography.  Being that it's early April in Portland, it's a bit of a crap-shoot weather-wise.  Fortunately, the weather is partially sunny, with no threat of rain in sight!
