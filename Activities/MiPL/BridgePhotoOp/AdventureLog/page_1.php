The plan is to all meet at 9am under the west side of the Hawthorne Bridge.  When I arrive everybody is already there.  In attendance is Raj, Lisa, Gretchen, Sasha, Sam, Kunjam, myself (Jeff), and Ankesh.... hey, where's Ankesh???  Raj soon raises him on his cell and we all find out he's on his way, trekking by foot over Hawthorne Bridge from the eastside, having the smarts to park his vehicle for free (unlike myself, I parked on the westside).
