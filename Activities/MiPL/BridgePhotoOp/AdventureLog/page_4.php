<p>
Here are some interesting factoids about the Morrison Bridge, as per <a href="javascript:myPopup5('http://www.travelportland.com')">www.travelportland.com</a>:
<p>
<hr>
<center><b>M O R R I S O N&nbsp;&nbsp;&nbsp;B R I D G E</b></center>
<hr>
<br>
Opened: May 24, 1958 
<br>
Cost: $12.9 million
<br>
Type: Steel double-leaf Chicago-style fixed trunnion bascule drawbridge
<br>
Main span: 284 feet long
<br>
Owner: Multnomah County
<p>
Highlights:
<p>
<ul>
<li>As part of the Willamette Light Brigade’s project to light all of Portland ’s downtown bridges, this bridge was the first to be illuminated (1987). 
<p>
<li>The bridge was named after Scottish immigrant John L. Morrison, who served as a lieutenant in the Oregon Rangers. 
</ul>
