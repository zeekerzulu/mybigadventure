<p>
Some cool refreshment!  I think this fountain is a knock-off of the more elaborate Benson Bubblers that are sprinkled around the city.  Commissioned in 1912 by Simon Benson, a civil leader, lumber baron, and self-proclaimed teetotaler, the 20 Benson Bubblers were intended to provide the community an alternative to alchol.
<p>
Benson boasted of his success, claiming the local saloons experienced a 40% dip in sales after the fountains were installed.  Benson is now long gone, so I think the time has arrived to start pumping cold beer through them!
<p>
Hey, you know what?!?  If truth be told, Portland's drinking fountains really freak me out.  The water is always running, which makes me wonder if the water is being recycled, like in non-drinking fountains.  You know what I mean?
