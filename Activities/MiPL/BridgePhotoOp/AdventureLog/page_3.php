<p>
Between the Hawthorne and Morrison Bridges you'll find a grand water fountain, the Salmon Street Springs.  Click <a href="javascript:myPopup2('http://virtualguidebooks.com/Oregon/PortlandColumbiaGorge/PortlandRiver/SalmonStreetSprings.html')">here</a> for a virtual panorama of the fountain.  185 water jets pump a maximum of 4,924 gallons of water a minute, often in unpredictable patterns and configurations.  It is in full-squirting glory as I approach it.  But, as soon as I level my camera to take a shot, the magnificant waterwork haults, and is replaced with this pretty, but paultry, and far less spectacular substitution.
<p>
<a href="index.php?action=Pics&name=Large/DSCN0056.jpg"><img src="Pics/Small/DSCN0056.jpg"></a>
<p>
Ankesh is bummed too.  Looking all professional with his tripod, he was setting up for the same shot as I when the plug is pulled.  I try to get him to wander into the fountain for a closer shot of the smaller fountain, but, to no avail, he isn't budging.  I don't blame him, I'd hate to be within the fountain's confines when the outer water ring reactivates.  Now, -that- would be a funny picture!
<p>
I wonder how many people have done just that, arriving on site only to see the smaller fountain in action.  Thinking that's all there is to the fountain, they move in for the photo-kill, not noticing the dormant outer water ring.  It'd almost be worth while, sticking around to see if someone would be lured into the fountain's wet water web!
