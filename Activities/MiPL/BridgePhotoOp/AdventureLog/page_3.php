<p>
The Hawthorne Bridge, the oldest vertical-lift bridge in the world, is a cool bridge because it's "old school".  Back in the day, apparently building a tall bridge was not an option.  So, it's low enough to require a Rube Goldberg-like contraption to raise and lower the bridge platform to allow the passageway of tall watercraft.
<p>
The three shots above are all black and white.  Since the sun is so prominent in the background, it causes my digital camera to "squint" which underexposes all images.  I have limited control over my camera's shutter speed, so it's practically impossible to get shots like these with any kind of color saturation.  So, black and white is my offering.  They actually look pretty good, I like the middle one the best.  How about you?
