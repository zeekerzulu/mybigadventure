Here are some interesting factoids about the Steel Bridge, as per <a href="javascript:myPopup5('http://www.travelportland.com')">www.travelportland.com</a>:
<p>
<hr>
<center><b>S T E E L&nbsp;&nbsp;&nbsp;B R I D G E</b></center>
<hr>
<br>
Opened: July 21, 1912 (trains); August 12, 1912 (automobiles)
<br>
Cost: $1.7 million
<br>
Type: Steel-through truss (Pratt), telescoping double-deck vertical lift
<br>
Main span: 211 feet long
<br>
Owner: Union Pacific Railroad (railroad section) and State of Oregon (automobile section)
<p>
Highlights:
<p>
<ul>
<li>The design of the Steel Bridge features two decks (the lower deck for freight trains; the upper for automobiles and MAX light rail). The lower of the two decks can move independently of the other. This unique design has never been duplicated. 
<p>
<li>To accommodate river traffic, the lower deck can be raised a remarkable 45 feet in 10 seconds; the upper deck, 90 feet in 90 seconds. 
<p>
<li>Before the mid-century decline in streetcar use, the upper roadway deck accommodated Portland ’s first electric trolley cars. 
<p>
<li>In 1986, following a $10 million upgrade, the Steel Bridge became the cross-river link for Portland ’s MAX light rail system. 
<p>
<li>When the predecessor of the current Steel Bridge was built in 1888, wrought iron was the most common building material available for bridges. Bucking tradition, however, local contractors fashioned Portland ’s new bridge from steel. The descriptive name stuck. When the existing Steel Bridge was built in nearly the same location as the older structure, the name transferred. 
<p>
<li>The lower deck of the Steel Bridge was recently fitted with a $2.5 million pedestrian and bicycle crossing that links Gov. Tom McCall Waterfront Park to the new Eastbank Esplanade and its 1,200-foot floating walkway. 
</ul>
