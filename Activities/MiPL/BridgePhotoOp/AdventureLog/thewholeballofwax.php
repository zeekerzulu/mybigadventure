The Hawthorne Bridge, the oldest vertical-lift bridge on the world, is a cool bridge because it's "old school".  Back in the day, apparently building a tall bridge was not an option.  So, it's low enough to require a Rube Goldberg-like contraption to raise and lower the bridge platform to allow the passageway of tall watercraft.
