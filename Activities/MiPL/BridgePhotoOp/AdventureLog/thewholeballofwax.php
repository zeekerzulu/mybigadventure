Here are some interesting factoids about the Hawthorne Bridge, as per <a href="javascript:myPopup5('http://www.travelportland.com')">www.travelportland.com</a>:
<p>
<hr>
<center><b>H A W T H O R N E&nbsp;&nbsp;&nbsp;B R I D G E</b></center>
<hr>
<br>
Opened: December 19, 1910 
<br>
Cost: $500,000
<br>
Type: Steel-through truss (Parker), vertical lift
<br>
Main span: 244 feet long
<br>
Owner: Multnomah County
<p>
Highlights:
<p>
<ul>
<li>The Hawthorne, which gained national recognition for its design, was one of three such bridges in the Portland area built by the inventor of the vertical-lift drawbridge, John Alexander Low Waddell. 
<p>
<li>The Hawthorne is the world’s oldest vertical-lift bridge. 
<p>
<li>The bridge is named after Dr. J. C. Hawthorne, who helped to found the Oregon Hospital for the Insane, which was originally located on Asylum Street in East Portland . Asylum Street was renamed Hawthorne Street five years after the hospital relocated to Salem . 
<p>
<li>In the spring of 1998, a year-long renovation project closed the Hawthorne Bridge . Sidewalks were widened, lift systems were upgraded, and the steel grated deck was replaced – to name just a few of the improvements. 
</ul>
