Here's Kunjam shooting the Broadway Bridge.  Looking at the bridge, it seems Sam's request has expired and the bridge is now back to its normal, straight self.  Check out all the big ships in the distance.  Portland is a rather large center for container shipments.  You can also see the Fremont Bridge past the big ships.  It's a double deck bridge, with the upper deck designed to receive westbound traffic, serving up great views of downtown Portland which is predominately located on the westside of the Willamette River.
<p>
Here are some interesting factoids about the Fremont Bridge, as per <a href="javascript:myPopup5('http://www.travelportland.com')">www.travelportland.com</a>:
<p>
<hr>
<center><b>F R E M O N T&nbsp;&nbsp;&nbsp;B R I D G E</b></center>
<hr>
<br>
Opened: November 11, 1973
<br>
Cost: $82 million
<br>
Type: Steel three-span half-through tied arch, with orthotropic upper deck
<br>
Main span: 1,255 feet long
<br>
Owner: State of Oregon
<p>
Highlights:
<p>
<ul>
<li>The Fremont, the newest bridge to span the Willamette River, is America’s longest tied-arch bridge. It also has the longest main span of any bridge in Oregon. 
<p>
<li>Using 32 hydraulic jacks, the bridge’s “rainbow” arch was raised into place from the river below. Lifting the arch’s 6,000 tons set a world record.
<p>
<li>The bridge is named after explorer and army officer John Charles Fremont. Fremont, nicknamed “The Pathfinder,” was given federal funds to survey the Oregon Trail in 1842. He later opened a route to California from The Dalles. In the 1856 presidential election, Fremont ran as a Republican and anti-slavery candidate.
</ul>
