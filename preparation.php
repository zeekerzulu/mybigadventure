<b>Thursday, May 6th, 2004</b>
<p>
For the past 4 weeks I've been looking for a van camper and it's been a rocky road from day one.  Since many people use these vehicles as their daily drivers, not many are on the market and those that are get snatched up really quick.  It's definitely a seller's market.  After looking at many vehicles (some too old, some too expensive, the rest having too many problems) I've decided to "build a camper", sort of like the principal of the <a href="http://www.buildabear.com/?cps=www.buildabear.com&cache=www.buildabear.com">Build-A-Bear</a> stores that have been popping up lately.  But instead of using arms and legs and fuzzy ears, I'll be struggling with wood, nails and camping equipment.  My father has graciously agreed to help me with this project (he used to build houses) so with his supervision and my sweat equity, I'm hopeful to come up with a useful configuration that will make life more comfortable for me whilst on the road.
<p>
So today my primary goal is to go to Camping World to determine what my options are and how much the camping equipment will cost me.  Additionally I'll be making some calls to pin down a van.  Preferrably I want to buy from a private owner.-->
